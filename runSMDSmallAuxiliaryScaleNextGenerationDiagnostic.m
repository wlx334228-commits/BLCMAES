function experiment = runSMDSmallAuxiliaryScaleNextGenerationDiagnostic( ...
        outputRoot,numberOfRuns,problemNumbers,branchRepeats)
%RUNSMALLAUXILIARYSCALENEXTGENERATIONDIAGNOSTIC One-step scale diagnostic.
% This is the previous snapshot-branch diagnostic.  It is retained under a
% distinct name because its t+1 probe metrics are not terminal performance
% metrics for the five algorithm variants.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 1 || isempty(outputRoot)
    outputRoot = fullfile(projectRoot,'results_nextgen_small_auxiliary_scale_2D', ...
        'SMD1_to_SMD8_10runs_R3_all_valid');
end
if nargin < 2 || isempty(numberOfRuns), numberOfRuns = 10; end
if nargin < 3 || isempty(problemNumbers), problemNumbers = 1:8; end
if nargin < 4 || isempty(branchRepeats), branchRepeats = 3; end

studyOptions = struct( ...
    'version','next_generation_small_auxiliary_scale_v1', ...
    'etas',[.10 .15 .20 .25], ...
    'includeA0Baseline',true, ...
    'includeA1Control',false, ...
    'referenceVariant','A0', ...
    'responseMode','baseline_relative', ...
    'fallbackEta',.20);
experiment = runSMDNextGenerationScaleExperiment(outputRoot,numberOfRuns, ...
    problemNumbers,branchRepeats,studyOptions);
end
