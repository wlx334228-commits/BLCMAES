function [runSummary,stageSummary] = summarisePredictionScaleActualEvents( ...
    eventTable,candidateTable)
%SUMMARISEPREDICTIONSCALEACTUALEVENTS Aggregate real F050 auxiliary events.
% All candidate rows in one run and phase are reduced before the final
% cross-run summary, so repeated generations never masquerade as independent
% experimental replications.

assert(istable(eventTable) && istable(candidateTable), ...
    'Actual event and candidate inputs must be tables.');
if isempty(eventTable)
    runSummary = table(); stageSummary = table(); return;
end
runNames = {'SMD','run_no','seed','stage','event_count','candidate_count', ...
    'progress_median','progress_min','progress_max','sigma_median','sigma_IQR', ...
    'eta_median','auxiliary_step_median','auxiliary_step_IQR', ...
    'cma_rms_scale_median','cma_rms_scale_IQR', ...
    'auxiliary_rms_scale_median','auxiliary_rms_scale_IQR', ...
    'auxiliary_UF_median','delta_UF_to_direct_median', ...
    'Q_pred','Q_rank','parent_selection_rate','history_improvement_rate', ...
    'distance_median','relative_cma_distance_median', ...
    'standardized_distance_median','boundary_repairs'};
rows = cell(0,numel(runNames));
for smdNo = unique(eventTable.SMD)'
    smdEvents = eventTable(eventTable.SMD == smdNo,:);
    for stageCell = unique(smdEvents.stage)'
        stage = tableText(stageCell,1);
        stageEvents = smdEvents(strcmp(smdEvents.stage,stage),:);
        for runNo = unique(stageEvents.run_no)'
            events = stageEvents(stageEvents.run_no == runNo,:);
            candidates = candidateTable(candidateTable.SMD == smdNo & ...
                candidateTable.run_no == runNo & ...
                strcmp(candidateTable.stage,stage),:);
            assert(~isempty(candidates), ...
                'Every real auxiliary event must have candidate records.');
            [sigma,sigmaIQR] = medianIQR(events.sigma);
            [step,stepIQR] = medianIQR(events.auxiliary_step);
            [cmaRms,cmaRmsIQR] = medianIQR(events.cma_rms_scale);
            [auxRms,auxRmsIQR] = medianIQR(events.auxiliary_rms_scale);
            rows(end+1,:) = {smdNo,runNo,events.seed(1),stage,height(events), ...
                height(candidates),median(events.progress),min(events.progress), ...
                max(events.progress),sigma,sigmaIQR,median(events.eta), ...
                step,stepIQR,cmaRms,cmaRmsIQR,auxRms,auxRmsIQR, ...
                median(candidates.auxiliary_UF), ...
                median(candidates.delta_UF_to_direct), ...
                mean(candidates.better_than_direct), ...
                mean(candidates.better_than_normal_pair_rate), ...
                meanIgnoringNaN(candidates.parent_selected), ...
                mean(candidates.better_than_history_best), ...
                median(candidates.actual_distance_to_prediction), ...
                median(candidates.relative_cma_distance), ...
                median(candidates.standardized_distance), ...
                sum(candidates.boundary_repair_count)}; %#ok<AGROW>
        end
    end
end
runSummary = cell2table(rows,'VariableNames',runNames);

summaryNames = {'SMD','stage','independent_runs','event_count','candidate_count', ...
    'sigma_median','sigma_IQR','eta_median','auxiliary_step_median', ...
    'auxiliary_step_IQR','cma_rms_scale_median','cma_rms_scale_IQR', ...
    'auxiliary_rms_scale_median','auxiliary_rms_scale_IQR', ...
    'auxiliary_UF_median','auxiliary_UF_IQR','delta_UF_to_direct_median', ...
    'delta_UF_to_direct_IQR','Q_pred_median','Q_pred_IQR', ...
    'Q_rank_median','Q_rank_IQR','parent_selection_rate_median', ...
    'parent_selection_rate_IQR','history_improvement_rate_median', ...
    'history_improvement_rate_IQR','distance_median','distance_IQR', ...
    'relative_cma_distance_median','relative_cma_distance_IQR', ...
    'standardized_distance_median','standardized_distance_IQR', ...
    'boundary_repairs_total'};
summaryRows = cell(0,numel(summaryNames));
for smdNo = unique(runSummary.SMD)'
    smdRows = runSummary(runSummary.SMD == smdNo,:);
    for stageCell = unique(smdRows.stage)'
        stage = tableText(stageCell,1);
        subset = smdRows(strcmp(smdRows.stage,stage),:);
        [sigma,sigmaIQR] = medianIQR(subset.sigma_median);
        [step,stepIQR] = medianIQR(subset.auxiliary_step_median);
        [cmaRms,cmaRmsIQR] = medianIQR(subset.cma_rms_scale_median);
        [auxRms,auxRmsIQR] = medianIQR(subset.auxiliary_rms_scale_median);
        [UF,UFIQR] = medianIQR(subset.auxiliary_UF_median);
        [delta,deltaIQR] = medianIQR(subset.delta_UF_to_direct_median);
        [Qpred,QpredIQR] = medianIQR(subset.Q_pred);
        [Qrank,QrankIQR] = medianIQR(subset.Q_rank);
        [parent,parentIQR] = medianIQR(subset.parent_selection_rate);
        [history,historyIQR] = medianIQR(subset.history_improvement_rate);
        [distance,distanceIQR] = medianIQR(subset.distance_median);
        [relative,relativeIQR] = medianIQR(subset.relative_cma_distance_median);
        [standardised,standardisedIQR] = medianIQR(subset.standardized_distance_median);
        summaryRows(end+1,:) = {smdNo,stage,height(subset), ...
            sum(subset.event_count),sum(subset.candidate_count),sigma,sigmaIQR, ...
            median(subset.eta_median),step,stepIQR,cmaRms,cmaRmsIQR, ...
            auxRms,auxRmsIQR,UF,UFIQR,delta,deltaIQR,Qpred,QpredIQR, ...
            Qrank,QrankIQR,parent,parentIQR,history,historyIQR,distance, ...
            distanceIQR,relative,relativeIQR,standardised,standardisedIQR, ...
            sum(subset.boundary_repairs)}; %#ok<AGROW>
    end
end
stageSummary = cell2table(summaryRows,'VariableNames',summaryNames);
end

function value = meanIgnoringNaN(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = mean(values); end
end

function [middle,spread] = medianIQR(values)
values = sort(values(isfinite(values)));
if isempty(values), middle = NaN; spread = NaN; return; end
middle = median(values);
if numel(values) < 2, spread = NaN; return; end
spread = percentile(values,75)-percentile(values,25);
end

function value = percentile(values,percent)
position = 1+(numel(values)-1)*percent/100;
lower = floor(position); upper = ceil(position);
if lower == upper
    value = values(lower);
else
    value = values(lower)+(position-lower)*(values(upper)-values(lower));
end
end

function text = tableText(values,index)
if iscell(values), text = values{index}; else, text = char(values(index)); end
end
