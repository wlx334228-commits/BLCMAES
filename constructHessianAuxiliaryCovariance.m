function info = constructHessianAuxiliaryCovariance(model,cmaUpperCovariance,options)
%CONSTRUCTHESSIANAUXILIARYCOVARIANCE Curvature-shaped upper covariance.
% The quadratic Hessian was fitted in z=(xu-m)/s coordinates.  For a
% valid concave model, A=-H is positive definite and its inverse defines
% the local shape: flatter directions receive larger variance.  The final
% covariance is trace-matched to the current CMA-ES upper covariance, so
% this helper changes shape/orientation only, not total upper variance.

requiredModelFields = {'H','scale','valid'};
for i = 1:numel(requiredModelFields)
    assert(isfield(model,requiredModelFields{i}), ...
        'BLCMAES:HessianCovariance', ...
        'Prediction model lacks field %s.',requiredModelFields{i});
end
if ~model.valid
    error('BLCMAES:HessianCovariance', ...
        'The pending quadratic prediction is not valid.');
end
H = (model.H + model.H') / 2;
upperDim = size(H,1);
if size(H,2) ~= upperDim || ~isreal(H) || any(~isfinite(H(:)))
    error('BLCMAES:HessianCovariance', ...
        'The quadratic Hessian is not a finite square real matrix.');
end
if ~isfinite(model.scale) || model.scale <= 0
    error('BLCMAES:HessianCovariance', ...
        'The normalized-coordinate scale s_t is invalid.');
end

% The model has already passed a negative-definite test while being fitted.
% Repeat it here because this helper is also a defensive boundary before
% external candidates are evaluated.
A = -H;
[~,notPositiveDefinite] = chol(A);
if notPositiveDefinite
    error('BLCMAES:HessianCovariance', ...
        'The negative Hessian is not positive definite.');
end
[Q,diagonal] = eig(A);
rawEigenvalues = real(diag(diagonal));
if any(~isfinite(rawEigenvalues)) || any(rawEigenvalues <= 0)
    error('BLCMAES:HessianCovariance', ...
        'The negative-Hessian eigenvalues are invalid.');
end
largestCurvature = max(rawEigenvalues);

% The floor is relative to the actual curvature scale.  It simultaneously
% accounts for floating-point precision, a user-visible relative threshold,
% and the requested maximum condition number; no absolute cross-problem
% curvature constant is used.
relativeFloor = max(options.hessianCovarianceRelativeEigenvalueFloor, ...
    sqrt(eps));
eigenvalueFloor = max([largestCurvature * relativeFloor, ...
    largestCurvature / options.hessianCovarianceMaxCondition, ...
    eps(largestCurvature)]);
regularizedEigenvalues = max(rawEigenvalues,eigenvalueFloor);
clipped = rawEigenvalues < eigenvalueFloor;

rawShape = model.scale^2 * Q * diag(1 ./ regularizedEigenvalues) * Q';
rawShape = (rawShape + rawShape') / 2;
if any(~isfinite(rawShape(:))) || trace(rawShape) <= 0
    error('BLCMAES:HessianCovariance', ...
        'The inverse-curvature shape matrix is invalid.');
end

cmaUpperCovariance = (cmaUpperCovariance + cmaUpperCovariance') / 2;
[cmaVectors,cmaDiagonal] = eig(cmaUpperCovariance);
cmaEigenvalues = real(diag(cmaDiagonal));
if any(~isfinite(cmaEigenvalues)) || any(cmaEigenvalues <= 0) || ...
        any(~isfinite(cmaUpperCovariance(:)))
    error('BLCMAES:HessianCovariance', ...
        'The current CMA-ES upper covariance is not positive definite.');
end
cmaTrace = trace(cmaUpperCovariance);
shapeTrace = trace(rawShape);
calibration = cmaTrace / shapeTrace;
if ~isfinite(calibration) || calibration <= 0
    error('BLCMAES:HessianCovariance', ...
        'Trace calibration of the Hessian covariance failed.');
end
covariance = calibration * rawShape;
covariance = (covariance + covariance') / 2;
[covarianceVectors,covarianceDiagonal] = eig(covariance);
covarianceEigenvalues = real(diag(covarianceDiagonal));
if any(~isfinite(covarianceEigenvalues)) || any(covarianceEigenvalues <= 0)
    error('BLCMAES:HessianCovariance', ...
        'The calibrated Hessian covariance is not positive definite.');
end

% The largest covariance eigenvalue corresponds to the smallest curvature.
[~,hessianPrincipalIndex] = max(covarianceEigenvalues);
[~,cmaPrincipalIndex] = max(cmaEigenvalues);
alignment = abs(dot(covarianceVectors(:,hessianPrincipalIndex), ...
    cmaVectors(:,cmaPrincipalIndex)));
alignment = min(1,max(0,real(alignment)));
principalAngleDegrees = acosd(alignment);

info = struct('covariance',covariance, ...
    'rawShapeCovariance',rawShape, ...
    'negativeHessian',A, ...
    'negativeHessianEigenvectors',Q, ...
    'rawCurvatureEigenvalues',rawEigenvalues, ...
    'regularizedCurvatureEigenvalues',regularizedEigenvalues, ...
    'eigenvalueFloor',eigenvalueFloor, ...
    'regularizedMask',clipped, ...
    'regularizedCount',sum(clipped), ...
    'rawCurvatureCondition',max(rawEigenvalues)/min(rawEigenvalues), ...
    'regularizedCurvatureCondition', ...
        max(regularizedEigenvalues)/min(regularizedEigenvalues), ...
    'calibration',calibration, ...
    'cmaTrace',cmaTrace, ...
    'hessianTrace',trace(covariance), ...
    'traceRatio',trace(covariance)/cmaTrace, ...
    'cmaEigenvalues',cmaEigenvalues, ...
    'cmaCondition',max(cmaEigenvalues)/min(cmaEigenvalues), ...
    'covarianceEigenvalues',covarianceEigenvalues, ...
    'covarianceCondition', ...
        max(covarianceEigenvalues)/min(covarianceEigenvalues), ...
    'principalAngleDegrees',principalAngleDegrees);
end
