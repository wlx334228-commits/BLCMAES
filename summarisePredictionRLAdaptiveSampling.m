function [summary,tests] = summarisePredictionRLAdaptiveSampling( ...
    runs,specifications,problemNumbers)
%SUMMARISEPREDICTIONRLADAPTIVESAMPLING Read-only paired RL experiment report.
% This function does not evaluate an SMD objective or retrain an Actor.

required = {'SMD','experiment_id','run_no','seed','upper_error','lower_error', ...
    'upper_success','lower_success','UFE','LFE_total', ...
    'prediction_injected_generations','direct_parent_selection_rate', ...
    'auxiliary_parent_selection_rate','direct_new_best_total', ...
    'auxiliary_new_best_total','consistency_passed', ...
    'rl_action_generations','rl_actor_update_generations','rl_eta_median', ...
    'rl_delta_median','rl_reward_median','rl_trace_ratio_median', ...
    'rl_covariance_condition_median','rl_final_actor_parameter_norm'};
assert(all(ismember(required,runs.Properties.VariableNames)), ...
    'RL run table lacks required experiment columns.');

names = {'SMD','experiment_id','sampling_distribution', ...
    'normal_candidate_count','direct_candidate_count','auxiliary_candidate_count', ...
    'runs','upper_successes','upper_success_rate','lower_successes', ...
    'lower_success_rate','upper_error_median','upper_error_IQR', ...
    'lower_error_median','lower_error_IQR','UFE_median','UFE_IQR', ...
    'LFE_median','LFE_IQR','injected_generations_median', ...
    'direct_parent_selection_rate_median','auxiliary_parent_selection_rate_median', ...
    'direct_new_best_median','auxiliary_new_best_median', ...
    'rl_action_generations_median','rl_actor_update_generations_median', ...
    'rl_eta_median','rl_eta_IQR','rl_delta_median','rl_delta_IQR', ...
    'rl_reward_median','rl_reward_IQR','rl_advantage_median', ...
    'rl_trace_ratio_median','rl_covariance_condition_median', ...
    'rl_auxiliary_UF_median','rl_direct_true_UF_median', ...
    'rl_final_actor_parameter_norm_median','consistency_passed_runs'};
records = cell(0,numel(names));
for smdNo = problemNumbers(:)'
    for index = 1:numel(specifications)
        spec = specifications(index);
        subset = runs(runs.SMD == smdNo & ...
            strcmp(runs.experiment_id,spec.id),:);
        assert(~isempty(subset),'Missing SMD%d %s records.',smdNo,spec.id);
        [upper,upperIQR] = medianIQR(subset.upper_error);
        [lower,lowerIQR] = medianIQR(subset.lower_error);
        [ufe,ufeIQR] = medianIQR(subset.UFE);
        [lfe,lfeIQR] = medianIQR(subset.LFE_total);
        [eta,etaIQR] = medianIQR(subset.rl_eta_median);
        [delta,deltaIQR] = medianIQR(subset.rl_delta_median);
        [reward,rewardIQR] = medianIQR(subset.rl_reward_median);
        records(end+1,:) = {smdNo,spec.id,spec.distribution, ...
            spec.normalCount,spec.directCount,spec.auxiliaryCount, ...
            height(subset),sum(subset.upper_success ~= 0), ...
            mean(subset.upper_success ~= 0),sum(subset.lower_success ~= 0), ...
            mean(subset.lower_success ~= 0),upper,upperIQR,lower,lowerIQR, ...
            ufe,ufeIQR,lfe,lfeIQR, ...
            finiteMedian(subset.prediction_injected_generations), ...
            finiteMedian(subset.direct_parent_selection_rate), ...
            finiteMedian(subset.auxiliary_parent_selection_rate), ...
            finiteMedian(subset.direct_new_best_total), ...
            finiteMedian(subset.auxiliary_new_best_total), ...
            finiteMedian(subset.rl_action_generations), ...
            finiteMedian(subset.rl_actor_update_generations),eta,etaIQR, ...
            delta,deltaIQR,reward,rewardIQR, ...
            finiteMedian(subset.rl_advantage_median), ...
            finiteMedian(subset.rl_trace_ratio_median), ...
            finiteMedian(subset.rl_covariance_condition_median), ...
            finiteMedian(subset.rl_auxiliary_UF_median), ...
            finiteMedian(subset.rl_direct_true_UF_median), ...
            finiteMedian(subset.rl_final_actor_parameter_norm), ...
            sum(subset.consistency_passed ~= 0)}; %#ok<AGROW>
    end
end
summary = cell2table(records,'VariableNames',names);
tests = pairedTests(runs,problemNumbers);
end

function tests = pairedTests(runs,problems)
comparisons = {'Q_vs_A0','A0','Q';'F050_vs_Q','Q','F050'; ...
    'RL1_vs_F050','F050','RL1';'RL2_vs_F050','F050','RL2'; ...
    'RL3_vs_F050','F050','RL3';'RL3_vs_Q','Q','RL3'};
names = {'SMD','comparison','reference_experiment','variant_experiment', ...
    'paired_runs','reference_upper_successes','variant_upper_successes', ...
    'reference_lower_successes','variant_lower_successes', ...
    'reference_upper_error_median','variant_upper_error_median', ...
    'reference_lower_error_median','variant_lower_error_median', ...
    'reference_UFE_median','variant_UFE_median', ...
    'reference_LFE_median','variant_LFE_median', ...
    'upper_error_p','lower_error_p','UFE_p','LFE_p', ...
    'upper_error_p_holm','lower_error_p_holm','UFE_p_holm','LFE_p_holm', ...
    'upper_error_advantage','lower_error_advantage','UFE_advantage', ...
    'LFE_advantage','evaluation_advantage_eligible'};
records = cell(0,numel(names));
for smdNo = problems(:)'
    for i = 1:size(comparisons,1)
        reference = rowsFor(runs,smdNo,comparisons{i,2});
        variant = rowsFor(runs,smdNo,comparisons{i,3});
        [reference,variant] = alignPairs(reference,variant,smdNo,comparisons{i,1});
        upper = pairedWilcoxonSignedRank(variant.upper_error,reference.upper_error);
        lower = pairedWilcoxonSignedRank(variant.lower_error,reference.lower_error);
        ufe = pairedWilcoxonSignedRank(variant.UFE,reference.UFE);
        lfe = pairedWilcoxonSignedRank(variant.LFE_total,reference.LFE_total);
        eligible = sum(reference.upper_success ~= 0) > 0 && ...
            sum(reference.lower_success ~= 0) > 0 && ...
            sum(variant.upper_success ~= 0) >= sum(reference.upper_success ~= 0) && ...
            sum(variant.lower_success ~= 0) >= sum(reference.lower_success ~= 0);
        records(end+1,:) = {smdNo,comparisons{i,1},comparisons{i,2}, ...
            comparisons{i,3},height(reference), ...
            sum(reference.upper_success ~= 0),sum(variant.upper_success ~= 0), ...
            sum(reference.lower_success ~= 0),sum(variant.lower_success ~= 0), ...
            finiteMedian(reference.upper_error),finiteMedian(variant.upper_error), ...
            finiteMedian(reference.lower_error),finiteMedian(variant.lower_error), ...
            finiteMedian(reference.UFE),finiteMedian(variant.UFE), ...
            finiteMedian(reference.LFE_total),finiteMedian(variant.LFE_total), ...
            upper.p,lower.p,ufe.p,lfe.p,NaN,NaN,NaN,NaN, ...
            false,false,false,false,eligible}; %#ok<AGROW>
    end
end
tests = cell2table(records,'VariableNames',names);
tests = holmAndAdvantages(tests);
end

function subset = rowsFor(runs,smdNo,id)
subset = runs(runs.SMD == smdNo & strcmp(runs.experiment_id,id),:);
end

function [reference,variant] = alignPairs(reference,variant,smdNo,comparison)
assert(height(reference) == height(variant) && ~isempty(reference), ...
    'SMD%d %s has unmatched paired data.',smdNo,comparison);
reference = sortrows(reference,'run_no'); variant = sortrows(variant,'run_no');
assert(isequal(reference.run_no,variant.run_no) && ...
    isequal(reference.seed,variant.seed), ...
    'SMD%d %s does not share paired seeds.',smdNo,comparison);
end

function tests = holmAndAdvantages(tests)
metrics = {'upper_error','lower_error','UFE','LFE'};
for smdNo = unique(tests.SMD)'
    rows = tests.SMD == smdNo;
    for i = 1:numel(metrics)
        metric = metrics{i};
        tests.([metric '_p_holm'])(rows) = holmAdjust(tests.([metric '_p'])(rows));
    end
end
tests.upper_error_advantage = tests.upper_error_p_holm < 0.05 & ...
    tests.variant_upper_error_median < tests.reference_upper_error_median;
tests.lower_error_advantage = tests.lower_error_p_holm < 0.05 & ...
    tests.variant_lower_error_median < tests.reference_lower_error_median;
tests.UFE_advantage = tests.evaluation_advantage_eligible & ...
    tests.UFE_p_holm < 0.05 & tests.variant_UFE_median < tests.reference_UFE_median;
tests.LFE_advantage = tests.evaluation_advantage_eligible & ...
    tests.LFE_p_holm < 0.05 & tests.variant_LFE_median < tests.reference_LFE_median;
end

function adjusted = holmAdjust(values)
adjusted = NaN(size(values)); valid = find(isfinite(values));
if isempty(valid), return; end
[ordered,order] = sort(values(valid)); previous = 0; result = NaN(numel(ordered),1);
for i = 1:numel(ordered)
    previous = max(previous,min(1,(numel(ordered)-i+1)*ordered(i)));
    result(i) = previous;
end
adjusted(valid(order)) = result;
end

function value = finiteMedian(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = median(values); end
end

function [middle,spread] = medianIQR(values)
values = sort(values(isfinite(values)));
if isempty(values), middle = NaN; spread = NaN; return; end
middle = median(values);
if numel(values) < 2, spread = NaN; return; end
spread = percentile(values,75)-percentile(values,25);
end

function value = percentile(values,p)
position = 1+(numel(values)-1)*p/100; low = floor(position); high = ceil(position);
if low == high, value = values(low); else, value = values(low)+(position-low)*(values(high)-values(low)); end
end
