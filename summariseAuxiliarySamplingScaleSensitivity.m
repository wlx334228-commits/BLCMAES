function [summary,pairedTests] = summariseAuxiliarySamplingScaleSensitivity( ...
    runs,specifications,problemNumbers)
%SUMMARISEAUXILIARYSAMPLINGSCALESENSITIVITY Offline eta-study statistics.
% Reads completed runs only; it never invokes an SMD objective, lower-level
% search, model fit, or random-number generator.

required = {'SMD','experiment_id','run_no','seed','upper_error', ...
    'lower_error','upper_success','lower_success','UFE','LFE_total', ...
    'prediction_injected_generations','auxiliary_parent_selection_rate', ...
    'auxiliary_new_best_total','auxiliary_better_than_direct_generation_rate', ...
    'auxiliary_better_than_direct_individual_rate', ...
    'auxiliary_best_better_than_normal_generation_rate', ...
    'auxiliary_better_than_normal_pair_rate', ...
    'auxiliary_actual_distance_median','auxiliary_relative_distance_median', ...
    'auxiliary_sampling_scale_median','consistency_passed'};
assert(all(ismember(required,runs.Properties.VariableNames)), ...
    'The eta-study run table lacks required diagnostic columns.');

names = {'SMD','experiment_id','auxiliary_sampling_scale', ...
    'normal_candidate_count','direct_candidate_count','auxiliary_candidate_count', ...
    'runs','upper_successes','upper_success_rate','lower_successes', ...
    'lower_success_rate','upper_error_median','upper_error_IQR', ...
    'lower_error_median','lower_error_IQR','UFE_median','UFE_IQR', ...
    'LFE_median','LFE_IQR','injected_generations_median', ...
    'auxiliary_better_direct_generation_rate_median', ...
    'auxiliary_better_direct_generation_rate_IQR', ...
    'auxiliary_better_direct_individual_rate_median', ...
    'auxiliary_better_direct_individual_rate_IQR', ...
    'auxiliary_best_better_normal_generation_rate_median', ...
    'auxiliary_best_better_normal_generation_rate_IQR', ...
    'auxiliary_better_normal_pair_rate_median', ...
    'auxiliary_better_normal_pair_rate_IQR', ...
    'auxiliary_parent_selection_rate_median', ...
    'auxiliary_parent_selection_rate_IQR', ...
    'auxiliary_new_best_median','auxiliary_new_best_IQR', ...
    'auxiliary_distance_median','auxiliary_distance_IQR', ...
    'auxiliary_relative_distance_median','auxiliary_relative_distance_IQR', ...
    'logged_sampling_scale_median','consistency_passed_runs'};
rows = cell(0,numel(names));
for smdNo = problemNumbers(:)'
    for specIndex = 1:numel(specifications)
        spec = specifications(specIndex);
        subset = runs(runs.SMD == smdNo & ...
            strcmp(runs.experiment_id,spec.id),:);
        assert(~isempty(subset),'Missing SMD%d %s records.',smdNo,spec.id);
        [upperMedian,upperIQR] = medianIQR(subset.upper_error);
        [lowerMedian,lowerIQR] = medianIQR(subset.lower_error);
        [ufeMedian,ufeIQR] = medianIQR(subset.UFE);
        [lfeMedian,lfeIQR] = medianIQR(subset.LFE_total);
        [betterDirectGeneration,betterDirectGenerationIQR] = ...
            medianIQR(subset.auxiliary_better_than_direct_generation_rate);
        [betterDirectIndividual,betterDirectIndividualIQR] = ...
            medianIQR(subset.auxiliary_better_than_direct_individual_rate);
        [betterNormalGeneration,betterNormalGenerationIQR] = ...
            medianIQR(subset.auxiliary_best_better_than_normal_generation_rate);
        [betterNormalPair,betterNormalPairIQR] = ...
            medianIQR(subset.auxiliary_better_than_normal_pair_rate);
        [auxParentRate,auxParentRateIQR] = ...
            medianIQR(subset.auxiliary_parent_selection_rate);
        [auxNewBest,auxNewBestIQR] = medianIQR(subset.auxiliary_new_best_total);
        [distance,distanceIQR] = medianIQR(subset.auxiliary_actual_distance_median);
        [relativeDistance,relativeDistanceIQR] = ...
            medianIQR(subset.auxiliary_relative_distance_median);
        [loggedScale,~] = medianIQR(subset.auxiliary_sampling_scale_median);
        rows(end+1,:) = {smdNo,spec.id,spec.auxiliarySamplingScale, ...
            spec.normalCount,spec.directCount,spec.auxiliaryCount, ...
            height(subset),sum(subset.upper_success ~= 0), ...
            mean(subset.upper_success ~= 0),sum(subset.lower_success ~= 0), ...
            mean(subset.lower_success ~= 0),upperMedian,upperIQR, ...
            lowerMedian,lowerIQR,ufeMedian,ufeIQR,lfeMedian,lfeIQR, ...
            finiteMedian(subset.prediction_injected_generations), ...
            betterDirectGeneration,betterDirectGenerationIQR, ...
            betterDirectIndividual,betterDirectIndividualIQR, ...
            betterNormalGeneration,betterNormalGenerationIQR, ...
            betterNormalPair,betterNormalPairIQR,auxParentRate,auxParentRateIQR, ...
            auxNewBest,auxNewBestIQR,distance,distanceIQR, ...
            relativeDistance,relativeDistanceIQR,loggedScale, ...
            sum(subset.consistency_passed ~= 0)}; %#ok<AGROW>
    end
end
summary = cell2table(rows,'VariableNames',names);
pairedTests = buildPairwiseTests(runs,problemNumbers);
end

function tests = buildPairwiseTests(runs,problemNumbers)
comparisons = { ...
    'A1_vs_A0','A0','A1'; ...
    'E025_vs_A0','A0','E025'; 'E050_vs_A0','A0','E050'; ...
    'E075_vs_A0','A0','E075'; 'E100_vs_A0','A0','E100'; ...
    'E025_vs_A1','A1','E025'; 'E050_vs_A1','A1','E050'; ...
    'E075_vs_A1','A1','E075'; 'E100_vs_A1','A1','E100'; ...
    'E025_vs_E100','E100','E025'; 'E050_vs_E100','E100','E050'; ...
    'E075_vs_E100','E100','E075'};
names = {'SMD','comparison','reference_experiment','variant_experiment', ...
    'paired_runs','reference_upper_successes','variant_upper_successes', ...
    'reference_lower_successes','variant_lower_successes', ...
    'reference_upper_error_median','variant_upper_error_median', ...
    'reference_lower_error_median','variant_lower_error_median', ...
    'reference_UFE_median','variant_UFE_median', ...
    'reference_LFE_median','variant_LFE_median', ...
    'upper_error_p','lower_error_p','UFE_p','LFE_p', ...
    'upper_error_p_holm','lower_error_p_holm','UFE_p_holm','LFE_p_holm', ...
    'upper_error_method','lower_error_method','UFE_method','LFE_method', ...
    'upper_error_advantage','lower_error_advantage','UFE_advantage', ...
    'LFE_advantage','evaluation_advantage_eligible'};
rows = cell(0,numel(names));
for smdNo = problemNumbers(:)'
    for comparisonIndex = 1:size(comparisons,1)
        comparison = comparisons{comparisonIndex,1};
        referenceId = comparisons{comparisonIndex,2};
        variantId = comparisons{comparisonIndex,3};
        reference = runs(runs.SMD == smdNo & ...
            strcmp(runs.experiment_id,referenceId),:);
        variant = runs(runs.SMD == smdNo & ...
            strcmp(runs.experiment_id,variantId),:);
        [reference,variant] = alignPairs(reference,variant,smdNo,comparison);
        upper = pairedWilcoxonSignedRank(variant.upper_error,reference.upper_error);
        lower = pairedWilcoxonSignedRank(variant.lower_error,reference.lower_error);
        ufe = pairedWilcoxonSignedRank(variant.UFE,reference.UFE);
        lfe = pairedWilcoxonSignedRank(variant.LFE_total,reference.LFE_total);
        eligible = sum(reference.upper_success ~= 0) > 0 && ...
            sum(reference.lower_success ~= 0) > 0 && ...
            sum(variant.upper_success ~= 0) >= sum(reference.upper_success ~= 0) && ...
            sum(variant.lower_success ~= 0) >= sum(reference.lower_success ~= 0);
        rows(end+1,:) = {smdNo,comparison,referenceId,variantId, ...
            height(reference),sum(reference.upper_success ~= 0), ...
            sum(variant.upper_success ~= 0),sum(reference.lower_success ~= 0), ...
            sum(variant.lower_success ~= 0), ...
            finiteMedian(reference.upper_error),finiteMedian(variant.upper_error), ...
            finiteMedian(reference.lower_error),finiteMedian(variant.lower_error), ...
            finiteMedian(reference.UFE),finiteMedian(variant.UFE), ...
            finiteMedian(reference.LFE_total),finiteMedian(variant.LFE_total), ...
            upper.p,lower.p,ufe.p,lfe.p,NaN,NaN,NaN,NaN, ...
            upper.method,lower.method,ufe.method,lfe.method, ...
            false,false,false,false,eligible}; %#ok<AGROW>
    end
end
tests = cell2table(rows,'VariableNames',names);
tests = applyHolmAndAdvantages(tests);
end

function [reference,variant] = alignPairs(reference,variant,smdNo,comparison)
assert(height(reference) == height(variant) && ~isempty(reference), ...
    'SMD%d %s has unmatched paired data.',smdNo,comparison);
reference = sortrows(reference,'run_no');
variant = sortrows(variant,'run_no');
assert(isequal(reference.run_no,variant.run_no) && ...
    isequal(reference.seed,variant.seed), ...
    'SMD%d %s does not share the same paired seeds.',smdNo,comparison);
end

function tests = applyHolmAndAdvantages(tests)
metrics = {'upper_error','lower_error','UFE','LFE'};
for smdNo = unique(tests.SMD)'
    index = tests.SMD == smdNo;
    for metricIndex = 1:numel(metrics)
        metric = metrics{metricIndex};
        tests.([metric '_p_holm'])(index) = ...
            holmAdjust(tests.([metric '_p'])(index));
    end
end
tests.upper_error_advantage = tests.upper_error_p_holm < 0.05 & ...
    tests.variant_upper_error_median < tests.reference_upper_error_median;
tests.lower_error_advantage = tests.lower_error_p_holm < 0.05 & ...
    tests.variant_lower_error_median < tests.reference_lower_error_median;
tests.UFE_advantage = tests.evaluation_advantage_eligible & ...
    tests.UFE_p_holm < 0.05 & ...
    tests.variant_UFE_median < tests.reference_UFE_median;
tests.LFE_advantage = tests.evaluation_advantage_eligible & ...
    tests.LFE_p_holm < 0.05 & ...
    tests.variant_LFE_median < tests.reference_LFE_median;
end

function adjusted = holmAdjust(pValues)
adjusted = NaN(size(pValues));
valid = find(isfinite(pValues));
if isempty(valid), return; end
[ordered,order] = sort(pValues(valid));
adjustedOrdered = NaN(numel(ordered),1);
previous = 0;
for i = 1:numel(ordered)
    previous = max(previous,min(1,(numel(ordered)-i+1)*ordered(i)));
    adjustedOrdered(i) = previous;
end
adjusted(valid(order)) = adjustedOrdered;
end

function [middle,spread] = medianIQR(values)
values = sort(values(isfinite(values)));
if isempty(values), middle = NaN; spread = NaN; return; end
middle = median(values);
if numel(values) < 2, spread = NaN; return; end
spread = percentile(values,75)-percentile(values,25);
end

function value = finiteMedian(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = median(values); end
end

function value = percentile(values,percent)
position = 1+(numel(values)-1)*percent/100;
low = floor(position); high = ceil(position);
if low == high, value = values(low); else
    value = values(low)+(position-low)*(values(high)-values(low));
end
end
