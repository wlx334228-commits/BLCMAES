function [correctedUpper,entry,state] = applyIndividualPredictionCorrection( ...
    CMA,rawUpper,rawLower,generation,BI,options,state)
%APPLYINDIVIDUALPREDICTIONCORRECTION Apply one A0--A4 sample transform.
% Sampling has already happened and the original boundary repair has already
% run.  Only upper coordinates may change.  No objective, lower search, or
% global random number is touched here.

populationSize = size(rawUpper,1);
upperDim = BI.u_dim;
assert(size(rawUpper,2) == upperDim && size(rawLower,1) == populationSize, ...
    'BLCMAES:InvalidSample','Unexpected joint-sample dimensions.');
if isempty(state)
    state = initializeIndividualPredictionState(BI,options);
end

entry = createSampleEntry(CMA,rawUpper,rawLower,generation,BI,options);
correctedUpper = rawUpper;
activeAfterWarmup = generation > options.startGeneration;
selected = false(populationSize,1);
xPred = NaN(1,upperDim);
% A0 also needs a zero vector for the audit record.  Initialising here keeps
% every mode on the same logging path without changing any sampled point.
requestedVectors = zeros(populationSize,upperDim);

switch options.mode
    case 'A0'
        % Original BL-CMA-ES: retain the normal joint sample exactly.
    case 'A3'
        % Match the A1 timing but isolate its 0.9 population contraction.
        if activeAfterWarmup
            selected(:) = true;
            requestedVectors = -options.weight * bsxfun(@minus,rawUpper, ...
                entry.cma_mean_before_sampling);
        else
            requestedVectors = zeros(populationSize,upperDim);
        end
    otherwise
        % A1, A2 and A4 require a model fitted only after the prior
        % generation has finished all true evaluations.
        pendingIsUsable = activeAfterWarmup && isfield(state,'pending') && ...
            isfield(state.pending,'valid') && state.pending.valid;
        if pendingIsUsable
            xPred = state.pending.x_pred;
            pendingIsUsable = isreal(xPred) && all(isfinite(xPred)) && ...
                numel(xPred) == upperDim;
        end
        if pendingIsUsable
            entry.prediction_valid_used = true;
            entry.prediction_source_generation = state.pending.source_generation;
            entry.x_pred_used = xPred;
            entry.weight_used = options.weight;
            switch options.mode
                case 'A1'
                    selected(:) = true;
                    requestedVectors = options.weight * bsxfun(@minus,xPred,rawUpper);
                case 'A2'
                    selected(:) = true;
                    translation = options.weight * ...
                        (xPred-entry.cma_mean_before_sampling);
                    requestedVectors = repmat(translation,populationSize,1);
                case 'A4'
                    selected(selectPartialIndices(state,populationSize, ...
                        options.partialCount)) = true;
                    requestedVectors(selected,:) = options.weight * ...
                        bsxfun(@minus,xPred,rawUpper(selected,:));
            end
        end
end

entry.transformation_selected = selected;
entry.requested_correction_vectors = requestedVectors;
requestedUpper = rawUpper + requestedVectors;
for i = find(selected)'
    actual = requestedUpper(i,:);
    high = actual > BI.u_ub;
    low = actual < BI.u_lb;
    % Keep the project's midpoint boundary repair.  rawUpper is the normal,
    % already repaired sample and is the correct reference for this second
    % repair.
    actual(high) = (rawUpper(i,high) + BI.u_ub(high)) / 2;
    actual(low) = (rawUpper(i,low) + BI.u_lb(low)) / 2;
    correctedUpper(i,:) = actual;
    entry.boundary_coordinate_repaired(i,:) = high | low;
end
entry.correction_vectors = correctedUpper - rawUpper;
entry.requested_correction_lengths = ...
    sqrt(sum(entry.requested_correction_vectors.^2,2));
entry.correction_lengths = sqrt(sum(entry.correction_vectors.^2,2));
entry.boundary_repaired = any(entry.boundary_coordinate_repaired,2);
entry.correction_applied = entry.correction_lengths > 0;
entry.correction_selected_count = sum(entry.transformation_selected);
entry.correction_applied_count = sum(entry.correction_applied);
entry.upper_after = correctedUpper;
entry.joint_after_correction = [correctedUpper,rawLower];
entry.upper_dispersion_before = populationDispersion(rawUpper);
entry.upper_dispersion_after = populationDispersion(correctedUpper);
if entry.upper_dispersion_before > eps
    entry.upper_dispersion_ratio = entry.upper_dispersion_after / ...
        entry.upper_dispersion_before;
end
entry.max_correction_over_sigma = max(entry.correction_lengths) / ...
    max(CMA.sigma,eps);
entry.abnormal_correction = any(~isfinite(correctedUpper(:))) || ...
    entry.upper_dispersion_after <= eps * max(1,entry.upper_dispersion_before);
end

function indices = selectPartialIndices(state,populationSize,partialCount)
if isempty(state.partialSelectionStream)
    error('BLCMAES:PartialSelectionStream', ...
        'A4 requires its local selection stream.');
end
count = min(partialCount,populationSize);
[~,order] = sort(rand(state.partialSelectionStream,1,populationSize));
indices = order(1:count);
end

function dispersion = populationDispersion(points)
if size(points,1) < 2
    dispersion = 0;
    return;
end
centered = bsxfun(@minus,points,mean(points,1));
dispersion = mean(sum(centered.^2,2));
end

function entry = createSampleEntry(CMA,rawUpper,rawLower,generation,BI,options)
populationSize = size(rawUpper,1);
upperDim = BI.u_dim;
jointDim = BI.dim;
entry = struct('generation',generation,'mode',options.mode, ...
    'cma_mean_before_sampling',CMA.xmean(1:upperDim), ...
    'cma_mean_after_update',NaN(1,upperDim), ...
    'mean_directly_corrected',false, ...
    'prediction_valid_used',false, ...
    'prediction_source_generation',NaN, ...
    'x_pred_used',NaN(1,upperDim), ...
    'weight_requested',options.weight,'weight_used',0, ...
    'upper_before',rawUpper,'upper_after',rawUpper, ...
    'upper_for_cma_update',rawUpper, ...
    'joint_before_correction',[rawUpper,rawLower], ...
    'joint_after_correction',[rawUpper,rawLower], ...
    'upper_entering_lower_search',NaN(populationSize,upperDim), ...
    'joint_entering_evaluation',NaN(populationSize,jointDim), ...
    'joint_after_true_evaluation',NaN(populationSize,jointDim), ...
    'upper_objective_after_true_evaluation',NaN(populationSize,1), ...
    'joint_for_cma_update',NaN(populationSize,jointDim), ...
    'selected_parent_indices',zeros(1,0), ...
    'selected_parent_joint',NaN(0,jointDim), ...
    'selected_parent_is_transformed',false(1,0), ...
    'transformation_selected',false(populationSize,1), ...
    'correction_selected_count',0,'correction_applied_count',0, ...
    'requested_correction_vectors',zeros(populationSize,upperDim), ...
    'correction_vectors',zeros(populationSize,upperDim), ...
    'requested_correction_lengths',zeros(populationSize,1), ...
    'correction_lengths',zeros(populationSize,1), ...
    'correction_applied',false(populationSize,1), ...
    'boundary_repaired',false(populationSize,1), ...
    'boundary_coordinate_repaired',false(populationSize,upperDim), ...
    'upper_dispersion_before',NaN,'upper_dispersion_after',NaN, ...
    'upper_dispersion_ratio',NaN,'max_correction_over_sigma',NaN, ...
    'abnormal_correction',false,'population_size',populationSize, ...
    'population_UF',NaN(populationSize,1),'population_fit',NaN(populationSize,1), ...
    'fitness_rank',NaN(populationSize,1), ...
    'transformed_UF_median',NaN,'untransformed_UF_median',NaN, ...
    'transformed_rank_median',NaN,'untransformed_rank_median',NaN, ...
    'generation_best_UF',NaN,'elite_UF',NaN,'best_so_far_UF',NaN, ...
    'population_UF_min',NaN,'population_UF_median',NaN, ...
    'population_UF_std',NaN,'UFE',NaN,'LFE_total',NaN, ...
    'mean_update_applied',false,'termination_reason','', ...
    'consistency_checked',false,'consistency_passed',NaN, ...
    'consistency_message','not_checked', ...
    'next_prediction_valid',false,'next_prediction_reason','not_fitted', ...
    'next_x_pred',NaN(1,upperDim),'next_prediction_model',struct());
end

