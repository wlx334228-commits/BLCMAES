function report = testHighDimPredictionSensitivity(outputDir,sampleCounts,injectCounts)
%TESTHIGHDIMPREDICTIONSENSITIVITY Non-evaluating tests for 10-D M/K cases.
% Validates the four requested archive sizes (M=100,200,250,300) and the
% E0/E1--E4 candidate layouts (K=6 or K=3) without calling an SMD function.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(projectRoot,'results_prediction_injection_tests', ...
        'highdim_sensitivity_smoke');
end
if nargin < 2 || isempty(sampleCounts), sampleCounts = [100,200,250,300]; end
if nargin < 3 || isempty(injectCounts), injectCounts = [3,6]; end
validateattributes(sampleCounts,{'numeric'}, ...
    {'vector','integer','>=',66});
validateattributes(injectCounts,{'numeric'}, ...
    {'vector','integer','>=',1,'<=',12});
assert(all(ismember(sampleCounts,[100,200,250,300])), ...
    'This smoke test is restricted to M=100,200,250,300.');
assert(all(ismember(injectCounts,[3,6])), ...
    'This smoke test is restricted to K=3 and K=6.');
if exist(outputDir,'dir') ~= 7, mkdir(outputDir); end

BI = getBLOPinfo('SMD',1,20);
assert(BI.u_dim == 10 && BI.l_dim == 10 && BI.dim == 20, ...
    'The sensitivity test requires DU=10, DL=10.');
populationSize = 4 + floor(3*log(BI.dim));
assert(populationSize == 12,'Original 10+10 lambda must be 12.');

caseIndex = 0;
report = struct();
for sampleCount = sampleCounts(:)'
    [model,expectedPrediction] = knownConcaveModel(BI,sampleCount,caseIndex+1);
    assert(model.valid && model.coefficientCount == 66, ...
        'Complete 10-D fit failed for M=%d.',sampleCount);
    assert(size(model.H,1) == 10 && size(model.quadraticPairs,1) == 55, ...
        '10-D Hessian/pair count is invalid for M=%d.',sampleCount);
    assert(norm(model.x_pred-expectedPrediction) < 1e-8, ...
        'Stationary point recovery failed for M=%d.',sampleCount);
    for injectCount = injectCounts(:)'
        caseIndex = caseIndex + 1;
        options = injectionOptions(BI,sampleCount,injectCount,3000+caseIndex);
        state = initializePredictionInjectionState(BI,options);
        state.pending = struct('valid',true,'x_pred',expectedPrediction, ...
            'source_generation',25,'model',model);
        rawUpper = reshape(1:(populationSize*BI.u_dim), ...
            BI.u_dim,populationSize)' / 100;
        rawLower = zeros(populationSize,BI.l_dim);
        CMA = struct('xmean',zeros(1,BI.dim),'sigma',0.25, ...
            'C',eye(BI.dim),'B',eye(BI.dim),'D',ones(1,BI.dim));
        rngBefore = rng;
        [upper,lower,entry] = applyPredictionInjection(CMA,rawUpper, ...
            rawLower,26,BI,options,state);
        assert(isequal(rngBefore,rng), ...
            'Injection changed the global random sequence for M=%d K=%d.', ...
            sampleCount,injectCount);
        assert(isequal(size(upper),[populationSize,BI.u_dim]) && ...
            isequal(size(lower),[populationSize,BI.l_dim]), ...
            'Candidate dimensions are invalid for M=%d K=%d.', ...
            sampleCount,injectCount);
        assert(sum(strcmp(entry.source_labels,'normal')) == ...
            populationSize-injectCount, ...
            'Normal-candidate count is invalid for M=%d K=%d.', ...
            sampleCount,injectCount);
        assert(sum(strcmp(entry.source_labels,'predicted_direct')) == 1 && ...
            sum(strcmp(entry.source_labels,'predicted_auxiliary')) == ...
                injectCount-1, ...
            'Prediction candidate composition is invalid for M=%d K=%d.', ...
            sampleCount,injectCount);
        directIndex = populationSize-injectCount+1;
        assert(norm(upper(directIndex,:)-expectedPrediction) < 1e-8, ...
            'Direct point was not inserted in the expected slot.');
        fieldName = sprintf('M%d_K%d',sampleCount,injectCount);
        report.(fieldName) = struct('sampleCount',sampleCount, ...
            'predictionInjectCount',injectCount, ...
            'normalCandidateCount',populationSize-injectCount, ...
            'directCandidateCount',1, ...
            'auxiliaryCandidateCount',injectCount-1, ...
            'prediction',model.x_pred,'entry',entry);
    end
end
save(fullfile(outputDir,'highdim_prediction_sensitivity_test_report.mat'), ...
    'report','sampleCounts','injectCounts');
disp(report);
end

function options = injectionOptions(BI,sampleCount,injectCount,seed)
BI.predictionInjection = struct('mode',sprintf('K%d',injectCount), ...
    'predictionInjectCount',injectCount, ...
    'candidatePolicy','direct_plus_auxiliary','logEnabled',true, ...
    'startGeneration',10,'historyGenerations',10,'useAllHistory',true, ...
    'sampleCount',sampleCount,'auxiliaryRandomSeed',seed, ...
    'maxPredictionNormalizedDistance',Inf,'consistencyCheckEnabled',true);
options = predictionInjectionOptions(BI);
end

function [model,expectedPrediction] = knownConcaveModel(BI,sampleCount,seed)
% The response is a complete strict concave quadratic in the original
% coordinates.  fitLocalUpperQuadratic may normalize internally; its
% recovered stationary point must still equal this original-space solution.
rng(4000+seed,'twister');
upperDim = BI.u_dim;
randomMatrix = randn(upperDim);
H = -(randomMatrix'*randomMatrix + 0.5*eye(upperDim));
linear = linspace(-0.3,0.4,upperDim)';
expectedPrediction = (-(H \ linear))';
historyCount = sampleCount + 80;
x = randn(historyCount,upperDim);
UF = 2 + x*linear + 0.5*sum((x*H).*x,2);
history = [10*ones(historyCount,1),(1:historyCount)',x,UF];
options = injectionOptions(BI,sampleCount,3,1000+seed);
model = fitLocalUpperQuadratic(history,zeros(1,upperDim),10,options);
end
