function [summary,pairedTests] = summariseHighDimPredictionSensitivity( ...
    runs,fitRuns,specifications,problemNumbers)
%SUMMARISEHIGHDIMPREDICTIONSENSITIVITY Offline M/K sensitivity statistics.
% Inputs are the already completed records for A0, E0, and E1--E4.  This
% function does not run BLCMAES, refit a model, draw random values, or call
% an upper/lower objective.  It only aggregates saved logs and applies
% paired Wilcoxon signed-rank tests followed by Holm correction.

requiredRuns = {'SMD','experiment_id','run_no','seed','upper_error', ...
    'lower_error','upper_success','lower_success','UFE','LFE_total', ...
    'nominal_budget_carried_error','direct_parent_selection_rate', ...
    'direct_fitness_rank_median','result_root','mat_file'};
requiredFits = {'SMD','experiment_id','run_no','fit_attempts', ...
    'fit_successes','first_valid_fit_generation', ...
    'first_injection_generation','design_condition_median', ...
    'hessian_evaluable_attempts','hessian_negative_definite_attempts'};
assert(all(ismember(requiredRuns,runs.Properties.VariableNames)), ...
    'Sensitivity run table is missing required fields.');
assert(all(ismember(requiredFits,fitRuns.Properties.VariableNames)), ...
    'Sensitivity fit table is missing required fields.');

summaryNames = {'SMD','experiment_id','archive_sample_count', ...
    'prediction_inject_count','normal_candidate_count', ...
    'direct_candidate_count','auxiliary_candidate_count','runs', ...
    'upper_successes','upper_success_rate','lower_successes', ...
    'lower_success_rate','upper_error_median','upper_error_IQR', ...
    'lower_error_median','lower_error_IQR','UFE_median','UFE_IQR', ...
    'LFE_median','LFE_IQR','nominal_budget_error_median', ...
    'nominal_budget_error_IQR','first_hit_UFE_median_successful', ...
    'first_hit_LFE_median_successful','fit_attempts_total', ...
    'fit_successes_total','fit_success_rate', ...
    'first_valid_fit_generation_median', ...
    'first_injection_generation_median','design_condition_median', ...
    'hessian_evaluable_attempts_total', ...
    'hessian_negative_definite_attempts_total', ...
    'hessian_negative_definite_rate','direct_rank_median', ...
    'direct_parent_selection_rate_median'};
summaryRows = cell(0,numel(summaryNames));
for smdNo = problemNumbers(:)'
    for specIndex = 1:numel(specifications)
        spec = specifications(specIndex);
        subset = runs(runs.SMD == smdNo & ...
            strcmp(runs.experiment_id,spec.id),:);
        fitSubset = fitRuns(fitRuns.SMD == smdNo & ...
            strcmp(fitRuns.experiment_id,spec.id),:);
        assert(height(subset) > 0 && height(subset) == height(fitSubset), ...
            'Run and fit rows do not align for SMD%d %s.',smdNo,spec.id);
        upperSuccesses = sum(subset.upper_success ~= 0);
        lowerSuccesses = sum(subset.lower_success ~= 0);
        successful = subset.upper_success ~= 0;
        fitAttempts = sum(fitSubset.fit_attempts);
        fitSuccesses = sum(fitSubset.fit_successes);
        hessianAttempts = sum(fitSubset.hessian_evaluable_attempts);
        hessianNegative = sum(fitSubset.hessian_negative_definite_attempts);
        summaryRows(end+1,:) = {smdNo,spec.id,spec.sampleCount, ...
            spec.injectCount,spec.normalCount,spec.directCount, ...
            spec.auxiliaryCount,height(subset),upperSuccesses, ...
            upperSuccesses/height(subset),lowerSuccesses, ...
            lowerSuccesses/height(subset),finiteMedian(subset.upper_error), ...
            finiteIQR(subset.upper_error),finiteMedian(subset.lower_error), ...
            finiteIQR(subset.lower_error),finiteMedian(subset.UFE), ...
            finiteIQR(subset.UFE),finiteMedian(subset.LFE_total), ...
            finiteIQR(subset.LFE_total), ...
            finiteMedian(subset.nominal_budget_carried_error), ...
            finiteIQR(subset.nominal_budget_carried_error), ...
            finiteMedian(subset.first_hit_UFE(successful)), ...
            finiteMedian(subset.first_hit_LFE(successful)),fitAttempts, ...
            fitSuccesses,safeRatio(fitSuccesses,fitAttempts), ...
            finiteMedian(fitSubset.first_valid_fit_generation), ...
            finiteMedian(fitSubset.first_injection_generation), ...
            finiteMedian(fitSubset.design_condition_median),hessianAttempts, ...
            hessianNegative,safeRatio(hessianNegative,hessianAttempts), ...
            finiteMedian(subset.direct_fitness_rank_median), ...
            finiteMedian(subset.direct_parent_selection_rate)}; %#ok<AGROW>
    end
end
summary = cell2table(summaryRows,'VariableNames',summaryNames);
pairedTests = pairedComparisons(runs,specifications,problemNumbers);
end

function pairedTests = pairedComparisons(runs,specifications,problemNumbers)
% Compare every E group with A0.  For each pair, common-budget error is
% reconstructed from only logged true evaluations at min(final UFE_A0,
% final UFE_variant); it does not add an evaluation.
baseSpec = specifications(strcmp({specifications.id},'A0'));
variantSpecs = specifications(~strcmp({specifications.id},'A0'));
names = {'SMD','comparison','reference_experiment','variant_experiment', ...
    'archive_sample_count','prediction_inject_count', ...
    'normal_candidate_count','direct_candidate_count', ...
    'auxiliary_candidate_count','paired_runs', ...
    'reference_upper_successes','variant_upper_successes', ...
    'reference_lower_successes','variant_lower_successes', ...
    'reference_upper_error_median','variant_upper_error_median', ...
    'reference_lower_error_median','variant_lower_error_median', ...
    'reference_UFE_median','variant_UFE_median', ...
    'reference_LFE_median','variant_LFE_median','common_UFE_median', ...
    'reference_common_budget_error_median', ...
    'variant_common_budget_error_median','upper_error_p', ...
    'lower_error_p','UFE_p','LFE_p','common_budget_upper_error_p', ...
    'upper_error_p_holm','lower_error_p_holm','UFE_p_holm', ...
    'LFE_p_holm','common_budget_upper_error_p_holm', ...
    'upper_error_method','lower_error_method','UFE_method','LFE_method', ...
    'common_budget_upper_error_method','upper_error_advantage', ...
    'lower_error_advantage','UFE_advantage','LFE_advantage', ...
    'common_budget_upper_error_advantage','evaluation_advantage_eligible'};
rows = cell(0,numel(names));
for smdNo = problemNumbers(:)'
    reference = runs(runs.SMD == smdNo & ...
        strcmp(runs.experiment_id,baseSpec.id),:);
    assert(~isempty(reference),'Missing A0 rows for SMD%d.',smdNo);
    for i = 1:numel(variantSpecs)
        spec = variantSpecs(i);
        variant = runs(runs.SMD == smdNo & ...
            strcmp(runs.experiment_id,spec.id),:);
        [reference,variant] = alignPairedRows(reference,variant,smdNo,spec.id);
        commonUFE = min(reference.UFE,variant.UFE);
        referenceBudgetError = NaN(height(reference),1);
        variantBudgetError = NaN(height(variant),1);
        for rowIndex = 1:height(reference)
            referenceBudgetError(rowIndex) = carriedErrorAtUFE( ...
                reference(rowIndex,:),commonUFE(rowIndex));
            variantBudgetError(rowIndex) = carriedErrorAtUFE( ...
                variant(rowIndex,:),commonUFE(rowIndex));
        end
        upperTest = pairedWilcoxonSignedRank(variant.upper_error, ...
            reference.upper_error);
        lowerTest = pairedWilcoxonSignedRank(variant.lower_error, ...
            reference.lower_error);
        UFETest = pairedWilcoxonSignedRank(variant.UFE,reference.UFE);
        LFETest = pairedWilcoxonSignedRank(variant.LFE_total,reference.LFE_total);
        budgetTest = pairedWilcoxonSignedRank(variantBudgetError, ...
            referenceBudgetError);
        successEligible = sum(variant.upper_success ~= 0) >= ...
            sum(reference.upper_success ~= 0) && ...
            sum(variant.lower_success ~= 0) >= sum(reference.lower_success ~= 0);
        rows(end+1,:) = {smdNo,'vs_A0',baseSpec.id,spec.id, ...
            spec.sampleCount,spec.injectCount,spec.normalCount, ...
            spec.directCount,spec.auxiliaryCount,height(reference), ...
            sum(reference.upper_success ~= 0),sum(variant.upper_success ~= 0), ...
            sum(reference.lower_success ~= 0),sum(variant.lower_success ~= 0), ...
            finiteMedian(reference.upper_error),finiteMedian(variant.upper_error), ...
            finiteMedian(reference.lower_error),finiteMedian(variant.lower_error), ...
            finiteMedian(reference.UFE),finiteMedian(variant.UFE), ...
            finiteMedian(reference.LFE_total),finiteMedian(variant.LFE_total), ...
            finiteMedian(commonUFE),finiteMedian(referenceBudgetError), ...
            finiteMedian(variantBudgetError),upperTest.p,lowerTest.p, ...
            UFETest.p,LFETest.p,budgetTest.p,NaN,NaN,NaN,NaN,NaN, ...
            upperTest.method,lowerTest.method,UFETest.method,LFETest.method, ...
            budgetTest.method,false,false,false,false,false,successEligible}; %#ok<AGROW>
    end
end
pairedTests = cell2table(rows,'VariableNames',names);
if isempty(pairedTests), return; end
pairedTests = applyHolmAndAdvantages(pairedTests);
end

function [reference,variant] = alignPairedRows(reference,variant,smdNo,variantId)
assert(height(reference) == height(variant), ...
    'SMD%d %s does not have the same number of paired rows as A0.', ...
    smdNo,variantId);
reference = sortrows(reference,'run_no');
variant = sortrows(variant,'run_no');
assert(isequal(reference.run_no,variant.run_no) && ...
    isequal(reference.seed,variant.seed), ...
    'SMD%d %s is not paired with A0 by run number and seed.',smdNo,variantId);
end

function errorValue = carriedErrorAtUFE(row,budget)
resultRoot = char(row.result_root);
matFile = char(row.mat_file);
if exist(matFile,'file') ~= 2
    matFile = fullfile(resultRoot,portableRelativePath(matFile));
end
assert(exist(matFile,'file') == 2,'Missing run log: %s',matFile);
loaded = load(matFile,'injectionLog','BI');
UFE = [loaded.injectionLog.UFE];
lastIndex = find(UFE <= budget,1,'last');
assert(~isempty(lastIndex), ...
    'No completed generation at common UFE %.15g in %s.',budget,matFile);
bestError = Inf;
for i = 1:lastIndex
    values = [loaded.injectionLog(i).upper_objective_after_true_evaluation(:); ...
        loaded.injectionLog(i).population_UF(:)];
    if loaded.injectionLog(i).external_refinement_upper_evaluated
        values(end+1,1) = loaded.injectionLog(i).external_refinement_UF; %#ok<AGROW>
    end
    values = values(isfinite(values));
    if ~isempty(values)
        bestError = min(bestError,min(abs(values-loaded.BI.u_fopt)));
    end
end
errorValue = bestError;
end

function tests = applyHolmAndAdvantages(tests)
metricNames = {'upper_error','lower_error','UFE','LFE', ...
    'common_budget_upper_error'};
for smdNo = unique(tests.SMD)'
    subset = tests.SMD == smdNo;
    for metricIndex = 1:numel(metricNames)
        metric = metricNames{metricIndex};
        rawColumn = [metric '_p'];
        adjustedColumn = [metric '_p_holm'];
        tests.(adjustedColumn)(subset) = holmAdjust(tests.(rawColumn)(subset));
    end
end
tests.upper_error_advantage = tests.upper_error_p_holm < 0.05 & ...
    tests.variant_upper_error_median < tests.reference_upper_error_median;
tests.lower_error_advantage = tests.lower_error_p_holm < 0.05 & ...
    tests.variant_lower_error_median < tests.reference_lower_error_median;
tests.UFE_advantage = tests.evaluation_advantage_eligible & ...
    tests.UFE_p_holm < 0.05 & ...
    tests.variant_UFE_median < tests.reference_UFE_median;
tests.LFE_advantage = tests.evaluation_advantage_eligible & ...
    tests.LFE_p_holm < 0.05 & ...
    tests.variant_LFE_median < tests.reference_LFE_median;
tests.common_budget_upper_error_advantage = ...
    tests.common_budget_upper_error_p_holm < 0.05 & ...
    tests.variant_common_budget_error_median < ...
    tests.reference_common_budget_error_median;
end

function adjusted = holmAdjust(pValues)
adjusted = NaN(size(pValues));
valid = find(isfinite(pValues));
if isempty(valid), return; end
[ordered,order] = sort(pValues(valid));
adjustedOrdered = NaN(numel(ordered),1);
previous = 0;
for i = 1:numel(ordered)
    previous = max(previous,min(1,(numel(ordered)-i+1)*ordered(i)));
    adjustedOrdered(i) = previous;
end
adjusted(valid(order)) = adjustedOrdered;
end

function value = finiteMedian(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = median(values); end
end

function value = finiteIQR(values)
values = sort(values(isfinite(values)));
if numel(values) < 2
    value = NaN;
    return;
end
value = percentile(values,75) - percentile(values,25);
end

function value = percentile(values,percent)
position = 1 + (numel(values)-1) * percent/100;
lower = floor(position);
upper = ceil(position);
if lower == upper
    value = values(lower);
else
    value = values(lower) + (position-lower) * (values(upper)-values(lower));
end
end

function value = safeRatio(numerator,denominator)
if denominator == 0, value = NaN; else, value = numerator/denominator; end
end

function localPath = portableRelativePath(relativePath)
localPath = strrep(relativePath,'/',filesep);
localPath = strrep(localPath,'\',filesep);
end
