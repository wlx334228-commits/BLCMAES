function value = modelNumber(model,name)
value = NaN;
if isstruct(model) && isfield(model,name) && isnumeric(model.(name)) && ...
        isscalar(model.(name)) && isfinite(model.(name))
    value = model.(name);
end
end

function value = modelLogical(model,name)
value = false;
if isstruct(model) && isfield(model,name) && ...
        (islogical(model.(name)) || isnumeric(model.(name))) && ...
        isscalar(model.(name)) && isfinite(model.(name))
    value = logical(model.(name));
end
end

function value = modelText(model,defaultValue)
value = defaultValue;
if isstruct(model) && isfield(model,'modelType') && ...
        (ischar(model.modelType) || isstring(model.modelType))
    value = char(model.modelType);
end
end
