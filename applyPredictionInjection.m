function [upper,lower,entry,state] = applyPredictionInjection( ...
    CMA,rawUpper,rawLower,generation,BI,options,state)
%APPLYPREDICTIONINJECTION Construct K=0,...,lambda evaluated candidates.
% All main-distribution samples are first drawn exactly as in the original
% code. When a pending prediction is valid, the final K slots are replaced
% before any lower-level or upper-level evaluation. The legacy
% direct-plus-auxiliary policy uses one direct prediction and K-1 auxiliary
% joint samples. The auxiliary-only policy uses K auxiliary joint samples,
% with the prediction only as their upper sampling centre.

populationSize = size(rawUpper,1);
assert(size(rawUpper,2) == BI.u_dim && size(rawLower,1) == populationSize, ...
    'BLCMAES:InvalidSample','Unexpected joint-sample dimensions.');
if isempty(state)
    state = initializePredictionInjectionState(BI,options);
end
if options.predictionInjectCount > populationSize
    error('BLCMAES:PredictionInjectionCount', ...
        'predictionInjectCount=%d exceeds population size %d.', ...
        options.predictionInjectCount,populationSize);
end
upper = rawUpper;
lower = rawLower;
entry = createEntry(CMA,rawUpper,rawLower,generation,BI,options);

if ~options.enabled || generation <= options.startGeneration || ...
        ~state.pending.valid
    entry.injection_reason = injectionReason(options,generation,state);
    entry.upper_after_injection = upper;
    entry.lower_after_injection = lower;
    entry.joint_after_injection = [upper,lower];
    return;
end

xPredRequested = state.pending.x_pred;
if ~isreal(xPredRequested) || numel(xPredRequested) ~= BI.u_dim || ...
        any(~isfinite(xPredRequested))
    entry.injection_reason = 'invalid_pending_prediction';
    entry.upper_after_injection = upper;
    entry.lower_after_injection = lower;
    entry.joint_after_injection = [upper,lower];
    return;
end

injectCount = options.predictionInjectCount;
injectedStart = populationSize-injectCount+1;
if options.usesDirectPrediction
    directIndex = injectedStart;
    auxiliaryIndices = (directIndex+1):populationSize;
    predictionReference = rawUpper(directIndex,:);
else
    directIndex = NaN;
    auxiliaryIndices = injectedStart:populationSize;
    % The prediction itself is not evaluated in auxiliary-only mode.  This
    % reference is used only by the existing boundary-repair rule to form a
    % feasible auxiliary-distribution centre.
    predictionReference = rawUpper(auxiliaryIndices(1),:);
end
[xPredActual,predictionCentreRepair] = repairUpperCandidate( ...
    xPredRequested,predictionReference,BI);
entry.prediction_valid_used = true;
entry.prediction_source_generation = state.pending.source_generation;
entry.prediction_model_type = modelText(state.pending.model, ...
    options.predictionModelType);
entry.predicted_UF_by_model = modelNumber(state.pending.model,'predictedUF');
entry.prediction_model_train_MSE = modelNumber(state.pending.model,'trainMSE');
entry.prediction_model_validation_MSE = ...
    modelNumber(state.pending.model,'validationMSE');
entry.prediction_model_training_epochs = ...
    modelNumber(state.pending.model,'trainingEpochs');
entry.prediction_model_best_epoch = ...
    modelNumber(state.pending.model,'bestEpoch');
entry.prediction_optimizer_converged = ...
    modelLogical(state.pending.model,'optimizerConverged');
entry.prediction_optimizer_iterations = ...
    modelNumber(state.pending.model,'optimizerIterations');
entry.prediction_optimizer_start_count = ...
    modelNumber(state.pending.model,'optimizerStartCount');
entry.prediction_optimizer_successful_starts = ...
    modelNumber(state.pending.model,'optimizerSuccessfulStarts');
entry.prediction_at_search_boundary = ...
    modelLogical(state.pending.model,'predictionAtSearchBoundary');
entry.prediction_to_nearest_history_sample = ...
    modelNumber(state.pending.model,'predictionToNearestSample');
entry.x_pred_requested = xPredRequested;
entry.x_pred_actual = xPredActual;
entry.prediction_center_requested_step = xPredRequested - ...
    entry.cma_mean_before_sampling(1:BI.u_dim);
entry.prediction_center_actual_step = xPredActual - ...
    entry.cma_mean_before_sampling(1:BI.u_dim);
entry.injection_reason = 'prediction_injected';
entry.prediction_distance_to_cma_mean = norm( ...
    entry.prediction_center_actual_step);
if ~isempty(state.history)
    [~,bestHistoryIndex] = max(state.history(:,end));
    entry.prediction_distance_to_history_best = norm(xPredActual - ...
        state.history(bestHistoryIndex,3:(BI.u_dim+2)));
end

% Draw all auxiliary members before changing any population slot.  If the
% requested covariance decomposition is numerically unusable, this entire
% generation deliberately falls back to the already-drawn normal population
% instead of evaluating a partially injected population.
auxiliaryRaw = NaN(0,BI.dim);
auxiliaryActual = NaN(0,BI.dim);
auxiliaryRepair = false(0,BI.dim);
samplingInfo = struct();
rlDecision = emptyPredictionRLDecision(BI.u_dim);
if ~isempty(auxiliaryIndices)
    if isempty(state.auxiliaryStream)
        error('BLCMAES:AuxiliaryRandomStream', ...
            'This policy requires its private auxiliary sampling stream.');
    end
    auxiliaryMean = CMA.xmean;
    % Use the bounded prediction only as the auxiliary upper centre. The
    % lower centre remains the main CMA-ES lower mean. In auxiliary-only
    % mode this is the sole use of xPredActual: no population member is set
    % equal to it directly.
    auxiliaryMean(1:BI.u_dim) = xPredActual;
    if options.rlEnabled
        [state.rlState,rlDecision] = choosePredictionRLAction( ...
            state.rlState,CMA,xPredActual,state.history,state.pending.model, ...
            BI,options);
        entry.rl_action_attempted = true;
        entry.rl_action_valid = rlDecision.valid;
        entry.rl_action_reason = rlDecision.reason;
        entry.rl_mode = options.rlMode;
        entry.rl_state_raw = rlDecision.state_raw;
        entry.rl_state_normalized = rlDecision.state_normalized;
        entry.rl_actor_mean = rlDecision.actor_mean;
        entry.rl_actor_log_std = rlDecision.actor_log_std;
        entry.rl_actor_std = rlDecision.actor_std;
        entry.rl_action_latent = rlDecision.action_latent;
        entry.rl_eta = rlDecision.eta;
        entry.rl_delta = rlDecision.delta;
        entry.rl_eta_learned = rlDecision.eta_learned;
        entry.rl_delta_learned = rlDecision.delta_learned;
        entry.rl_cma_eigenvalues = rlDecision.cmaEigenvalues;
        entry.rl_eigenvalues = rlDecision.rlEigenvalues;
        entry.rl_covariance = rlDecision.upperCovariance;
        entry.rl_covariance_trace_ratio = rlDecision.trace_ratio;
        entry.rl_covariance_condition = rlDecision.covariance_condition;
        entry.rl_principal_directions = rlDecision.principalDirections;
        if ~rlDecision.valid
            % The already drawn normal population is the safe fallback.
            entry.prediction_valid_used = false;
            entry.injection_reason = 'rl_action_failed_normal_fallback';
            entry.upper_after_injection = upper;
            entry.lower_after_injection = lower;
            entry.joint_after_injection = [upper,lower];
            return;
        end
    end
    try
        [auxiliaryRaw,samplingInfo] = sampleAuxiliaryJointCandidates( ...
            CMA,auxiliaryMean,numel(auxiliaryIndices),BI,options, ...
            state.auxiliaryStream,state.pending.model,rlDecision);
    catch samplingException
        if strncmp(samplingException.identifier,'BLCMAES:Auxiliary', ...
                numel('BLCMAES:Auxiliary')) || ...
                strcmp(samplingException.identifier,'BLCMAES:HessianCovariance')
            entry.prediction_valid_used = false;
            if strcmp(options.auxiliarySamplingDistribution,'hessian_gaussian')
                % This is an explicit all-normal safe fallback: a valid
                % prediction without a numerically valid curvature shape
                % never leads to partially injected/evaluated candidates.
                entry.hessian_covariance_attempted = true;
                entry.hessian_covariance_success = false;
                entry.hessian_covariance_failure_reason = ...
                    samplingException.message;
                entry.injection_reason = ...
                    'hessian_covariance_failed_normal_fallback';
            elseif strcmp(options.auxiliarySamplingDistribution, ...
                    'rl_adaptive_gaussian')
                entry.rl_action_valid = false;
                entry.rl_action_reason = samplingException.message;
                entry.injection_reason = 'rl_covariance_failed_normal_fallback';
            else
                entry.injection_reason = 'auxiliary_sampling_failed';
            end
            entry.upper_after_injection = upper;
            entry.lower_after_injection = lower;
            entry.joint_after_injection = [upper,lower];
            return;
        end
        rethrow(samplingException);
    end
end

if options.usesDirectPrediction
    upper(directIndex,:) = xPredActual;
    entry.source_labels{directIndex} = 'predicted_direct';
    entry.direct_index = directIndex;
    entry.direct_boundary_repaired = predictionCentreRepair;
    entry.direct_requested_step = entry.prediction_center_requested_step;
    entry.direct_actual_step = entry.prediction_center_actual_step;
else
    % Kept separate from direct_boundary_repaired so boundary-repair totals
    % remain interpretable when no direct candidate exists.
    entry.prediction_center_boundary_repaired = predictionCentreRepair;
end
if ~isempty(auxiliaryIndices)
    auxiliaryActual = NaN(numel(auxiliaryIndices),BI.dim);
    auxiliaryRepair = false(numel(auxiliaryIndices),BI.dim);
    for j = 1:numel(auxiliaryIndices)
        [auxiliaryActual(j,:),auxiliaryRepair(j,:)] = repairJointCandidate( ...
            auxiliaryRaw(j,:),auxiliaryMean,BI);
        index = auxiliaryIndices(j);
        upper(index,:) = auxiliaryActual(j,1:BI.u_dim);
        lower(index,:) = auxiliaryActual(j,BI.u_dim+1:end);
        entry.source_labels{index} = 'predicted_auxiliary';
    end
    entry.auxiliary_index = auxiliaryIndices(1);
    entry.auxiliary_indices = auxiliaryIndices;
    entry.auxiliary_mean = repmat(auxiliaryMean,numel(auxiliaryIndices),1);
    entry.auxiliary_raw_joint = auxiliaryRaw;
    entry.auxiliary_actual_joint = auxiliaryActual;
    entry.auxiliary_boundary_repaired = auxiliaryRepair;
    entry.auxiliary_upper_center = samplingInfo.upperCenter;
    entry.auxiliary_upper_target_covariance = samplingInfo.upperTargetCovariance;
    entry.auxiliary_lower_conditional_covariance = ...
        samplingInfo.lowerConditionalCovariance;
    entry.auxiliary_isotropic_variance = samplingInfo.isotropicVariance;
    entry.auxiliary_sampling_scale = samplingInfo.samplingScale;
    entry.cma_upper_rms_search_scale = samplingInfo.cmaUpperRmsSearchScale;
    entry.hessian_covariance_attempted = samplingInfo.hessianCovarianceAttempted;
    entry.hessian_covariance_success = samplingInfo.hessianCovarianceSuccess;
    entry.hessian_covariance_failure_reason = ...
        samplingInfo.hessianCovarianceFailureReason;
    entry.hessian_negative_matrix = samplingInfo.hessianNegativeMatrix;
    entry.hessian_raw_curvature_eigenvalues = ...
        samplingInfo.hessianRawCurvatureEigenvalues;
    entry.hessian_regularized_curvature_eigenvalues = ...
        samplingInfo.hessianRegularizedCurvatureEigenvalues;
    entry.hessian_eigenvalue_floor = samplingInfo.hessianEigenvalueFloor;
    entry.hessian_regularized_mask = samplingInfo.hessianRegularizedMask;
    entry.hessian_regularized_count = samplingInfo.hessianRegularizedCount;
    entry.hessian_raw_curvature_condition = ...
        samplingInfo.hessianRawCurvatureCondition;
    entry.hessian_regularized_curvature_condition = ...
        samplingInfo.hessianRegularizedCurvatureCondition;
    entry.hessian_shape_covariance = samplingInfo.hessianShapeCovariance;
    entry.hessian_auxiliary_covariance = samplingInfo.hessianAuxiliaryCovariance;
    entry.hessian_auxiliary_covariance_eigenvalues = ...
        samplingInfo.hessianAuxiliaryCovarianceEigenvalues;
    entry.hessian_auxiliary_covariance_condition = ...
        samplingInfo.hessianAuxiliaryCovarianceCondition;
    entry.cma_upper_covariance_eigenvalues = ...
        samplingInfo.cmaUpperCovarianceEigenvalues;
    entry.cma_upper_covariance_condition = ...
        samplingInfo.cmaUpperCovarianceCondition;
    entry.hessian_cma_trace_ratio = samplingInfo.hessianCmaTraceRatio;
    entry.hessian_cma_principal_angle_degrees = ...
        samplingInfo.hessianCmaPrincipalAngleDegrees;
    entry.auxiliary_upper_raw_offsets = bsxfun(@minus, ...
        auxiliaryRaw(:,1:BI.u_dim),samplingInfo.upperCenter);
    entry.auxiliary_upper_actual_offsets = bsxfun(@minus, ...
        auxiliaryActual(:,1:BI.u_dim),samplingInfo.upperCenter);
    entry.auxiliary_raw_distance_to_prediction = sqrt(sum( ...
        entry.auxiliary_upper_raw_offsets.^2,2));
    entry.auxiliary_actual_distance_to_prediction = sqrt(sum( ...
        entry.auxiliary_upper_actual_offsets.^2,2));
    entry.auxiliary_relative_distance_to_cma_scale = ...
        entry.auxiliary_actual_distance_to_prediction / ...
        max(samplingInfo.cmaUpperRmsSearchScale,eps);
    if options.rlEnabled
        % This is the covariance that actually generated the two evaluated
        % auxiliary points, after all positive-definiteness checks.
        entry.rl_covariance = samplingInfo.upperTargetCovariance;
    end
end

entry.upper_after_injection = upper;
entry.lower_after_injection = lower;
entry.joint_after_injection = [upper,lower];
entry.injected_indices = find(~strcmp(entry.source_labels,'normal'))';
entry.injected_count = numel(entry.injected_indices);
entry.effective_injected_count = entry.injected_count;
entry.normal_sample_count = populationSize-entry.injected_count;
end

function [jointSamples,info] = sampleAuxiliaryJointCandidates( ...
    CMA,auxiliaryMean,sampleCount,BI,options,stream,predictionModel,rlDecision)
% Construct the auxiliary joint population without touching the global RNG.
% For the alternative upper distributions, lower variables are sampled
% from the original CMA-ES Gaussian conditional on the new upper location.
% The RL branch deliberately retains the legacy direct-CMA lower draw so it
% is paired fairly with the existing fixed-eta CMA-Gaussian baseline; in all
% cases the changed object is only the upper distribution around x_pred.

upperDim = BI.u_dim;
% This helper has eight inputs.  Do not overwrite the valid RL action that
% applyPredictionInjection has just selected for this generation.
if nargin < 8 || isempty(rlDecision)
    rlDecision = emptyPredictionRLDecision(upperDim);
end
lowerDim = BI.l_dim;
jointDim = BI.dim;
C = (CMA.C + CMA.C') / 2;
Cuu = C(1:upperDim,1:upperDim);
Cul = C(1:upperDim,upperDim+1:end);
Cll = C(upperDim+1:end,upperDim+1:end);
if rcond(Cuu) <= eps
    error('BLCMAES:AuxiliaryCovariance', ...
        'The upper CMA-ES covariance block is numerically singular.');
end
conditionalMap = Cuu \ Cul;
conditionalLowerCovariance = CMA.sigma^2 * (Cll - Cul' * conditionalMap);
conditionalLowerCovariance = ...
    (conditionalLowerCovariance + conditionalLowerCovariance') / 2;
upperTargetCovariance = CMA.sigma^2 * Cuu;
upperCenter = auxiliaryMean(1:upperDim);
lowerCenter = auxiliaryMean(upperDim+1:end);
isotropicVariance = CMA.sigma^2 * trace(Cuu) / upperDim;
cmaUpperRmsSearchScale = sqrt(max(isotropicVariance,0));
samplingScale = options.auxiliarySamplingScale;
upperTargetCovariance = samplingScale^2 * upperTargetCovariance;
jointSamples = NaN(sampleCount,jointDim);
hessianInfo = emptyHessianSamplingInfo(upperDim);

switch options.auxiliarySamplingDistribution
    case 'cma_gaussian'
        % Preserve the historic B2/K implementation exactly: one private
        % row-vector normal draw per auxiliary member, transformed through
        % the full joint CMA-ES eigensystem.
        for j = 1:sampleCount
            jointSamples(j,:) = auxiliaryMean + CMA.sigma * ...
                randn(stream,1,jointDim) .* CMA.D * CMA.B';
            % eta changes only the upper perturbation about x_pred.  eta=1
            % is exactly the previous A2 joint-sampling implementation;
            % lower coordinates retain their existing sampled values.
            jointSamples(j,1:upperDim) = upperCenter + samplingScale * ...
                (jointSamples(j,1:upperDim)-upperCenter);
        end
    case 'rl_adaptive_gaussian'
        % Keep the legacy B2 lower-coordinate draw intact.  RL changes only
        % the upper marginal around x_pred, so F050 and RL use the same
        % private-stream joint normal draws and the same lower marginal.
        if ~rlDecision.valid || any(~isfinite(rlDecision.upperCovariance(:)))
            error('BLCMAES:AuxiliaryCovariance', ...
                'No valid pre-sampling RL auxiliary covariance is available.');
        end
        upperTargetCovariance = (rlDecision.upperCovariance + ...
            rlDecision.upperCovariance')/2;
        rlFactor = symmetricSquareRoot(upperTargetCovariance, ...
            'RL auxiliary covariance');
        for j = 1:sampleCount
            normalDraw = randn(stream,1,jointDim);
            legacyJoint = auxiliaryMean + CMA.sigma * ...
                normalDraw .* CMA.D * CMA.B';
            upper = upperCenter + normalDraw(1:upperDim) * rlFactor';
            jointSamples(j,:) = [upper,legacyJoint(upperDim+1:end)];
        end
    case {'isotropic_gaussian','uniform_ellipsoid','hessian_gaussian'}
        upperFactor = symmetricSquareRoot(Cuu,'upper CMA-ES covariance');
        lowerFactor = symmetricSquareRoot( ...
            conditionalLowerCovariance,'conditional lower covariance');
        if strcmp(options.auxiliarySamplingDistribution,'hessian_gaussian')
            cmaUpperCovariance = CMA.sigma^2 * Cuu;
            hessianBuild = constructHessianAuxiliaryCovariance( ...
                predictionModel,cmaUpperCovariance,options);
            % This experiment compares shapes only.  The runner fixes eta=1
            % for H1, but retaining this multiplication makes an explicitly
            % requested auxiliarySamplingScale mathematically transparent.
            hessianCovariance = options.auxiliarySamplingScale^2 * ...
                hessianBuild.covariance;
            hessianFactor = symmetricSquareRoot( ...
                hessianCovariance,'Hessian auxiliary covariance');
            upperTargetCovariance = hessianCovariance;
            hessianInfo = makeHessianSamplingInfo(hessianBuild, ...
                hessianCovariance,options.auxiliarySamplingScale);
        end
        for j = 1:sampleCount
            normalDraw = randn(stream,1,jointDim);
            switch options.auxiliarySamplingDistribution
                case 'isotropic_gaussian'
                    upper = upperCenter + samplingScale * ...
                        sqrt(isotropicVariance) * ...
                        normalDraw(1:upperDim);
                case 'uniform_ellipsoid'
                    directionNorm = norm(normalDraw(1:upperDim));
                    if directionNorm <= 0
                        % A zero normal vector has probability zero, but the
                        % deterministic fallback keeps the routine total.
                        direction = [1,zeros(1,upperDim-1)];
                    else
                        direction = normalDraw(1:upperDim) / directionNorm;
                    end
                    radius = rand(stream,1)^(1/upperDim);
                    upper = upperCenter + samplingScale * ...
                        sqrt(upperDim+2) * CMA.sigma * ...
                        radius * direction * upperFactor';
                case 'hessian_gaussian'
                    upper = upperCenter + normalDraw(1:upperDim) * ...
                        hessianFactor';
            end
            upperOffset = upper - upperCenter;
            lowerConditionalMean = lowerCenter + upperOffset * conditionalMap;
            lower = lowerConditionalMean + normalDraw(upperDim+1:end) * ...
                lowerFactor';
            jointSamples(j,:) = [upper,lower];
        end
        if strcmp(options.auxiliarySamplingDistribution,'isotropic_gaussian')
            upperTargetCovariance = samplingScale^2 * ...
                isotropicVariance * eye(upperDim);
        end
    otherwise
        error('BLCMAES:AuxiliaryDistribution', ...
            'Unsupported auxiliary sampling distribution: %s', ...
            options.auxiliarySamplingDistribution);
end

info = struct('upperCenter',upperCenter, ...
    'upperTargetCovariance',upperTargetCovariance, ...
    'lowerConditionalCovariance',conditionalLowerCovariance, ...
    'isotropicVariance',isotropicVariance, ...
    'samplingScale',samplingScale, ...
    'cmaUpperRmsSearchScale',cmaUpperRmsSearchScale, ...
    'hessianCovarianceAttempted',hessianInfo.attempted, ...
    'hessianCovarianceSuccess',hessianInfo.success, ...
    'hessianCovarianceFailureReason',hessianInfo.failureReason, ...
    'hessianNegativeMatrix',hessianInfo.negativeMatrix, ...
    'hessianRawCurvatureEigenvalues',hessianInfo.rawCurvatureEigenvalues, ...
    'hessianRegularizedCurvatureEigenvalues', ...
        hessianInfo.regularizedCurvatureEigenvalues, ...
    'hessianEigenvalueFloor',hessianInfo.eigenvalueFloor, ...
    'hessianRegularizedMask',hessianInfo.regularizedMask, ...
    'hessianRegularizedCount',hessianInfo.regularizedCount, ...
    'hessianRawCurvatureCondition',hessianInfo.rawCurvatureCondition, ...
    'hessianRegularizedCurvatureCondition', ...
        hessianInfo.regularizedCurvatureCondition, ...
    'hessianShapeCovariance',hessianInfo.shapeCovariance, ...
    'hessianAuxiliaryCovariance',hessianInfo.auxiliaryCovariance, ...
    'hessianAuxiliaryCovarianceEigenvalues', ...
        hessianInfo.auxiliaryCovarianceEigenvalues, ...
    'hessianAuxiliaryCovarianceCondition', ...
        hessianInfo.auxiliaryCovarianceCondition, ...
    'cmaUpperCovarianceEigenvalues',hessianInfo.cmaUpperCovarianceEigenvalues, ...
    'cmaUpperCovarianceCondition',hessianInfo.cmaUpperCovarianceCondition, ...
    'hessianCmaTraceRatio',hessianInfo.cmaTraceRatio, ...
    'hessianCmaPrincipalAngleDegrees',hessianInfo.cmaPrincipalAngleDegrees);
end

function info = emptyHessianSamplingInfo(upperDim)
% Keep all MAT-log entries rectangular for A0/A1/A2 and H1 alike.
info = struct('attempted',false,'success',false, ...
    'failureReason','not_requested', ...
    'negativeMatrix',NaN(upperDim), ...
    'rawCurvatureEigenvalues',NaN(upperDim,1), ...
    'regularizedCurvatureEigenvalues',NaN(upperDim,1), ...
    'eigenvalueFloor',NaN, ...
    'regularizedMask',false(upperDim,1), ...
    'regularizedCount',0, ...
    'rawCurvatureCondition',NaN, ...
    'regularizedCurvatureCondition',NaN, ...
    'shapeCovariance',NaN(upperDim), ...
    'auxiliaryCovariance',NaN(upperDim), ...
    'auxiliaryCovarianceEigenvalues',NaN(upperDim,1), ...
    'auxiliaryCovarianceCondition',NaN, ...
    'cmaUpperCovarianceEigenvalues',NaN(upperDim,1), ...
    'cmaUpperCovarianceCondition',NaN, ...
    'cmaTraceRatio',NaN, ...
    'cmaPrincipalAngleDegrees',NaN);
end

function info = makeHessianSamplingInfo(build,covariance,samplingScale)
info = emptyHessianSamplingInfo(size(covariance,1));
[vectors,diagonal] = eig((covariance+covariance')/2);
covarianceEigenvalues = real(diag(diagonal));
% Scaling is unity for H1 in this experiment.  These fields retain their
% true values if a caller later requests a non-unit local scale.
if samplingScale ~= 1
    covarianceEigenvalues = samplingScale^2 * build.covarianceEigenvalues;
end
info.attempted = true;
info.success = true;
info.failureReason = 'valid';
info.negativeMatrix = build.negativeHessian;
info.rawCurvatureEigenvalues = build.rawCurvatureEigenvalues;
info.regularizedCurvatureEigenvalues = build.regularizedCurvatureEigenvalues;
info.eigenvalueFloor = build.eigenvalueFloor;
info.regularizedMask = build.regularizedMask;
info.regularizedCount = build.regularizedCount;
info.rawCurvatureCondition = build.rawCurvatureCondition;
info.regularizedCurvatureCondition = build.regularizedCurvatureCondition;
info.shapeCovariance = build.rawShapeCovariance;
info.auxiliaryCovariance = covariance;
info.auxiliaryCovarianceEigenvalues = covarianceEigenvalues;
info.auxiliaryCovarianceCondition = ...
    max(covarianceEigenvalues)/min(covarianceEigenvalues);
info.cmaUpperCovarianceEigenvalues = build.cmaEigenvalues;
info.cmaUpperCovarianceCondition = build.cmaCondition;
info.cmaTraceRatio = trace(covariance)/build.cmaTrace;
info.cmaPrincipalAngleDegrees = build.principalAngleDegrees;
% vectors is deliberately evaluated so non-real eigenvectors are surfaced
% by the finite/positive covariance checks above rather than hidden.
assert(isreal(vectors) && all(isfinite(vectors(:))), ...
    'BLCMAES:HessianCovariance', ...
    'The Hessian covariance eigensystem is invalid.');
end

function factor = symmetricSquareRoot(covariance,label)
covariance = (covariance + covariance') / 2;
[vectors,values] = eig(covariance);
eigenvalues = real(diag(values));
scale = max(1,max(abs(eigenvalues)));
if any(~isfinite(eigenvalues)) || min(eigenvalues) < -1e-10 * scale
    error('BLCMAES:AuxiliaryCovariance', ...
        '%s is not positive semidefinite.',label);
end
factor = real(vectors * diag(sqrt(max(eigenvalues,0))));
end

function reason = injectionReason(options,generation,state)
if ~options.enabled
    reason = 'A0';
elseif generation <= options.startGeneration
    reason = 'warmup';
elseif ~isfield(state,'pending') || ~state.pending.valid
    reason = 'invalid_prediction';
else
    reason = 'not_injected';
end
end

function [actual,repaired] = repairUpperCandidate(requested,reference,BI)
actual = requested;
high = actual > BI.u_ub;
low = actual < BI.u_lb;
actual(high) = (reference(high)+BI.u_ub(high))/2;
actual(low) = (reference(low)+BI.u_lb(low))/2;
repaired = high | low;
end

function [actual,repaired] = repairJointCandidate(requested,reference,BI)
actual = requested;
upper = actual(1:BI.u_dim);
lower = actual(BI.u_dim+1:end);
upperHigh = upper > BI.u_ub;
upperLow = upper < BI.u_lb;
lowerHigh = lower > BI.l_ub;
lowerLow = lower < BI.l_lb;
upper(upperHigh) = (reference(upperHigh)+BI.u_ub(upperHigh))/2;
upper(upperLow) = (reference(upperLow)+BI.u_lb(upperLow))/2;
