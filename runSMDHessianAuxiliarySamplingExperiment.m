function experiment = runSMDHessianAuxiliarySamplingExperiment( ...
    outputRoot,numberOfRuns,problemNumbers)
%RUNSMDHESSIANAUXILIARYSAMPLINGEXPERIMENT Formal A0/A1/A2/H1 comparison.
% Scope: unconstrained SMD1--SMD8 at (DU,DL)=(2,3), lambda=8.
%
% A0: 8 normal CMA-ES candidates;
% A1: 7 normal + 1 direct quadratic prediction;
% A2: 5 normal + 1 direct + 2 Gaussian auxiliaries using sigma^2*C_UU;
% H1: 5 normal + 1 direct + 2 Gaussian auxiliaries whose covariance shape
%     is the trace-matched inverse curvature of the same fitted quadratic.
%
% The default is the full, reproducible 20-run paired experiment:
%   runSMDHessianAuxiliarySamplingExperiment
% A smaller independent smoke batch, for example, is:
%   runSMDHessianAuxiliarySamplingExperiment([],1,1)

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 2 || isempty(numberOfRuns), numberOfRuns = 20; end
if nargin < 3 || isempty(problemNumbers), problemNumbers = 1:8; end
validateattributes(numberOfRuns,{'numeric'},{'scalar','integer','positive'});
validateattributes(problemNumbers,{'numeric'}, ...
    {'vector','integer','>=',1,'<=',8});
assert(numel(unique(problemNumbers)) == numel(problemNumbers), ...
    'problemNumbers must not contain duplicates.');
if nargin < 1 || isempty(outputRoot)
    if isequal(problemNumbers(:)',1:8)
        scope = 'SMD1_8';
    elseif numel(problemNumbers) == 1
        scope = sprintf('SMD%d',problemNumbers);
    else
        scope = sprintf('SMD%d_to_SMD%d',min(problemNumbers),max(problemNumbers));
    end
    outputRoot = fullfile(projectRoot,'results_hessian_auxiliary_sampling_2D', ...
        sprintf('%s_%druns',scope,numberOfRuns));
end
if exist(outputRoot,'dir') ~= 7, mkdir(outputRoot); end

specifications = hessianSpecifications(outputRoot);
saveOrValidateConfig(outputRoot,numberOfRuns,problemNumbers,specifications);

smokeRoot = fullfile(outputRoot,'smoke_test_H1');
if exist(fullfile(smokeRoot,'hessian_auxiliary_sampling_test_report.mat'), ...
        'file') ~= 2
    testHessianAuxiliarySampling(smokeRoot);
else
    fprintf('Reuse completed Hessian sampling smoke test: %s\n',smokeRoot);
end

for specIndex = 1:numel(specifications)
    spec = specifications(specIndex);
    fprintf(['Run %s: %d normal + %d direct + %d auxiliary; ' ...
        'distribution=%s.\n'],spec.id,spec.normalCount,spec.directCount, ...
        spec.auxiliaryCount,spec.auxiliarySamplingDistribution);
    runSMDPredictionInjection(spec.resultRoot,numberOfRuns,problemNumbers, ...
        spec.injectCount,'direct_plus_auxiliary',5,40, ...
        spec.auxiliarySamplingDistribution,1.0);
end

runs = collectRuns(specifications,problemNumbers,numberOfRuns);
[summary,pairedTests] = summariseHessianAuxiliarySamplingExperiment( ...
    runs,specifications,problemNumbers);
[matchedBudgetRuns,matchedBudgetSummary,matchedBudgetTests] = ...
    analyseHessianAuxiliaryMatchedBudget(runs,problemNumbers,outputRoot);
writetable(runs,fullfile(outputRoot,'hessian_auxiliary_runs.csv'));
writetable(summary,fullfile(outputRoot,'hessian_auxiliary_summary.csv'));
writetable(pairedTests, ...
    fullfile(outputRoot,'hessian_auxiliary_paired_wilcoxon.csv'));
writetable(matchedBudgetRuns, ...
    fullfile(outputRoot,'hessian_auxiliary_matched_budget_runs.csv'));
writetable(matchedBudgetSummary, ...
    fullfile(outputRoot,'hessian_auxiliary_matched_budget_summary.csv'));
writetable(matchedBudgetTests, ...
    fullfile(outputRoot,'hessian_auxiliary_matched_budget_wilcoxon.csv'));
experiment = struct('outputRoot',outputRoot,'numberOfRuns',numberOfRuns, ...
    'problemNumbers',problemNumbers,'specifications',specifications, ...
    'runs',runs,'summary',summary,'pairedTests',pairedTests, ...
    'matchedBudgetRuns',matchedBudgetRuns, ...
    'matchedBudgetSummary',matchedBudgetSummary, ...
    'matchedBudgetTests',matchedBudgetTests);
save(fullfile(outputRoot,'hessian_auxiliary_experiment_index.mat'), ...
    'experiment','-v7');
fprintf('\nA0/A1/A2/H1 Hessian auxiliary experiment completed: %s\n', ...
    outputRoot);
end

function specifications = hessianSpecifications(outputRoot)
specifications = [ ...
    makeSpec('A0',0,8,0,0,'cma_gaussian',outputRoot); ...
    makeSpec('A1',1,7,1,0,'cma_gaussian',outputRoot); ...
    makeSpec('A2',3,5,1,2,'cma_gaussian',outputRoot); ...
    makeSpec('H1',3,5,1,2,'hessian_gaussian',outputRoot)];
end

function spec = makeSpec(id,injectCount,normalCount,directCount, ...
    auxiliaryCount,distribution,outputRoot)
assert(normalCount+directCount+auxiliaryCount == 8, ...
    'Every (2+3) population must have exactly eight candidates.');
spec = struct('id',id,'injectCount',injectCount, ...
    'normalCount',normalCount,'directCount',directCount, ...
    'auxiliaryCount',auxiliaryCount, ...
    'auxiliarySamplingDistribution',distribution, ...
    'resultRoot',fullfile(outputRoot,[id '_' distribution]));
end

function saveOrValidateConfig(outputRoot,numberOfRuns,problemNumbers,specifications)
configFile = fullfile(outputRoot,'hessian_auxiliary_experiment_config.mat');
config = struct('totalDim',5,'upperDim',2,'lowerDim',3, ...
    'populationSize',8,'numberOfRuns',numberOfRuns, ...
    'problemNumbers',problemNumbers,'sampleCount',40, ...
    'startGeneration',10,'historyGenerations',10, ...
    'hessianCovarianceRelativeEigenvalueFloor',1e-6, ...
    'hessianCovarianceMaxCondition',1e4, ...
    'specifications',serialisableSpecifications(specifications), ...
    'comparisons',{{'A1_vs_A0','A2_vs_A1','H1_vs_A1','H1_vs_A2'}}, ...
    'notes',['A2 and H1 have identical K=3, direct prediction, history ' ...
        'model, normal/auxiliary counts, and trace-matched total upper ' ...
        'variance.  They differ only in auxiliary covariance shape.']);
if exist(configFile,'file') ~= 2
    save(configFile,'config');
    return;
end
loaded = load(configFile,'config');
previous = loaded.config;
assert(previous.totalDim == 5 && previous.numberOfRuns == numberOfRuns && ...
    isequal(previous.problemNumbers,problemNumbers) && ...
    isequal(previous.specifications,serialisableSpecifications(specifications)), ...
    ['This output directory has a different H1 configuration.  Choose a ' ...
     'fresh outputRoot rather than mixing experiments.']);
end

function allRuns = collectRuns(specifications,problemNumbers,numberOfRuns)
allRuns = table();
for specIndex = 1:numel(specifications)
    spec = specifications(specIndex);
    fileName = fullfile(spec.resultRoot,'injection_runs.csv');
    assert(exist(fileName,'file') == 2,'Missing result table: %s',fileName);
    rows = readtable(fileName);
    rows = rows(ismember(rows.SMD,problemNumbers) & ...
        rows.prediction_inject_count == spec.injectCount,:);
    validateSchedule(rows,spec,problemNumbers,numberOfRuns);
    rows.experiment_id = repmat({spec.id},height(rows),1);
    rows.auxiliary_sampling_distribution = repmat( ...
        {spec.auxiliarySamplingDistribution},height(rows),1);
    rows.configured_normal_candidate_count = repmat(spec.normalCount,height(rows),1);
    rows.configured_direct_candidate_count = repmat(spec.directCount,height(rows),1);
    rows.configured_auxiliary_candidate_count = repmat( ...
        spec.auxiliaryCount,height(rows),1);
    % A master-relative path keeps the combined result table usable after
    % the entire project/output folder is copied to another machine.
    rows.result_root = repmat({[spec.id '_' spec.auxiliarySamplingDistribution]}, ...
        height(rows),1);
    if isempty(allRuns), allRuns = rows; else, allRuns = [allRuns;rows]; end %#ok<AGROW>
end
allRuns = sortrows(allRuns,{'SMD','experiment_id','run_no'});
end

function stored = serialisableSpecifications(specifications)
% Do not store absolute result roots in the immutable master configuration.
stored = specifications;
for i = 1:numel(stored)
    stored(i).resultRoot = [stored(i).id '_' ...
        stored(i).auxiliarySamplingDistribution];
end
end

function validateSchedule(rows,spec,problemNumbers,numberOfRuns)
for smdNo = problemNumbers(:)'
    subset = rows(rows.SMD == smdNo,:);
    assert(height(subset) == numberOfRuns, ...
        '%s has an incomplete SMD%d run set.',spec.id,smdNo);
    assert(isequal(sort(subset.run_no)',1:numberOfRuns), ...
        '%s has duplicate/missing runs for SMD%d.',spec.id,smdNo);
    expectedSeed = (smdNo-1)*numberOfRuns+subset.run_no;
    assert(all(subset.seed == expectedSeed), ...
        '%s does not use the paired seed schedule for SMD%d.',spec.id,smdNo);
end
end
