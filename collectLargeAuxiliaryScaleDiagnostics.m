function [generations,runDiagnostics] = collectLargeAuxiliaryScaleDiagnostics( ...
        outputRoot,runs)
%COLLECTLARGEAUXILIARYSCALEDIAGNOSTICS Read existing logs, no evaluations.
% Distinguishes boundary repair of sampled coordinates from the existing
% CMA-ES length limit applied only to selected parents' adaptation steps.

names = {'SMD','variant','run_no','seed','eta','generation','UFE', ...
    'auxiliary_count','raw_distance_median','actual_distance_median', ...
    'relative_distance_median','distance_retention_median', ...
    'auxiliary_upper_repaired_candidates','auxiliary_joint_repaired_candidates', ...
    'direct_repaired_candidates','auxiliary_selected_parents', ...
    'auxiliary_limited_parent_steps','auxiliary_parent_step_scale_median'};
runNames = {'SMD','variant','run_no','seed','eta','auxiliary_count', ...
    'raw_distance_median','actual_distance_median','relative_distance_median', ...
    'distance_retention_median','auxiliary_upper_repaired_candidates', ...
    'auxiliary_joint_repaired_candidates','direct_repaired_candidates', ...
    'auxiliary_selected_parents','auxiliary_limited_parent_steps', ...
    'auxiliary_parent_step_scale_median'};
rows = cell(0,numel(names)); runRows = cell(height(runs),numel(runNames));
for i = 1:height(runs)
    relative = strrep(char(runs.mat_file(i)),char(92),filesep);
    relative = strrep(relative,'/',filesep);
    loaded = load(fullfile(outputRoot,char(runs.result_directory(i)),relative), ...
        'injectionLog','BI');
    rawAll=[]; actualAll=[]; relativeAll=[]; retentionAll=[]; scalesAll=[];
    totals = zeros(1,6);
    for j = 1:numel(loaded.injectionLog)
        e = loaded.injectionLog(j);
        raw = e.auxiliary_raw_distance_to_prediction(:);
        actual = e.auxiliary_actual_distance_to_prediction(:);
        relativeDistance = e.auxiliary_relative_distance_to_cma_scale(:);
        retention = NaN(size(raw));
        nonzero = raw > 0;
        retention(nonzero) = actual(nonzero)./raw(nonzero);
        upperRepaired = sum(any(e.auxiliary_boundary_repaired(:, ...
            1:loaded.BI.u_dim),2));
        jointRepaired = sum(any(e.auxiliary_boundary_repaired,2));
        directRepaired = sum(e.direct_boundary_repaired);
        auxiliaryParents = strcmp(e.selected_parent_sources(:),'predicted_auxiliary');
        parentScales = e.parent_step_scales(:);
        assert(numel(parentScales)==numel(auxiliaryParents), ...
            'Parent-step diagnostics have inconsistent dimensions.');
        auxScales = parentScales(auxiliaryParents);
        selected = sum(auxiliaryParents); limited = sum(auxScales < 1);
        counts = [numel(raw),upperRepaired,jointRepaired,directRepaired,selected,limited];
        totals = totals + counts;
        rawAll = [rawAll;raw]; actualAll = [actualAll;actual]; %#ok<AGROW>
        relativeAll = [relativeAll;relativeDistance]; %#ok<AGROW>
        retentionAll = [retentionAll;retention]; scalesAll = [scalesAll;auxScales]; %#ok<AGROW>
        rows(end+1,:) = {runs.SMD(i),char(runs.variant(i)), ...
            runs.run_no(i),runs.seed(i),runs.auxiliary_sampling_scale(i), ...
            j,e.UFE,numel(raw),finiteMedian(raw),finiteMedian(actual), ...
            finiteMedian(relativeDistance),finiteMedian(retention), ...
            upperRepaired,jointRepaired,directRepaired,selected,limited, ...
            finiteMedian(auxScales)}; %#ok<AGROW>
    end
    runRows(i,:) = {runs.SMD(i),char(runs.variant(i)),runs.run_no(i), ...
        runs.seed(i),runs.auxiliary_sampling_scale(i),totals(1), ...
        finiteMedian(rawAll),finiteMedian(actualAll),finiteMedian(relativeAll), ...
        finiteMedian(retentionAll),totals(2),totals(3),totals(4), ...
        totals(5),totals(6),finiteMedian(scalesAll)};
end
generations = cell2table(rows,'VariableNames',names);
runDiagnostics = cell2table(runRows,'VariableNames',runNames);
writetable(generations,fullfile(outputRoot,'auxiliary_scale_generation_diagnostics.csv'));
writetable(runDiagnostics,fullfile(outputRoot,'auxiliary_scale_run_diagnostics.csv'));
end

function value = finiteMedian(values)
values = values(isfinite(values));
if isempty(values), value=NaN; else, value=median(values); end
end
