function report = testSmallAuxiliaryScaleExperiment(outputRoot)
%TESTSMALLAUXILIARYSCALEEXPERIMENT Structural test of the small-eta study.
% It verifies the five branches, K3/A0 population layouts, matched normal
% draws, A0-referenced outcomes, and complete isolation of the main run.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 1 || isempty(outputRoot)
    outputRoot = fullfile(projectRoot, ...
        'results_nextgen_small_auxiliary_scale_tests','smoke_SMD1_R1');
end
experiment = runSMDSmallAuxiliaryScaleNextGenerationDiagnostic( ...
    outputRoot,1,1,1);
outcomes = experiment.outcomeTable;
updates = experiment.updateTable;
candidates = experiment.candidateTable;
completed = outcomes(outcomes.probe_completed ~= 0,:);
assert(~isempty(completed),'Small-eta smoke test did not complete a t+1 probe.');

expected = {'A0','eta_010','eta_015','eta_020','eta_025'};
assert(isequal(sort(unique(completed.variant))',sort(expected)), ...
    'The small-eta experiment did not produce the requested five branches.');
k3 = completed(strcmp(completed.candidate_policy,'K3'),:);
a0 = completed(strcmp(completed.candidate_policy,'A0'),:);
assert(all(k3.intervention_normal_count == 5 & ...
    k3.intervention_direct_count == 1 & k3.intervention_auxiliary_count == 2), ...
    'A K3 small-eta branch is not 5 normal + 1 direct + 2 auxiliary.');
assert(all(a0.intervention_normal_count == 8 & ...
    a0.intervention_direct_count == 0 & a0.intervention_auxiliary_count == 0), ...
    'The A0 branch is not an eight-normal-candidate original CMA-ES update.');
assert(all(a0.is_reference_variant ~= 0 & abs(a0.R_stable) < 1e-12 & ...
    abs(a0.raw_delta_Q) < 1e-12), ...
    'A0 is not recorded as the zero-response reference branch.');
assert(all(k3.probe_normal_count == 5 & a0.probe_normal_count == 5), ...
    'Every branch must evaluate five normal-only t+1 probe candidates.');

states = unique(k3(:,{'state_index','repeat_no'}),'rows');
expectedEtas = [.10;.15;.20;.25];
for i = 1:height(states)
    stateK3 = k3(k3.state_index == states.state_index(i) & ...
        k3.repeat_no == states.repeat_no(i),:);
    stateA0 = a0(a0.state_index == states.state_index(i) & ...
        a0.repeat_no == states.repeat_no(i),:);
    assert(height(stateK3) == 4 && ...
        all(abs(sort(stateK3.eta)-expectedEtas) < 1e-12) && height(stateA0) == 1, ...
        'A valid state lacks a matched four-scale K3 set or its A0 branch.');
    updatePart = updates(updates.state_index == states.state_index(i) & ...
        updates.repeat_no == states.repeat_no(i),:);
    assert(height(updatePart) == 5 && ...
        numel(unique(updatePart.upper_before_injection)) == 1, ...
        'The five branches did not reuse the same current-generation normal population.');
    a0Draws = candidates.standard_normal_draw( ...
        candidates.state_index == states.state_index(i) & ...
        candidates.repeat_no == states.repeat_no(i) & ...
        strcmp(candidates.variant,'A0'));
    for eta = expectedEtas'
        branchDraws = candidates.standard_normal_draw( ...
            candidates.state_index == states.state_index(i) & ...
            candidates.repeat_no == states.repeat_no(i) & ...
            abs(candidates.eta-eta) < 1e-12);
        assert(isequal(a0Draws,branchDraws), ...
            'A0 and a K3 scale branch used different t+1 normal directions.');
    end
end
assert(exist(fullfile(outputRoot,'nextgen_scale_vs_reference_wilcoxon.csv'), ...
    'file') == 2, 'The A0-reference statistical table was not written.');

% Re-run the uninstrumented K3 main trajectory.  The branch work must not
% alter its terminal state or its main UFE/LFE counters.
BI = getBLOPinfo('SMD',1,5);
BI.UmaxFEs=2500; BI.UmaxImprFEs=350; BI.LmaxFEs=250; BI.LmaxImprFEs=25;
BI.enablePredictionCorrection=false; BI.predictionCorrection=struct('logEnabled',false);
BI.enableIndividualPredictionCorrection=false;
BI.individualPredictionCorrection=struct('mode','A0','logEnabled',false);
BI.predictionInjection=struct('mode','K3','predictionInjectCount',3, ...
    'candidatePolicy','direct_plus_auxiliary', ...
    'auxiliarySamplingDistribution','cma_gaussian','auxiliarySamplingScale',.5, ...
    'predictionModelType','quadratic','logEnabled',true,'startGeneration',10, ...
    'historyGenerations',10,'useAllHistory',false,'sampleCount',40, ...
    'maxPredictionNormalizedDistance',Inf,'auxiliaryRandomSeed',500001, ...
    'randomSeed',1,'consistencyCheckEnabled',true);
rng(1,'twister'); baseline = BLCMAES(BI);
saved = load(fullfile(outputRoot,'SMD1_run001_main.mat'),'mainIns');
assert(baseline.UFEs == saved.mainIns.UFEs && ...
    baseline.LFEs == saved.mainIns.LFEs && ...
    abs(baseline.UF-saved.mainIns.UF) < 1e-12 && ...
    norm(baseline.UX-saved.mainIns.UX) < 1e-12, ...
    'Small-eta branch diagnostics changed the reference main trajectory.');

report = struct('outputRoot',outputRoot,'variants',{expected}, ...
    'completedK3States',height(k3)/4,'completedA0States',height(a0), ...
    'mainTrajectoryIsolated',true,'passed',true);
save(fullfile(outputRoot,'nextgen_small_scale_smoke_report.mat'),'report');
disp(report);
end
