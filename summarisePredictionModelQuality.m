function analysis = summarisePredictionModelQuality(details,outputRoot,settings)
%SUMMARISEPREDICTIONMODELQUALITY Independent-run, paired model comparisons.
% Generations are aggregated within a run before any inferential testing.
if isempty(details), error('No eligible t>=10 states with a real t+1 population.'); end
keys=unique(details(:,{'SMD','run_no','seed'}),'rows');
ids=["QP","CP","RBF","GPR","QP_analytic"];
if nargin<3, settings=struct(); end
if ~isfield(settings,'prefix'), settings.prefix='prediction_model'; end
if ~isfield(settings,'referenceId'), settings.referenceId='QP'; end
if isfield(settings,'modelIds'), ids=string(settings.modelIds); end
runRows=struct([]); stageRows=struct([]); pairRows=struct([]);
for k=1:height(keys)
    run=details(details.SMD==keys.SMD(k)&details.run_no==keys.run_no(k),:);
    for model=ids
        sub=run(run.model==model,:);
        if isempty(sub), continue; end
        runRows=append(runRows,oneRun(sub,0));
        for stage=1:3
            part=sub(sub.stage==stage,:);
            if ~isempty(part), stageRows=append(stageRows,oneRun(part,stage)); end
        end
    end
    for a=1:numel(ids)-1
        for b=a+1:numel(ids)
            A=run(run.model==ids(a),:); B=run(run.model==ids(b),:);
            if isempty(A)||isempty(B), continue; end
            assert(isequal(A.generation,B.generation),'Unpaired model opportunity rows.');
            pairRows=append(pairRows,onePair(A,B));
        end
    end
end
runSummary=struct2table(runRows); stageRun=struct2table(stageRows);
pairRun=struct2table(pairRows);
if isfield(settings,'plannedPairs')
    pairRun.family(:)="exploratory_refinement";
    for i=1:size(settings.plannedPairs,1)
        index=pairRun.reference_model==string(settings.plannedPairs{i,1}) & ...
            pairRun.variant_model==string(settings.plannedPairs{i,2});
        pairRun.family(index)="planned_refinement";
    end
end
summary=aggregateModels(runSummary,false);
stageSummary=aggregateModels(stageRun,true);
pairwise=aggregatePairs(pairRun);
for smd=unique(pairwise.SMD)'
    for family=unique(pairwise.family)'
        index=pairwise.SMD==smd & pairwise.family==family;
        pairwise.UF_delta_p_holm(index)=holm(pairwise.UF_delta_p_raw(index));
        pairwise.win_rate_p_holm(index)=holm(pairwise.win_rate_p_raw(index));
    end
end
pairwise.variant_UF_advantage=pairwise.UF_delta_p_holm<.05 & ...
    pairwise.median_run_UF_delta>0;
pairwise.reference_UF_advantage=pairwise.UF_delta_p_holm<.05 & ...
    pairwise.median_run_UF_delta<0;
analysis=struct('runSummary',runSummary,'summary',summary, ...
    'stageRunSummary',stageRun,'stageSummary',stageSummary, ...
    'pairwiseRun',pairRun,'pairwise',pairwise);
if ~strcmp(settings.referenceId,'QP')
    for name={'runSummary','summary','stageRunSummary','stageSummary'}
        T=analysis.(name{1});
        T.Properties.VariableNames=strrep(T.Properties.VariableNames,'_vs_QP',['_vs_' settings.referenceId]);
        analysis.(name{1})=T;
    end
end
writetable(analysis.runSummary,fullfile(outputRoot,[settings.prefix '_run_summary.csv']));
writetable(analysis.summary,fullfile(outputRoot,[settings.prefix '_summary.csv']));
writetable(analysis.stageRunSummary,fullfile(outputRoot,[settings.prefix '_stage_run_summary.csv']));
writetable(analysis.stageSummary,fullfile(outputRoot,[settings.prefix '_stage_summary.csv']));
writetable(pairRun,fullfile(outputRoot,[settings.prefix '_pairwise_run.csv']));
writetable(pairwise,fullfile(outputRoot,[settings.prefix '_pairwise.csv']));
end

function row=oneRun(D,stage)
valid=D.prediction_valid & D.evaluation_valid;
n=height(D); v=sum(valid);
row=struct('SMD',D.SMD(1),'run_no',D.run_no(1),'seed',D.seed(1), ...
    'model',D.model(1),'stage',stage,'opportunities',n,'fit_successes',sum(D.fit_success), ...
    'valid_predictions',sum(D.prediction_valid),'valid_evaluations',v, ...
    'fit_success_rate',sum(D.fit_success)/n,'valid_prediction_rate',sum(D.prediction_valid)/n, ...
    'valid_evaluation_rate',v/n,'effective_best_improvement_rate',sum(D.better_than_normal_best&valid)/n, ...
    'conditional_best_improvement_rate',conditional(D.better_than_normal_best,valid), ...
    'effective_median_improvement_rate',sum(D.better_than_normal_median&valid)/n, ...
    'conditional_median_improvement_rate',conditional(D.better_than_normal_median,valid), ...
    'effective_history_improvement_rate',sum(D.better_than_current_best&valid)/n, ...
    'conditional_history_improvement_rate',conditional(D.better_than_current_best,valid), ...
    'mean_rank',finiteMean(D.rank(valid)),'median_rank',finiteMedian(D.rank(valid)), ...
    'mean_normalized_rank',finiteMean(D.normalized_rank(valid)), ...
    'effective_parent_rate',sum(D.potential_parent&valid)/n, ...
    'conditional_parent_rate',conditional(D.potential_parent,valid), ...
    'normal_pair_win_rate',finiteMean(D.beats_normal_pair_rate(valid)), ...
    'mean_true_UF',finiteMean(D.true_UF(valid)),'median_true_UF',finiteMedian(D.true_UF(valid)), ...
    'mean_upper_error',finiteMean(D.upper_error(valid)), ...
    'median_upper_error',finiteMedian(D.upper_error(valid)), ...
    'mean_distance_to_optimum',finiteMean(D.distance_to_known_optimum(valid)), ...
    'median_distance_to_optimum',finiteMedian(D.distance_to_known_optimum(valid)), ...
    'mean_improvement_over_normal_best',finiteMean(D.improvement_over_normal_best(valid)), ...
    'median_improvement_vs_QP',finiteMedian(D.improvement_vs_QP(valid)), ...
    'lower_precision_rate',conditional(D.lower_precision_passed,valid), ...
    'median_lower_conditional_error',finiteMedian(D.lower_conditional_error(valid)), ...
    'search_boundary_rate',conditional(D.at_search_boundary,valid), ...
    'duplicate_history_rate',conditional(D.duplicate_history,valid), ...
    'mean_fit_seconds',mean(D.fit_seconds),'mean_search_seconds',mean(D.search_seconds), ...
    'total_fit_seconds',sum(D.fit_seconds),'total_search_seconds',sum(D.search_seconds), ...
    'total_true_evaluation_seconds',sum(D.true_evaluation_seconds), ...
    'extra_UFE',sum(D.extra_UFE),'extra_LFE',sum(D.extra_LFE), ...
    'first_valid_generation',firstValue(D.generation(valid)), ...
    'last_valid_generation',lastValue(D.generation(valid)), ...
    'gpr_mean_predicted_std',finiteMean(D.GPR_predicted_std(valid)));
end

function row=onePair(A,B)
validA=A.prediction_valid&A.evaluation_valid;
validB=B.prediction_valid&B.evaluation_valid; both=validA&validB;
delta=B.true_UF(both)-A.true_UF(both);
tolerance=1e-12*max(1,max(abs([A.true_UF(both),B.true_UF(both)]),[],2));
wins=delta>tolerance; losses=delta< -tolerance; ties=~wins&~losses;
distance=hypot(B.x_pred1(both)-A.x_pred1(both),B.x_pred2(both)-A.x_pred2(both));
reliable=both&A.lower_precision_passed&B.lower_precision_passed;
normalizedDelta=NaN(size(delta));
if ismember('normalized_refinement_scale',A.Properties.VariableNames)
    normalizedDelta=delta./A.normalized_refinement_scale(both);
end
family="fair_four_models";
if A.model(1)=="QP_analytic"||B.model(1)=="QP_analytic", family="analytic_reference"; end
row=struct('SMD',A.SMD(1),'run_no',A.run_no(1),'seed',A.seed(1), ...
    'reference_model',A.model(1),'variant_model',B.model(1),'family',family, ...
    'opportunities',height(A),'both_valid',sum(both),'reference_only_valid',sum(validA&~validB), ...
    'variant_only_valid',sum(validB&~validA),'both_invalid',sum(~validA&~validB), ...
    'variant_wins',sum(wins),'ties',sum(ties),'reference_wins',sum(losses), ...
    'conditional_variant_win_rate',finiteMean(double(wins)), ...
    'effective_variant_win_rate',sum(wins)/height(A), ...
    'mean_UF_delta',finiteMean(delta),'median_UF_delta',finiteMedian(delta), ...
    'mean_normalized_UF_delta',finiteMean(normalizedDelta), ...
    'median_normalized_UF_delta',finiteMedian(normalizedDelta), ...
    'median_pair_distance',finiteMedian(distance), ...
    'variant_good_when_reference_invalid',sum(validB&~validA&B.better_than_normal_best), ...
    'reference_good_when_variant_invalid',sum(validA&~validB&A.better_than_normal_best), ...
    'variant_good_when_reference_poor',sum(validB&validA&A.rank>A.mu&B.better_than_normal_best), ...
    'reference_good_when_variant_poor',sum(validA&validB&B.rank>B.mu&A.better_than_normal_best), ...
    'both_lower_accurate',sum(reliable), ...
    'reliable_median_UF_delta',finiteMedian(B.true_UF(reliable)-A.true_UF(reliable)));
end

function output=aggregateModels(T,byStage)
keys={'SMD','model'};
if byStage, keys{end+1}='stage'; end
groups=unique(T(:,keys),'rows'); result=struct([]);
metricNames=T.Properties.VariableNames;
skip={'SMD','run_no','seed','model','stage'};
metricNames=metricNames(~ismember(metricNames,skip));
for i=1:height(groups)
    index=T.SMD==groups.SMD(i)&T.model==groups.model(i);
    if byStage, index=index&T.stage==groups.stage(i); end
    sub=T(index,:); row=struct('SMD',groups.SMD(i),'model',groups.model(i));
    if byStage, row.stage=groups.stage(i); end
    row.independent_runs=height(sub);
    row.total_opportunities=sum(sub.opportunities);
    row.total_valid_predictions=sum(sub.valid_predictions);
    row.total_valid_evaluations=sum(sub.valid_evaluations);
    row.total_extra_UFE=sum(sub.extra_UFE); row.total_extra_LFE=sum(sub.extra_LFE);
    for name=metricNames
        values=sub.(name{1}); values=values(isfinite(values));
        row.([name{1} '_mean'])=finiteMean(values);
        row.([name{1} '_median'])=finiteMedian(values);
        row.([name{1} '_std'])=finiteStd(values);
        if isempty(values), row.([name{1} '_IQR'])=NaN;
        else, row.([name{1} '_IQR'])=iqr(values); end
    end
    result=append(result,row);
end
output=struct2table(result);
end

function output=aggregatePairs(T)
keys=unique(T(:,{'SMD','reference_model','variant_model','family'}),'rows');
rows=struct([]);
for i=1:height(keys)
    sub=T(T.SMD==keys.SMD(i)&T.reference_model==keys.reference_model(i)& ...
        T.variant_model==keys.variant_model(i),:);
    delta=sub.median_UF_delta;
    row=struct('SMD',keys.SMD(i),'reference_model',keys.reference_model(i), ...
        'variant_model',keys.variant_model(i),'family',keys.family(i), ...
        'independent_runs',height(sub),'paired_runs',sum(isfinite(delta)), ...
        'total_opportunities',sum(sub.opportunities),'both_valid',sum(sub.both_valid), ...
        'reference_only_valid',sum(sub.reference_only_valid), ...
        'variant_only_valid',sum(sub.variant_only_valid), ...
        'variant_wins',sum(sub.variant_wins),'ties',sum(sub.ties), ...
        'reference_wins',sum(sub.reference_wins), ...
        'mean_run_conditional_variant_win_rate',finiteMean(sub.conditional_variant_win_rate), ...
        'mean_run_effective_variant_win_rate',finiteMean(sub.effective_variant_win_rate), ...
        'median_run_UF_delta',finiteMedian(delta),'mean_run_UF_delta',finiteMean(delta), ...
        'median_run_normalized_UF_delta',finiteMedian(sub.median_normalized_UF_delta), ...
        'median_run_pair_distance',finiteMedian(sub.median_pair_distance), ...
        'variant_good_when_reference_invalid',sum(sub.variant_good_when_reference_invalid), ...
        'reference_good_when_variant_invalid',sum(sub.reference_good_when_variant_invalid), ...
        'variant_good_when_reference_poor',sum(sub.variant_good_when_reference_poor), ...
        'reference_good_when_variant_poor',sum(sub.reference_good_when_variant_poor), ...
        'both_lower_accurate',sum(sub.both_lower_accurate), ...
        'median_run_reliable_UF_delta',finiteMedian(sub.reliable_median_UF_delta), ...
        'UF_delta_p_raw',pairedP(delta),'UF_delta_p_holm',NaN, ...
        'win_rate_p_raw',pairedP(sub.conditional_variant_win_rate-.5), ...
        'win_rate_p_holm',NaN,'variant_UF_advantage',false,'reference_UF_advantage',false);
    rows=append(rows,row);
end
output=struct2table(rows);
end

function p=pairedP(delta)
delta=delta(isfinite(delta));
if numel(delta)<3, p=NaN;
elseif all(delta==0), p=1;
else, p=signrank(delta,0,'method','exact'); end
end

function corrected=holm(values)
corrected=NaN(size(values)); good=find(isfinite(values));
[sorted,order]=sort(values(good)); n=numel(sorted);
adjusted=min(1,cummax((n-(1:n)'+1).*sorted(:)));
corrected(good(order))=adjusted;
end

function rows=append(rows,row)
if isempty(rows), rows=row; else, rows(end+1,1)=row; end
end
function y=conditional(values,index)
if ~any(index), y=NaN; else, y=mean(values(index)); end
end
function y=finiteMean(x)
x=x(isfinite(x)); if isempty(x), y=NaN; else, y=mean(x); end
end
function y=finiteMedian(x)
x=x(isfinite(x)); if isempty(x), y=NaN; else, y=median(x); end
end
function y=finiteStd(x)
x=x(isfinite(x)); if isempty(x), y=NaN; else, y=std(x); end
end
function y=firstValue(x)
if isempty(x), y=NaN; else, y=x(1); end
end
function y=lastValue(x)
if isempty(x), y=NaN; else, y=x(end); end
end
