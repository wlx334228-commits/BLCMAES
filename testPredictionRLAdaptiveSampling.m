function report = testPredictionRLAdaptiveSampling(outputDir)
%TESTPREDICTIONRLADAPTIVESAMPLING Non-evaluating and short integration checks.
% It verifies the 5+1+2 layout, private-RNG isolation, bounded actions,
% trace-normalised covariance construction, mode-specific fixed actions,
% and that one post-evaluation actor update is made for one shared action.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(projectRoot,'results_prediction_rl_adaptive_sampling_tests', ...
        datestr(now,'yyyymmdd_HHMMSS'));
end
if exist(outputDir,'dir') ~= 7, mkdir(outputDir); end
BI = getBLOPinfo('SMD',1,5);
[CMA,rawUpper,rawLower] = syntheticCMA(BI);
model = syntheticQuadraticModel(CMA.xmean(1:2));
modes = {'eta_only','delta_only','joint'};
% Preallocate the actual report fields.  MATLAB cannot assign a populated
% scalar struct into an array created as repmat(struct(),...), because that
% array has zero fields.
checks = repmat(struct('mode','','eta',NaN,'delta',NaN, ...
    'trace_ratio',NaN,'reward',NaN,'actor_step',NaN, ...
    'candidate_entry',struct()),numel(modes),1);
for i = 1:numel(modes)
    options = rlOptions(BI,modes{i},600000+i);
    state = initializePredictionInjectionState(BI,options);
    state.pending = struct('valid',true,'x_pred',model.x_pred, ...
        'source_generation',10,'model',model);
    rngBefore = rng;
    [upper,lower,entry,state] = applyPredictionInjection(CMA,rawUpper, ...
        rawLower,11,BI,options,state);
    assert(isequal(rngBefore,rng), ...
        'RL action selection or auxiliary sampling changed the global RNG.');
    assert(entry.rl_action_valid && entry.prediction_valid_used, ...
        ['RL action was safely rejected. action reason: %s; ' ...
         'injection reason: %s'],entry.rl_action_reason,entry.injection_reason);
    assert(sum(strcmp(entry.source_labels,'normal')) == 5 && ...
        sum(strcmp(entry.source_labels,'predicted_direct')) == 1 && ...
        sum(strcmp(entry.source_labels,'predicted_auxiliary')) == 2, ...
        'RL candidate composition is not 5 normal + 1 direct + 2 auxiliary.');
    assert(isequal(upper(1:5,:),rawUpper(1:5,:)) && ...
        isequal(lower(1:5,:),rawLower(1:5,:)) && ...
        norm(upper(6,:)-model.x_pred) < 1e-12, ...
        'RL changed normal candidates or failed to use the direct prediction.');
    cmaTrace = trace(CMA.sigma^2*CMA.C(1:2,1:2));
    assert(abs(trace(entry.rl_covariance)-entry.rl_eta^2*cmaTrace) / ...
        max(cmaTrace,eps) < 1e-10, ...
        'RL covariance is not trace-normalised before eta scaling.');
    assert(entry.rl_eta >= options.rlEtaMin && entry.rl_eta <= options.rlEtaMax && ...
        abs(entry.rl_delta) <= options.rlDeltaMax+eps && ...
        all(eig(entry.rl_covariance)>0), ...
        'RL action bounds or covariance positive definiteness failed.');
    if strcmp(modes{i},'eta_only')
        assert(entry.rl_eta_learned && ~entry.rl_delta_learned && ...
            abs(entry.rl_delta) < 1e-12, ...
            'RL-1 must learn eta only and retain delta=0.');
    elseif strcmp(modes{i},'delta_only')
        assert(~entry.rl_eta_learned && entry.rl_delta_learned && ...
            abs(entry.rl_eta-options.rlFixedEta) < 1e-12, ...
            'RL-2 must retain fixed eta and learn delta only.');
    else
        assert(entry.rl_eta_learned && entry.rl_delta_learned, ...
            'RL-3 must learn eta and delta jointly.');
    end
    % Fabricated already-evaluated UF values drive only the post-evaluation
    % unit test; they are not a call to an SMD objective.
    entry.upper_objective_after_true_evaluation = [1;2;3;4;5;6;8;7];
    entry.direct_better_than_normal_pair_rate = 0.8;
    [state.rlState,update] = updatePredictionRLActor( ...
        state.rlState,entry,5.5,BI,options);
    assert(update.updated && update.actor_step_after == ...
        update.actor_step_before+1 && isfinite(update.reward), ...
        'One valid RL decision did not produce exactly one REINFORCE update.');
    checks(i) = struct('mode',modes{i},'eta',entry.rl_eta, ...
        'delta',entry.rl_delta,'trace_ratio',entry.rl_covariance_trace_ratio, ...
        'reward',update.reward,'actor_step',update.actor_step_after, ...
        'candidate_entry',entry);
end

% A malformed covariance/prediction action must safely keep all normal
% candidates; no mixed population is ever evaluated.
options = rlOptions(BI,'joint',700001);
state = initializePredictionInjectionState(BI,options);
state.pending = struct('valid',true,'x_pred',model.x_pred, ...
    'source_generation',10,'model',model);
badCMA = CMA; badCMA.C(1:2,1:2) = diag([1,0]);
[fallbackUpper,fallbackLower,fallbackEntry] = applyPredictionInjection( ...
    badCMA,rawUpper,rawLower,11,BI,options,state);
assert(isequal(fallbackUpper,rawUpper) && isequal(fallbackLower,rawLower) && ...
    all(strcmp(fallbackEntry.source_labels,'normal')) && ...
    strcmp(fallbackEntry.injection_reason,'rl_action_failed_normal_fallback'), ...
    'Invalid RL state did not use the all-normal safe fallback.');

report = struct('passed',true,'checks',checks, ...
    'fallback_entry',fallbackEntry,'integration',shortIntegration(BI));
save(fullfile(outputDir,'prediction_rl_adaptive_sampling_test_report.mat'), ...
    'report');
disp(report);
end

function [CMA,rawUpper,rawLower] = syntheticCMA(BI)
base = [1.0 0.2 0.1 0.0 0.0;0.4 1.1 0.0 0.1 0.0; ...
    0.2 0.1 1.0 0.0 0.1;0.0 0.2 0.1 0.9 0.0;0.1 0.0 0.2 0.1 0.8];
C = base*base'; [B,values] = eig(C);
CMA = struct('xmean',(BI.xrange(1,:)+BI.xrange(2,:))/2,'sigma',0.02, ...
    'C',C,'B',B,'D',sqrt(diag(values))');
rawUpper = repmat(CMA.xmean(1:2),8,1);
rawLower = repmat(CMA.xmean(3:end),8,1);
end

function model = syntheticQuadraticModel(center)
angle = 28*pi/180; R = [cos(angle),-sin(angle);sin(angle),cos(angle)];
model = struct('modelType','quadratic','valid',true,'H', ...
    -R*diag([0.6,5])*R','scale',0.4,'x_pred',center, ...
    'predictionToNearestSample',0.1);
end

function options = rlOptions(BI,mode,seed)
BItest = BI;
BItest.predictionInjection = struct('mode','K3','predictionInjectCount',3, ...
    'candidatePolicy','direct_plus_auxiliary', ...
    'auxiliarySamplingDistribution','rl_adaptive_gaussian', ...
    'auxiliarySamplingScale',1.0,'predictionModelType','quadratic', ...
    'logEnabled',true,'startGeneration',10,'historyGenerations',10, ...
    'sampleCount',40,'auxiliaryRandomSeed',seed,'rlRandomSeed',seed+100, ...
    'rlEnabled',true,'rlMode',mode,'rlFixedEta',0.5, ...
    'consistencyCheckEnabled',true);
options = predictionInjectionOptions(BItest);
end

function integration = shortIntegration(BI)
BIrun = BI; BIrun.UmaxFEs = 128; BIrun.UmaxImprFEs = 350;
BIrun.LmaxFEs = 250; BIrun.LmaxImprFEs = 25; BIrun.u_ftol = 0;
BIrun.enablePredictionCorrection = false;
BIrun.enableIndividualPredictionCorrection = false;
BIrun.predictionInjection = struct('mode','K3','predictionInjectCount',3, ...
    'candidatePolicy','direct_plus_auxiliary', ...
    'auxiliarySamplingDistribution','rl_adaptive_gaussian', ...
    'predictionModelType','quadratic','logEnabled',true, ...
    'startGeneration',10,'historyGenerations',10,'sampleCount',40, ...
    'auxiliaryRandomSeed',810001,'rlRandomSeed',810101,'randomSeed',321, ...
    'rlEnabled',true,'rlMode','joint','rlFixedEta',0.5, ...
    'consistencyCheckEnabled',true);
rng(321,'twister'); ins = BLCMAES(BIrun); log = ins.predictionInjectionLog;
assert(all(arrayfun(@(item) isequal(item.upper_entering_lower_search, ...
    item.upper_after_injection),log)), ...
    'RL integration failed evaluation-position consistency.');
for i = 1:numel(log)
    item = log(i);
    if item.mean_update_applied
        assert(item.consistency_checked && item.consistency_passed, ...
            'RL integration failed CMA update consistency.');
    end
end
integration = struct('UFE',ins.UFEs,'LFE',ins.LFEs, ...
    'action_generations',sum([log.rl_action_valid]), ...
    'actor_updates',sum([log.rl_actor_updated]));
end
