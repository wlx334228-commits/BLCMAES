function [summary,pairedTests,pairs] = comparePredictionInjectionPolicies( ...
    directOutputRoot,auxiliaryOnlyOutputRoot,outputDir)
%COMPAREPREDICTIONINJECTIONPOLICIES Compare direct and auxiliary-only K runs.
% Both input directories must come from runSMDPredictionInjection with the
% same SMD set, K set, number of runs, and paired seed definition.  The
% direct directory uses candidatePolicy='direct_plus_auxiliary'; the other
% uses candidatePolicy='auxiliary_only'.  K=0 is deliberately excluded from
% the statistical comparison because both policies are identical there.
%
% Example
%   comparePredictionInjectionPolicies( ...
%       'results_prediction_injection_K/20261028_174042', ...
%       'results_prediction_auxiliary_only_K/20261029_120000')

if nargin < 2 || isempty(directOutputRoot) || isempty(auxiliaryOnlyOutputRoot)
    error('BLCMAES:PolicyComparison', ...
        'Specify the completed direct and auxiliary-only result directories.');
end
if nargin < 3 || isempty(outputDir)
    outputDir = fullfile(auxiliaryOnlyOutputRoot,'comparison_with_direct');
end
assert(exist(directOutputRoot,'dir') == 7, ...
    'Missing direct result directory: %s',directOutputRoot);
assert(exist(auxiliaryOnlyOutputRoot,'dir') == 7, ...
    'Missing auxiliary-only result directory: %s',auxiliaryOnlyOutputRoot);
assert(exist(outputDir,'file') ~= 2, ...
    'Comparison output path is an existing file: %s',outputDir);
if ~exist(outputDir,'dir'), mkdir(outputDir); end

directRuns = readRunTable(directOutputRoot);
auxiliaryRuns = readRunTable(auxiliaryOnlyOutputRoot);
assertPolicy(directOutputRoot,'direct_plus_auxiliary',true);
assertPolicy(auxiliaryOnlyOutputRoot,'auxiliary_only',false);

commonSMD = intersect(unique(directRuns.SMD)',unique(auxiliaryRuns.SMD)');
commonK = setdiff(intersect(unique(directRuns.prediction_inject_count)', ...
    unique(auxiliaryRuns.prediction_inject_count)'),0);
assert(~isempty(commonSMD) && ~isempty(commonK), ...
    'The two experiment directories have no common SMD/K=1,...,8 runs.');

pairNames = {'SMD','K','run_no','seed','direct_upper_error', ...
    'auxiliary_upper_error','direct_lower_error','auxiliary_lower_error', ...
    'direct_upper_success','auxiliary_upper_success', ...
    'direct_lower_success','auxiliary_lower_success','direct_UFE', ...
    'auxiliary_UFE','direct_LFE','auxiliary_LFE'};
pairRows = cell(0,numel(pairNames));
for smdNo = commonSMD(:)'
    for K = commonK(:)'
        directSubset = directRuns(directRuns.SMD == smdNo & ...
            directRuns.prediction_inject_count == K,:);
        auxiliarySubset = auxiliaryRuns(auxiliaryRuns.SMD == smdNo & ...
            auxiliaryRuns.prediction_inject_count == K,:);
        assert(isequal(sort(directSubset.run_no),sort(auxiliarySubset.run_no)), ...
            ['SMD%d K%d has different completed run numbers in the two ' ...
             'directories. Finish or resume both experiments before ' ...
             'performing a paired comparison.'],smdNo,K);
        commonRuns = intersect(directSubset.run_no,auxiliarySubset.run_no);
        for runNo = commonRuns(:)'
            directRow = directSubset(directSubset.run_no == runNo,:);
            auxiliaryRow = auxiliarySubset(auxiliarySubset.run_no == runNo,:);
            assert(height(directRow) == 1 && height(auxiliaryRow) == 1, ...
                'Duplicate SMD%d K%d run %d rows.',smdNo,K,runNo);
            assert(directRow.seed == auxiliaryRow.seed, ...
                ['SMD%d K%d run %d does not use a paired seed: ' ...
                 'direct=%d, auxiliary-only=%d.'], ...
                smdNo,K,runNo,directRow.seed,auxiliaryRow.seed);
            pairRows(end+1,:) = {smdNo,K,runNo,directRow.seed, ...
                directRow.upper_error,auxiliaryRow.upper_error, ...
                directRow.lower_error,auxiliaryRow.lower_error, ...
                directRow.upper_success,auxiliaryRow.upper_success, ...
                directRow.lower_success,auxiliaryRow.lower_success, ...
                directRow.UFE,auxiliaryRow.UFE, ...
                directRow.LFE_total,auxiliaryRow.LFE_total}; %#ok<AGROW>
        end
    end
end
pairs = cell2table(pairRows,'VariableNames',pairNames);
pairs = sortrows(pairs,{'SMD','K','run_no'});

[summary,pairedTests] = summarisePairs(pairs);
writetable(pairs,fullfile(outputDir,'direct_vs_auxiliary_only_runs.csv'));
writetable(summary,fullfile(outputDir,'direct_vs_auxiliary_only_summary.csv'));
writetable(pairedTests, ...
    fullfile(outputDir,'direct_vs_auxiliary_only_wilcoxon.csv'));
save(fullfile(outputDir,'direct_vs_auxiliary_only.mat'), ...
    'pairs','summary','pairedTests','directOutputRoot','auxiliaryOnlyOutputRoot');
fprintf('Direct-versus-auxiliary-only comparison saved in %s\n',outputDir);
end

function runs = readRunTable(outputRoot)
runFile = fullfile(outputRoot,'injection_runs.csv');
assert(exist(runFile,'file') == 2,'Missing run table: %s',runFile);
runs = readtable(runFile);
required = {'SMD','prediction_inject_count','run_no','seed','upper_error', ...
    'lower_error','upper_success','lower_success','UFE','LFE_total'};
assert(all(ismember(required,runs.Properties.VariableNames)), ...
    'Run table %s does not have the required prediction-injection columns.',runFile);
end

function assertPolicy(outputRoot,expectedPolicy,allowMissingLegacyField)
configFile = fullfile(outputRoot,'experiment_config.mat');
assert(exist(configFile,'file') == 2, ...
    'Missing experiment configuration: %s',configFile);
loaded = load(configFile,'config');
assert(isfield(loaded,'config'),'Configuration file has no config struct: %s',configFile);
if ~isfield(loaded.config,'candidatePolicy')
    assert(allowMissingLegacyField, ...
        'Auxiliary-only directory has no candidatePolicy metadata.');
    actualPolicy = 'direct_plus_auxiliary';
else
    actualPolicy = normaliseCandidatePolicy(loaded.config.candidatePolicy);
end
assert(strcmp(actualPolicy,expectedPolicy), ...
    'Expected %s policy in %s, found %s.', ...
    expectedPolicy,outputRoot,actualPolicy);
end

function [summary,tests] = summarisePairs(pairs)
summaryNames = {'SMD','K','paired_runs', ...
    'direct_upper_error_median','auxiliary_upper_error_median', ...
    'direct_lower_error_median','auxiliary_lower_error_median', ...
    'direct_upper_successes','auxiliary_upper_successes', ...
    'direct_upper_success_rate','auxiliary_upper_success_rate', ...
    'direct_lower_successes','auxiliary_lower_successes', ...
    'direct_lower_success_rate','auxiliary_lower_success_rate', ...
    'direct_UFE_median','auxiliary_UFE_median', ...
    'direct_LFE_median','auxiliary_LFE_median'};
testNames = {'SMD','K','paired_runs','upper_error_p','lower_error_p', ...
    'UFE_p','LFE_p','test_method','upper_error_p_holm', ...
    'lower_error_p_holm','UFE_p_holm','LFE_p_holm', ...
    'auxiliary_upper_error_advantage','auxiliary_lower_error_advantage', ...
    'auxiliary_UFE_advantage','auxiliary_LFE_advantage'};
summaryRows = cell(0,numel(summaryNames));
testRows = cell(0,numel(testNames));
for smdNo = unique(pairs.SMD)'
    for K = unique(pairs.K(pairs.SMD == smdNo))'
        rows = pairs(pairs.SMD == smdNo & pairs.K == K,:);
        upper = pairedWilcoxonSignedRank( ...
            rows.auxiliary_upper_error,rows.direct_upper_error);
        lower = pairedWilcoxonSignedRank( ...
            rows.auxiliary_lower_error,rows.direct_lower_error);
        ufe = pairedWilcoxonSignedRank(rows.auxiliary_UFE,rows.direct_UFE);
        lfe = pairedWilcoxonSignedRank(rows.auxiliary_LFE,rows.direct_LFE);
        summaryRows(end+1,:) = {smdNo,K,height(rows), ...
            median(rows.direct_upper_error),median(rows.auxiliary_upper_error), ...
            median(rows.direct_lower_error),median(rows.auxiliary_lower_error), ...
            sum(rows.direct_upper_success),sum(rows.auxiliary_upper_success), ...
            mean(rows.direct_upper_success),mean(rows.auxiliary_upper_success), ...
            sum(rows.direct_lower_success),sum(rows.auxiliary_lower_success), ...
            mean(rows.direct_lower_success),mean(rows.auxiliary_lower_success), ...
            median(rows.direct_UFE),median(rows.auxiliary_UFE), ...
            median(rows.direct_LFE),median(rows.auxiliary_LFE)}; %#ok<AGROW>
        testRows(end+1,:) = {smdNo,K,height(rows),upper.p,lower.p,ufe.p,lfe.p, ...
            upper.method,NaN,NaN,NaN,NaN,false,false,false,false}; %#ok<AGROW>
    end
end
summary = cell2table(summaryRows,'VariableNames',summaryNames);
tests = cell2table(testRows,'VariableNames',testNames);
tests = applyHolmAndAdvantages(tests,summary);
end

function tests = applyHolmAndAdvantages(tests,summary)
for smdNo = unique(tests.SMD)'
    index = tests.SMD == smdNo;
    tests.upper_error_p_holm(index) = holmAdjust(tests.upper_error_p(index));
    tests.lower_error_p_holm(index) = holmAdjust(tests.lower_error_p(index));
    tests.UFE_p_holm(index) = holmAdjust(tests.UFE_p(index));
    tests.LFE_p_holm(index) = holmAdjust(tests.LFE_p(index));
end
for i = 1:height(tests)
    row = summary(summary.SMD == tests.SMD(i) & summary.K == tests.K(i),:);
    noUpperSuccessLoss = row.auxiliary_upper_successes >= ...
        row.direct_upper_successes;
    tests.auxiliary_upper_error_advantage(i) = ...
        tests.upper_error_p_holm(i) < 0.05 && ...
        row.auxiliary_upper_error_median < row.direct_upper_error_median;
    tests.auxiliary_lower_error_advantage(i) = ...
        tests.lower_error_p_holm(i) < 0.05 && ...
        row.auxiliary_lower_error_median < row.direct_lower_error_median;
    tests.auxiliary_UFE_advantage(i) = tests.UFE_p_holm(i) < 0.05 && ...
        noUpperSuccessLoss && row.auxiliary_UFE_median < row.direct_UFE_median;
    tests.auxiliary_LFE_advantage(i) = tests.LFE_p_holm(i) < 0.05 && ...
        noUpperSuccessLoss && row.auxiliary_LFE_median < row.direct_LFE_median;
end
end

function adjusted = holmAdjust(pValues)
adjusted = NaN(size(pValues));
valid = find(isfinite(pValues));
if isempty(valid), return; end
[orderedValues,order] = sort(pValues(valid));
count = numel(orderedValues);
adjustedOrdered = NaN(count,1);
previous = 0;
for i = 1:count
    previous = max(previous,min(1,(count-i+1)*orderedValues(i)));
    adjustedOrdered(i) = previous;
end
adjusted(valid(order)) = adjustedOrdered;
end

function policy = normaliseCandidatePolicy(policy)
if isstring(policy), policy = char(policy); end
validateattributes(policy,{'char'},{'row'});
policy = lower(strtrim(policy));
switch policy
    case {'direct_plus_auxiliary','direct_plus_aux','direct'}
        policy = 'direct_plus_auxiliary';
    case {'auxiliary_only','aux_only'}
        policy = 'auxiliary_only';
    otherwise
        error('BLCMAES:PolicyComparison', ...
            'Unknown candidate policy: %s',policy);
end
end
