function report = testPredictionScaleStageDiagnostic(outputDir)
%TESTPREDICTIONSCALESTAGEDIAGNOSTIC Verify paired, isolated diagnostics.
% This smoke test performs one short F050 run and then evaluates diagnostics
% only after that run has ended.  It verifies that no diagnostic operation
% changes the finished main trajectory, its counters, or MATLAB's global RNG.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(projectRoot,'results_prediction_scale_stage_diagnostic_tests', ...
        datestr(now,'yyyymmdd_HHMMSS'));
end
if exist(outputDir,'dir') ~= 7, mkdir(outputDir); end
BI = getBLOPinfo('SMD',1,5);
synthetic = syntheticState(BI);
etas = [0.25 0.5 0.75 1.0];
z = [0.5 -1.0;-0.75 0.25];
samples = generatePredictionScaleDiagnosticCandidates(synthetic,etas,z);
verifyPairing(samples,etas,z,synthetic);
boundaryState = synthetic;
boundaryState.x_pred = BI.u_ub;
boundarySamples = generatePredictionScaleDiagnosticCandidates( ...
    boundaryState,1.0,[100 100;-100 -100]);
assert(any([boundarySamples.boundary_repaired]) && ...
    all(cellfun(@(x) all(x <= BI.u_ub), ...
    {boundarySamples.actual_upper})), ...
    'Diagnostic boundary repair did not retain candidates within upper bounds.');

% Short real main run.  The usual F050 main policy and all original search
% components remain in force; only its budget is shortened for smoke speed.
BIrun = BI;
% Leave enough post-generation-10 opportunities for a valid negative-
% definite quadratic fit; this is still a short one-run smoke test rather
% than a formal experiment.
BIrun.UmaxFEs = 256; BIrun.UmaxImprFEs = 1000;
BIrun.LmaxFEs = 50; BIrun.LmaxImprFEs = 20; BIrun.u_ftol = 0;
BIrun.enablePredictionCorrection = false;
BIrun.enableIndividualPredictionCorrection = false;
BIrun.predictionInjection = struct('mode','K3','predictionInjectCount',3, ...
    'candidatePolicy','direct_plus_auxiliary', ...
    'auxiliarySamplingDistribution','cma_gaussian', ...
    'auxiliarySamplingScale',0.5,'predictionModelType','quadratic', ...
    'logEnabled',true,'startGeneration',10,'historyGenerations',10, ...
    'sampleCount',40,'auxiliaryRandomSeed',731001,'randomSeed',731, ...
    'consistencyCheckEnabled',true);
rng(731,'twister');
ins = BLCMAES(BIrun);
logBeforeDiagnostic = ins.predictionInjectionLog;
rngAfterMain = rng;
[states,selection] = selectPredictionScaleStageStates(logBeforeDiagnostic,BIrun);
assert(~isempty(states), ...
    'The short smoke run did not reach any valid quadratic prediction state.');
validLog = logBeforeDiagnostic([logBeforeDiagnostic.prediction_valid_used]);
assert(all(arrayfun(@(entry) sum(strcmp(entry.source_labels,'normal')) == 5 && ...
    sum(strcmp(entry.source_labels,'predicted_direct')) == 1 && ...
    sum(strcmp(entry.source_labels,'predicted_auxiliary')) == 2,validLog)), ...
    'The F050 main population is not 5 normal + 1 direct + 2 auxiliary.');
assert(all([validLog.UFE_before_sampling] <= [validLog.UFE]), ...
    'The pre-sampling UFE snapshot was not recorded correctly.');

global ulFunctionEvaluations llFunctionEvaluations;
UFEafterMain = ulFunctionEvaluations; LFEafterMain = llFunctionEvaluations;
[diagnosticRows,totals] = evaluatePredictionScaleDiagnosticState(states(1), ...
    BIrun,1,1,731,etas);
assert(numel(diagnosticRows) == 8 && totals.candidate_count == 8, ...
    'A state must create exactly four eta values times two candidates.');
assert(isequal(rngAfterMain,rng), ...
    'Offline diagnostic sampling or lower search changed MATLAB global RNG.');
assert(ulFunctionEvaluations == UFEafterMain && ...
    llFunctionEvaluations == LFEafterMain, ...
    'Diagnostic evaluations leaked into the finished main UFE/LFE counters.');
assert(isequaln(ins.predictionInjectionLog,logBeforeDiagnostic), ...
    'Diagnostic evaluation modified an already completed main trajectory.');
assert(all([diagnosticRows.z_seed] == diagnosticRows(1).z_seed), ...
    'Different eta values did not share the same z seed for one state.');
assert(all([diagnosticRows.x_pred_1] == diagnosticRows(1).x_pred_1) && ...
    all([diagnosticRows.x_pred_2] == diagnosticRows(1).x_pred_2) && ...
    all([diagnosticRows.sigma] == diagnosticRows(1).sigma) && ...
    all([diagnosticRows.Cuu_11] == diagnosticRows(1).Cuu_11) && ...
    all([diagnosticRows.Cuu_12] == diagnosticRows(1).Cuu_12) && ...
    all([diagnosticRows.Cuu_22] == diagnosticRows(1).Cuu_22), ...
    'The diagnostic state changed its prediction point or covariance across eta.');
for candidateIndex = 1:2
    subset = diagnosticRows([diagnosticRows.candidate_index] == candidateIndex);
    assert(numel(unique([subset.lower_random_seed])) == 1, ...
        'The same candidate index must reuse lower-level randomness across eta.');
end
report = struct('passed',true,'synthetic_samples',samples, ...
    'main_UFE',ins.UFEs,'main_LFE',ins.LFEs,'selection',selection, ...
    'selected_state',states(1),'diagnostic_rows',diagnosticRows, ...
    'diagnostic_totals',totals);
save(fullfile(outputDir,'prediction_scale_stage_diagnostic_test_report.mat'), ...
    'report','-v7');
disp(report);
end

function state = syntheticState(BI)
base = [1.0 0.2 0.1 0.0 0.0;0.4 1.1 0.0 0.1 0.0; ...
    0.2 0.1 1.0 0.0 0.1;0.0 0.2 0.1 0.9 0.0;0.1 0.0 0.2 0.1 0.8];
C = base*base';
state = struct('x_pred',[0 0],'C',C,'sigma',0.2, ...
    'u_lb',BI.u_lb,'u_ub',BI.u_ub);
end

function verifyPairing(samples,etas,z,state)
for etaIndex = 1:numel(etas)
    eta = etas(etaIndex);
    subset = samples(abs([samples.eta]-eta) < 1e-12);
    assert(numel(subset) == 2 && isequal([subset.z],reshape(z',1,[])), ...
        'Every eta must use exactly the same two standard-normal vectors.');
    for candidateIndex = 1:2
        reference = samples(candidateIndex);
        item = subset(candidateIndex);
        % The first two rows are the eta=etas(1) reference samples.  For a
        % fixed z, every other raw offset must differ only by eta/eta_ref.
        assert(norm(item.raw_offset-(eta/reference.eta)*reference.raw_offset) < 1e-12, ...
            'Raw paired offsets do not differ only by eta.');
        expected = eta^2*state.sigma^2*state.C(1:2,1:2);
        assert(norm(item.upper_covariance-expected,'fro') < 1e-12, ...
            'The diagnostic covariance does not equal eta^2 sigma^2 Cuu.');
    end
end
end
