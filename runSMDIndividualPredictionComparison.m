function summary = runSMDIndividualPredictionComparison(outputRoot,numberOfRuns,problemNumbers)
%RUNSMDINDIVIDUALPREDICTIONCOMPARISON Paired baseline/v2 experiments.
% Default: SMD1--SMD8, (2+3), ten matched seeds per variant.
projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 1 || isempty(outputRoot)
    outputRoot = fullfile(projectRoot,'results_individual_prediction_comparison', ...
        datestr(now,'yyyymmdd_HHMMSS'));
end
if nargin < 2 || isempty(numberOfRuns), numberOfRuns = 10; end
if nargin < 3 || isempty(problemNumbers), problemNumbers = 1:8; end
validateattributes(numberOfRuns,{'numeric'},{'scalar','integer','>=',1,'<=',10});
validateattributes(problemNumbers,{'numeric'},{'vector','integer','>=',1,'<=',8});
assert(numel(unique(problemNumbers)) == numel(problemNumbers),'Duplicate problems.');
assert(exist(outputRoot,'dir') ~= 7 && exist(outputRoot,'file') ~= 2, ...
    'Choose a fresh output directory: %s',outputRoot);
mkdir(outputRoot);

config = struct('problemNumbers',problemNumbers,'numberOfRuns',numberOfRuns, ...
    'totalDim',5,'upperDim',2,'lowerDim',3,'UmaxFEs',2500, ...
    'UmaxImprFEs',350,'LmaxFEs',250,'LmaxImprFEs',25, ...
    'weight',0.1,'startGeneration',10,'historyGenerations',10, ...
    'sampleCount',40);
save(fullfile(outputRoot,'experiment_config.mat'),'config');

sourceDir = fullfile(outputRoot,'source_snapshot');
mkdir(sourceDir);
sourceFiles = {'BLCMAES.m','predictionCorrectionOptions.m', ...
    'individualPredictionCorrectionOptions.m','fitLocalUpperQuadratic.m', ...
    'applyIndividualPredictionCorrection.m', ...
    'initializeIndividualPredictionState.m', ...
    'finalizeIndividualPredictionCorrection.m', ...
    'appendIndividualPredictionLog.m', ...
    'runSMDIndividualPredictionComparison.m', ...
    'testIndividualPredictionCorrection.m'};
for i = 1:numel(sourceFiles)
    copyfile(fullfile(projectRoot,sourceFiles{i}),sourceDir);
end

variants = {'baseline','individual_prediction'};
columns = {'SMD','variant','run_no','seed','UF','original_F','upper_error', ...
    'upper_success','UFE','LFE_total','generations','valid_predictions', ...
    'corrected_generations','corrected_individuals','boundary_repairs', ...
    'runtime_seconds','mat_file'};
rows = cell(0,numel(columns));
for smdNo = problemNumbers(:)'
    baseBI = getBLOPinfo('SMD',smdNo,config.totalDim);
    assert(baseBI.u_dim == config.upperDim && baseBI.l_dim == config.lowerDim);
    baseBI.UmaxFEs = config.UmaxFEs;
    baseBI.UmaxImprFEs = config.UmaxImprFEs;
    baseBI.LmaxFEs = config.LmaxFEs;
    baseBI.LmaxImprFEs = config.LmaxImprFEs;
    baseBI.u_N = 50;
    baseBI.l_N = 50;
    baseBI.generationDiagnostic = struct('enabled',true);
    for runNo = 1:numberOfRuns
        seed = (smdNo-1)*10 + runNo;
        for variantIndex = 1:numel(variants)
            variant = variants{variantIndex};
            BI = baseBI;
            BI.enablePredictionCorrection = false;
            BI.enableIndividualPredictionCorrection = strcmp(variant, ...
                'individual_prediction');
            BI.individualPredictionCorrection = struct('logEnabled',true, ...
                'weight',config.weight,'startGeneration',config.startGeneration, ...
                'historyGenerations',config.historyGenerations, ...
                'sampleCount',config.sampleCount);
            rng(seed,'twister');
            rngStateBefore = rng;
            timer = tic;
            ins = BLCMAES(BI);
            elapsed = toc(timer);
            rngStateAfter = rng;
            individualPredictionLog = ins.individualPredictionLog;
            metadata = struct('problem',BI.fn,'variant',variant,'runNo',runNo, ...
                'seed',seed,'rngStateBefore',rngStateBefore, ...
                'rngStateAfter',rngStateAfter,'runtimeSeconds',elapsed, ...
                'UFMeaning','UF = -original upper objective; larger is better', ...
                'strategy',['Generation t fits only evaluated samples through t; ' ...
                    'a valid point is first applied to all sampled upper ' ...
                    'individuals in generation t+1.']);
            runDir = fullfile(outputRoot,sprintf('SMD%d',smdNo),'DU2_DL3',variant);
            if ~exist(runDir,'dir'), mkdir(runDir); end
            matFile = fullfile(runDir, ...
                sprintf('SMD%d_DU2_DL3_run%02d.mat',smdNo,runNo));
            save(matFile,'ins','individualPredictionLog','BI','metadata','-v7');
            correctionCounts = arrayfun(@(item)sum(item.correction_applied), ...
                individualPredictionLog);
            validPredictions = sum([individualPredictionLog.next_prediction_valid]);
            correctedGenerations = sum(correctionCounts > 0);
            correctedIndividuals = sum(correctionCounts);
            boundaryRepairs = sum(arrayfun(@(item)sum(item.boundary_repaired), ...
                individualPredictionLog));
            errorUF = abs(ins.UF-BI.u_fopt);
            rows(end+1,:) = {smdNo,variant,runNo,seed,ins.UF,-ins.UF,errorUF, ...
                errorUF < BI.u_ftol,ins.UFEs,ins.LFEs, ...
                numel(individualPredictionLog),validPredictions, ...
                correctedGenerations,correctedIndividuals,boundaryRepairs, ...
                elapsed,matFile};
            runs = cell2table(rows,'VariableNames',columns);
            save(fullfile(outputRoot,'comparison_runs.mat'),'runs','config');
            writetable(runs,fullfile(outputRoot,'comparison_runs.csv'));
            fprintf(['SMD%d run %02d %-22s err=%.3g UFE=%d LFE=%d ' ...
                'correctedIndividuals=%d\n'], ...
                smdNo,runNo,variant,errorUF,ins.UFEs,ins.LFEs, ...
                correctedIndividuals);
        end
    end
end

summaryRows = cell(0,14);
for smdNo = problemNumbers(:)'
    baseline = runs(runs.SMD == smdNo & strcmp(runs.variant,'baseline'),:);
    prediction = runs(runs.SMD == smdNo & ...
        strcmp(runs.variant,'individual_prediction'),:);
    pairedSuccess = logical(baseline.upper_success) & logical(prediction.upper_success);
    successfulLFEReduction = NaN;
    if any(pairedSuccess)
        successfulLFEReduction = 100*mean(1 - ...
            prediction.LFE_total(pairedSuccess) ./ baseline.LFE_total(pairedSuccess));
    end
    summaryRows(end+1,:) = {smdNo,height(prediction), ...
        mean(baseline.upper_error),mean(prediction.upper_error), ...
        sum(baseline.upper_success),sum(prediction.upper_success), ...
        mean(baseline.UFE),mean(prediction.UFE), ...
        mean(baseline.LFE_total),mean(prediction.LFE_total), ...
        100*(1-mean(prediction.UFE)/mean(baseline.UFE)), ...
        100*(1-mean(prediction.LFE_total)/mean(baseline.LFE_total)), ...
        successfulLFEReduction,mean(prediction.corrected_individuals)};
end
summary = cell2table(summaryRows,'VariableNames',{'SMD','runs', ...
    'baseline_mean_upper_error','individual_mean_upper_error', ...
    'baseline_successes','individual_successes','baseline_mean_UFE', ...
    'individual_mean_UFE','baseline_mean_LFE','individual_mean_LFE', ...
    'UFE_reduction_pct','LFE_reduction_pct', ...
    'joint_success_mean_LFE_reduction_pct','mean_corrected_individuals'});
save(fullfile(outputRoot,'comparison_summary.mat'),'summary','runs','config');
writetable(summary,fullfile(outputRoot,'comparison_summary.csv'));
disp(summary);
fprintf('Individual-prediction comparison saved in %s\n',outputRoot);
end
