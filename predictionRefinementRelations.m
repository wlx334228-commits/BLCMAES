function [geometry,complementarity]=predictionRefinementRelations(details)
%PREDICTIONREFINEMENTRELATIONS Geometry and post-hoc potential, not CMA updates.
keys=unique(details(:,{'SMD','run_no','seed','generation'}),'rows');
geometryRows=struct([]); complementRows=struct([]);
for state=1:height(keys)
    sub=details(details.SMD==keys.SMD(state)&details.run_no==keys.run_no(state)& ...
        details.generation==keys.generation(state),:);
    p1=sub(sub.model=="P1",:);
    C=jsondecode(p1.C); meanJoint=jsondecode(p1.cma_mean); meanUpper=meanJoint(1:2)';
    if size(meanUpper,1)~=1, meanUpper=meanUpper'; end
    C=(C(1:2,1:2)+C(1:2,1:2)')/2; [V,D]=eig(C); eigenvalues=diag(D);
    floorValue=max(realmin,1e-12*max(eigenvalues)); regularized=any(eigenvalues<floorValue);
    inverseRoot=V*diag(1./sqrt(max(eigenvalues,floorValue)))*V'/p1.sigma;
    wanted=["P1","P2","G2","Q2","R2","P2_S2","G2_S2","Q2_S2","R2_S2"];
    points=sub(ismember(sub.model,wanted),:);
    for a=1:height(points)-1
        for b=a+1:height(points)
            A=points(a,:); B=points(b,:);
            row=struct('SMD',p1.SMD,'run_no',p1.run_no,'seed',p1.seed, ...
                'generation',p1.generation,'stage',p1.stage,'model_A',A.model,'model_B',B.model, ...
                'eligible_opportunity',p1.eligible_opportunity, ...
                'prediction_pair_valid',A.prediction_valid&&B.prediction_valid, ...
                'evaluation_pair_valid',A.evaluation_valid&&B.evaluation_valid, ...
                'x_A',A.x_pred,'x_B',B.x_pred,'direction_A',"",'direction_B',"", ...
                'whitened_direction_A',"",'whitened_direction_B',"", ...
                'euclidean_distance',NaN,'mahalanobis_sigma_distance',NaN, ...
                'cosine_raw',NaN,'cosine_whitened',NaN,'UF_A',A.true_UF,'UF_B',B.true_UF, ...
                'UF_B_minus_A',B.true_UF-A.true_UF,'rank_A',A.rank,'rank_B',B.rank, ...
                'potential_parent_A',A.potential_parent,'potential_parent_B',B.potential_parent, ...
                'covariance_regularized',regularized);
            if row.prediction_pair_valid
                xA=[A.x_pred1 A.x_pred2]; xB=[B.x_pred1 B.x_pred2];
                dA=xA-meanUpper; dB=xB-meanUpper;
                wA=dA*inverseRoot; wB=dB*inverseRoot;
                row.direction_A=string(jsonencode(dA)); row.direction_B=string(jsonencode(dB));
                row.whitened_direction_A=string(jsonencode(wA)); row.whitened_direction_B=string(jsonencode(wB));
                row.euclidean_distance=norm(xB-xA);
                row.mahalanobis_sigma_distance=norm((xB-xA)*inverseRoot);
                row.cosine_raw=cosine(dA,dB); row.cosine_whitened=cosine(wA,wB);
            end
            geometryRows=append(geometryRows,row);
        end
    end
    for mode=["S1","S2"]
        candidates=sub(sub.mode==mode,:);
        if isempty(candidates), continue; end
        valid=candidates.prediction_valid&candidates.evaluation_valid;
        best=NaN; winners=false(height(candidates),1);
        if any(valid), best=max(candidates.true_UF(valid)); winners=valid&candidates.true_UF==best; end
        for i=1:height(candidates)
            row=struct('SMD',p1.SMD,'run_no',p1.run_no,'seed',p1.seed, ...
                'generation',p1.generation,'stage',p1.stage,'mode',mode,'model',candidates.model(i), ...
                'eligible_opportunity',p1.eligible_opportunity,'P1_evaluation_valid',p1.evaluation_valid, ...
                'candidate_valid',valid(i),'any_refined_valid',any(valid), ...
                'all_refined_valid',all(valid),'best_refined_UF',best, ...
                'is_best_refined',winners(i),'is_unique_best_refined',winners(i)&&sum(winners)==1, ...
                'best_fractional_credit',double(winners(i))/max(1,sum(winners)), ...
                'better_than_P1',valid(i)&&p1.evaluation_valid&&candidates.true_UF(i)>p1.true_UF, ...
                'any_refined_better_than_P1',p1.evaluation_valid&&any(valid&candidates.true_UF>p1.true_UF), ...
                'P1_not_better_than_normal_best',p1.evaluation_valid&&~p1.better_than_normal_best, ...
                'rescues_normal_best',p1.evaluation_valid&&~p1.better_than_normal_best&& ...
                    valid(i)&&candidates.better_than_normal_best(i), ...
                'any_rescues_normal_best',p1.evaluation_valid&&~p1.better_than_normal_best&& ...
                    any(valid&candidates.better_than_normal_best), ...
                'best_refined_UF_minus_P1',best-p1.true_UF);
            complementRows=append(complementRows,row);
        end
    end
end
if isempty(geometryRows)
    geometry=table(zeros(0,1),strings(0,1),strings(0,1),'VariableNames',{'SMD','model_A','model_B'});
else, geometry=struct2table(geometryRows); end
complementarity=struct2table(complementRows);
end

function value=cosine(a,b)
denominator=norm(a)*norm(b);
if denominator==0||~isfinite(denominator), value=NaN;
else, value=max(-1,min(1,(a*b')/denominator)); end
end
function rows=append(rows,row)
if isempty(rows), rows=row; else, rows(end+1,1)=row; end
end
