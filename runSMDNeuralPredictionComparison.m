function experiment = runSMDNeuralPredictionComparison( ...
    outputRoot,numberOfRuns,problemNumbers)
%RUNSMDNEURALPREDICTIONCOMPARISON Paired A0/Q/NN study for SMD1--SMD8.
% A0 is original BL-CMA-ES.  Q and NN both use exactly seven normal CMA-ES
% samples plus one direct predicted point.  Thus the only experimental
% factor between Q and NN is the local prediction model: complete quadratic
% regression versus a freshly trained 2-6-1 tanh MLP and bounded multistart
% surrogate optimisation.  No Hessian auxiliary candidates are used here.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 2 || isempty(numberOfRuns), numberOfRuns = 20; end
if nargin < 3 || isempty(problemNumbers), problemNumbers = 1:8; end
validateattributes(numberOfRuns,{'numeric'},{'scalar','integer','positive'});
validateattributes(problemNumbers,{'numeric'}, ...
    {'vector','integer','>=',1,'<=',8});
assert(numel(unique(problemNumbers)) == numel(problemNumbers), ...
    'problemNumbers must not contain duplicates.');
if nargin < 1 || isempty(outputRoot)
    outputRoot = fullfile(projectRoot,'results_neural_prediction_comparison_2D', ...
        sprintf('SMD%d_to_SMD%d_%druns',min(problemNumbers), ...
        max(problemNumbers),numberOfRuns));
end
if exist(outputRoot,'dir') ~= 7, mkdir(outputRoot); end

specifications = neuralSpecifications(outputRoot);
saveOrValidateNeuralConfig(outputRoot,numberOfRuns,problemNumbers,specifications);
smokeRoot = fullfile(outputRoot,'smoke_test_neural_model');
if exist(fullfile(smokeRoot,'neural_prediction_model_test_report.mat'),'file') ~= 2
    testNeuralPredictionModel(smokeRoot);
else
    fprintf('Reuse completed neural-model smoke test: %s\n',smokeRoot);
end
if exist(fullfile(smokeRoot,'neural_prediction_end_to_end_test_report.mat'), ...
        'file') ~= 2
    testNeuralPredictionEndToEnd(smokeRoot);
else
    fprintf('Reuse completed neural end-to-end smoke test: %s\n',smokeRoot);
end

for specIndex = 1:numel(specifications)
    spec = specifications(specIndex);
    fprintf('Run %s: %d normal + %d direct, model=%s.\n', ...
        spec.id,spec.normalCount,spec.directCount,spec.predictionModelType);
    runSMDPredictionInjection(spec.resultRoot,numberOfRuns,problemNumbers, ...
        spec.injectCount,'direct_plus_auxiliary',5,40,'cma_gaussian',1.0, ...
        spec.predictionModelType);
end

runs = collectNeuralRuns(specifications,problemNumbers,numberOfRuns);
[summary,pairedTests] = summariseNeuralRuns(runs,specifications,problemNumbers);
fixedStateDiagnostics = diagnoseNeuralPredictionFixedStates( ...
    specifications(strcmp({specifications.id},'Q')).resultRoot,outputRoot);
writetable(runs,fullfile(outputRoot,'neural_prediction_runs.csv'));
writetable(summary,fullfile(outputRoot,'neural_prediction_summary.csv'));
writetable(pairedTests,fullfile(outputRoot, ...
    'neural_prediction_paired_wilcoxon.csv'));
experiment = struct('outputRoot',outputRoot,'numberOfRuns',numberOfRuns, ...
    'problemNumbers',problemNumbers,'specifications',specifications, ...
    'runs',runs,'summary',summary,'pairedTests',pairedTests, ...
    'fixedStateDiagnostics',fixedStateDiagnostics, ...
    'notes',['Q and NN use the same 40 local archive samples, 10-generation ' ...
     'history window, K=1 direct injection layout, seed schedule, budgets, ' ...
     'and all BL-CMA-ES settings.  NN training/optimisation uses no true ' ...
     'function evaluation.']);
save(fullfile(outputRoot,'neural_prediction_experiment_index.mat'), ...
    'experiment','-v7');
fprintf('\nA0/Q/NN neural prediction comparison completed: %s\n',outputRoot);
end

function specifications = neuralSpecifications(outputRoot)
specifications = [ ...
    makeSpec('A0',0,8,0,'quadratic',outputRoot); ...
    makeSpec('Q',1,7,1,'quadratic',outputRoot); ...
    makeSpec('NN',1,7,1,'neural_mlp',outputRoot)];
end

function spec = makeSpec(id,injectCount,normalCount,directCount,modelType,root)
assert(normalCount+directCount == 8, ...
    'Every (2+3) population must contain exactly eight candidates.');
spec = struct('id',id,'injectCount',injectCount,'normalCount',normalCount, ...
    'directCount',directCount,'predictionModelType',modelType, ...
    'resultRoot',fullfile(root,[id '_' modelType]));
end

function saveOrValidateNeuralConfig(outputRoot,numberOfRuns,problemNumbers,specifications)
fileName = fullfile(outputRoot,'neural_prediction_experiment_config.mat');
config = struct('totalDim',5,'upperDim',2,'lowerDim',3, ...
    'populationSize',8,'numberOfRuns',numberOfRuns, ...
    'problemNumbers',problemNumbers,'sampleCount',40, ...
    'startGeneration',10,'historyGenerations',10, ...
    'candidatePolicy','direct_plus_auxiliary', ...
    'comparisonLayout','A0:8normal; Q/NN:7normal+1direct; no auxiliary', ...
    'specifications',serialisableSpecifications(specifications), ...
    'comparisons',{{'Q_vs_A0','NN_vs_A0','NN_vs_Q'}});
if exist(fileName,'file') ~= 2
    save(fileName,'config');
    return;
end
loaded = load(fileName,'config');
previous = loaded.config;
assert(previous.totalDim == 5 && previous.numberOfRuns == numberOfRuns && ...
    isequal(previous.problemNumbers,problemNumbers) && ...
    isequal(previous.specifications,serialisableSpecifications(specifications)), ...
    ['This output directory has a different neural-comparison configuration. ' ...
     'Choose a fresh outputRoot rather than mixing experiments.']);
end

function stored = serialisableSpecifications(specifications)
stored = specifications;
for i = 1:numel(stored)
    stored(i).resultRoot = [stored(i).id '_' stored(i).predictionModelType];
end
end

function allRuns = collectNeuralRuns(specifications,problemNumbers,numberOfRuns)
allRuns = table();
for specIndex = 1:numel(specifications)
    spec = specifications(specIndex);
    csvFile = fullfile(spec.resultRoot,'injection_runs.csv');
    assert(exist(csvFile,'file') == 2,'Missing result table: %s',csvFile);
    rows = readtable(csvFile);
    rows = rows(ismember(rows.SMD,problemNumbers) & ...
        rows.prediction_inject_count == spec.injectCount,:);
    validateSchedule(rows,spec,problemNumbers,numberOfRuns);
    diagnostics = collectRunDiagnostics(rows,spec.resultRoot);
    rows = [rows diagnostics];
    rows.experiment_id = repmat({spec.id},height(rows),1);
    rows.prediction_model_type = repmat({spec.predictionModelType}, ...
        height(rows),1);
    rows.configured_normal_candidate_count = repmat(spec.normalCount, ...
        height(rows),1);
    rows.configured_direct_candidate_count = repmat(spec.directCount, ...
        height(rows),1);
    rows.configured_auxiliary_candidate_count = zeros(height(rows),1);
    rows.result_root = repmat({[spec.id '_' spec.predictionModelType]}, ...
        height(rows),1);
    if isempty(allRuns), allRuns = rows; else, allRuns = [allRuns;rows]; end %#ok<AGROW>
end
allRuns = sortrows(allRuns,{'SMD','experiment_id','run_no'});
end

function diagnostics = collectRunDiagnostics(rows,resultRoot)
names = {'prediction_fit_attempts','prediction_fit_successes', ...
    'prediction_fit_success_rate','prediction_boundary_rate', ...
    'first_prediction_generation', ...
    'model_train_MSE_median','model_validation_MSE_median', ...
    'model_training_epochs_median','model_optimizer_converged_rate', ...
    'model_optimizer_iterations_median','direct_true_UF_median', ...
    'direct_better_normal_pair_rate_median', ...
    'direct_better_all_normal_rate','direct_distance_to_cma_mean_median', ...
    'direct_distance_to_history_best_median'};
diagnostics = array2table(NaN(height(rows),numel(names)), ...
    'VariableNames',names);
for rowIndex = 1:height(rows)
    path = fullfile(resultRoot,portablePath(tableText(rows.mat_file,rowIndex)));
    loaded = load(path,'injectionLog');
    log = loaded.injectionLog;
    modelList = cell(numel(log),1);
    for g = 1:numel(log)
        modelList{g} = log(g).next_prediction_model;
    end
    valid = false(numel(log),1);
    attempted = false(numel(log),1);
    trainMSE = NaN(numel(log),1); validationMSE = NaN(numel(log),1);
    epochs = NaN(numel(log),1); optimiserConverged = NaN(numel(log),1);
    optimiserIterations = NaN(numel(log),1);
    for g = 1:numel(modelList)
        model = modelList{g};
        if isstruct(model) && ~isempty(fieldnames(model))
            attempted(g) = isfield(model,'reason') && ...
                ~strcmp(model.reason,'warmup') && ...
                ~strcmp(model.reason,'insufficient_samples');
            valid(g) = isfield(model,'valid') && logical(model.valid);
            trainMSE(g) = scalarField(model,'trainMSE');
            validationMSE(g) = scalarField(model,'validationMSE');
            epochs(g) = scalarField(model,'trainingEpochs');
            optimiserConverged(g) = scalarField(model,'optimizerConverged');
            optimiserIterations(g) = scalarField(model,'optimizerIterations');
        end
    end
    used = [log.prediction_valid_used]';
    diagnostics.prediction_fit_attempts(rowIndex) = sum(attempted);
    diagnostics.prediction_fit_successes(rowIndex) = sum(valid);
    diagnostics.prediction_fit_success_rate(rowIndex) = safeRatio(sum(valid),sum(attempted));
    diagnostics.prediction_boundary_rate(rowIndex) = ...
        safeRatio(sum([log.prediction_at_search_boundary]' & used),sum(used));
    firstUsed = find(used,1);
    if ~isempty(firstUsed)
        diagnostics.first_prediction_generation(rowIndex) = log(firstUsed).generation;
    end
    diagnostics.model_train_MSE_median(rowIndex) = finiteMedian(trainMSE);
    diagnostics.model_validation_MSE_median(rowIndex) = finiteMedian(validationMSE);
    diagnostics.model_training_epochs_median(rowIndex) = finiteMedian(epochs);
    diagnostics.model_optimizer_converged_rate(rowIndex) = ...
        finiteMean(optimiserConverged(valid));
    diagnostics.model_optimizer_iterations_median(rowIndex) = ...
        finiteMedian(optimiserIterations(valid));
    diagnostics.direct_true_UF_median(rowIndex) = ...
        finiteMedian([log.direct_true_UF]');
    diagnostics.direct_better_normal_pair_rate_median(rowIndex) = ...
        finiteMedian([log.direct_better_than_normal_pair_rate]');
    diagnostics.direct_better_all_normal_rate(rowIndex) = ...
        finiteMean(double([log.direct_better_than_all_normal]' & used));
    diagnostics.direct_distance_to_cma_mean_median(rowIndex) = ...
        finiteMedian([log.prediction_distance_to_cma_mean]');
    diagnostics.direct_distance_to_history_best_median(rowIndex) = ...
        finiteMedian([log.prediction_distance_to_history_best]');
end
end

function [summary,tests] = summariseNeuralRuns(runs,specifications,problems)
names = {'SMD','experiment_id','prediction_model_type','runs', ...
    'upper_successes','upper_success_rate','lower_successes','lower_success_rate', ...
    'upper_error_median','upper_error_IQR','lower_error_median','lower_error_IQR', ...
    'UFE_median','UFE_IQR','LFE_median','LFE_IQR', ...
    'prediction_fit_success_rate_median','prediction_injected_generations_median', ...
    'first_prediction_generation_median', ...
    'model_train_MSE_median','model_validation_MSE_median', ...
    'model_training_epochs_median','model_optimizer_converged_rate_median', ...
    'model_optimizer_iterations_median','prediction_boundary_rate_median', ...
    'direct_parent_selection_rate_median','direct_generation_best_median', ...
    'direct_new_best_median','direct_true_UF_median', ...
    'direct_better_normal_pair_rate_median','direct_better_all_normal_rate_median', ...
    'direct_distance_to_cma_mean_median', ...
    'direct_distance_to_history_best_median','consistency_passed_runs'};
records = cell(0,numel(names));
for smdNo = problems(:)'
    for s = 1:numel(specifications)
        spec = specifications(s);
        subset = runs(runs.SMD == smdNo & ...
            strcmp(runs.experiment_id,spec.id),:);
        [upperMedian,upperIQR] = medianIQR(subset.upper_error);
        [lowerMedian,lowerIQR] = medianIQR(subset.lower_error);
        [ufeMedian,ufeIQR] = medianIQR(subset.UFE);
        [lfeMedian,lfeIQR] = medianIQR(subset.LFE_total);
        records(end+1,:) = {smdNo,spec.id,spec.predictionModelType,height(subset), ...
            sum(subset.upper_success ~= 0),mean(subset.upper_success ~= 0), ...
            sum(subset.lower_success ~= 0),mean(subset.lower_success ~= 0), ...
            upperMedian,upperIQR,lowerMedian,lowerIQR,ufeMedian,ufeIQR, ...
            lfeMedian,lfeIQR,finiteMedian(subset.prediction_fit_success_rate), ...
            finiteMedian(subset.prediction_injected_generations), ...
            finiteMedian(subset.first_prediction_generation), ...
            finiteMedian(subset.model_train_MSE_median), ...
            finiteMedian(subset.model_validation_MSE_median), ...
            finiteMedian(subset.model_training_epochs_median), ...
            finiteMedian(subset.model_optimizer_converged_rate), ...
            finiteMedian(subset.model_optimizer_iterations_median), ...
            finiteMedian(subset.prediction_boundary_rate), ...
            finiteMedian(subset.direct_parent_selection_rate), ...
            finiteMedian(subset.direct_generation_best_total), ...
            finiteMedian(subset.direct_new_best_total), ...
            finiteMedian(subset.direct_true_UF_median), ...
            finiteMedian(subset.direct_better_normal_pair_rate_median), ...
            finiteMedian(subset.direct_better_all_normal_rate), ...
            finiteMedian(subset.direct_distance_to_cma_mean_median), ...
            finiteMedian(subset.direct_distance_to_history_best_median), ...
            sum(subset.consistency_passed ~= 0)}; %#ok<AGROW>
    end
end
summary = cell2table(records,'VariableNames',names);
tests = buildPairwiseTests(runs,problems);
end

function tests = buildPairwiseTests(runs,problems)
comparisons = {'Q_vs_A0','A0','Q';'NN_vs_A0','A0','NN';'NN_vs_Q','Q','NN'};
names = {'SMD','comparison','reference_experiment','variant_experiment', ...
    'paired_runs','reference_upper_successes','variant_upper_successes', ...
    'reference_lower_successes','variant_lower_successes', ...
    'reference_upper_error_median','variant_upper_error_median', ...
    'reference_lower_error_median','variant_lower_error_median', ...
    'reference_UFE_median','variant_UFE_median', ...
    'reference_LFE_median','variant_LFE_median', ...
    'upper_error_p','lower_error_p','UFE_p','LFE_p', ...
    'upper_error_p_holm','lower_error_p_holm','UFE_p_holm','LFE_p_holm', ...
    'upper_error_advantage','lower_error_advantage','UFE_advantage', ...
    'LFE_advantage','evaluation_advantage_eligible'};
records = cell(0,numel(names));
for smdNo = problems(:)'
    for c = 1:size(comparisons,1)
        reference = runs(runs.SMD == smdNo & ...
            strcmp(runs.experiment_id,comparisons{c,2}),:);
        variant = runs(runs.SMD == smdNo & ...
            strcmp(runs.experiment_id,comparisons{c,3}),:);
        [reference,variant] = alignedPairs(reference,variant,smdNo,comparisons{c,1});
        upper = pairedWilcoxonSignedRank(variant.upper_error,reference.upper_error);
        lower = pairedWilcoxonSignedRank(variant.lower_error,reference.lower_error);
        ufe = pairedWilcoxonSignedRank(variant.UFE,reference.UFE);
        lfe = pairedWilcoxonSignedRank(variant.LFE_total,reference.LFE_total);
        eligible = sum(reference.upper_success ~= 0) > 0 && ...
            sum(reference.lower_success ~= 0) > 0 && ...
            sum(variant.upper_success ~= 0) >= sum(reference.upper_success ~= 0) && ...
            sum(variant.lower_success ~= 0) >= sum(reference.lower_success ~= 0);
        records(end+1,:) = {smdNo,comparisons{c,1},comparisons{c,2}, ...
            comparisons{c,3},height(reference), ...
            sum(reference.upper_success ~= 0),sum(variant.upper_success ~= 0), ...
            sum(reference.lower_success ~= 0),sum(variant.lower_success ~= 0), ...
            finiteMedian(reference.upper_error),finiteMedian(variant.upper_error), ...
            finiteMedian(reference.lower_error),finiteMedian(variant.lower_error), ...
            finiteMedian(reference.UFE),finiteMedian(variant.UFE), ...
            finiteMedian(reference.LFE_total),finiteMedian(variant.LFE_total), ...
            upper.p,lower.p,ufe.p,lfe.p,NaN,NaN,NaN,NaN, ...
            false,false,false,false,eligible}; %#ok<AGROW>
    end
end
tests = cell2table(records,'VariableNames',names);
tests = holmAndAdvantages(tests);
end

function [reference,variant] = alignedPairs(reference,variant,smdNo,comparison)
assert(height(reference) == height(variant) && ~isempty(reference), ...
    'SMD%d %s has unmatched paired data.',smdNo,comparison);
reference = sortrows(reference,'run_no');
variant = sortrows(variant,'run_no');
assert(isequal(reference.run_no,variant.run_no) && ...
    isequal(reference.seed,variant.seed), ...
    'SMD%d %s does not share paired seeds.',smdNo,comparison);
end

function tests = holmAndAdvantages(tests)
metrics = {'upper_error','lower_error','UFE','LFE'};
for smdNo = unique(tests.SMD)'
    rows = tests.SMD == smdNo;
    for metricIndex = 1:numel(metrics)
        metric = metrics{metricIndex};
        tests.([metric '_p_holm'])(rows) = holmAdjust(tests.([metric '_p'])(rows));
    end
end
tests.upper_error_advantage = tests.upper_error_p_holm < 0.05 & ...
    tests.variant_upper_error_median < tests.reference_upper_error_median;
tests.lower_error_advantage = tests.lower_error_p_holm < 0.05 & ...
    tests.variant_lower_error_median < tests.reference_lower_error_median;
tests.UFE_advantage = tests.evaluation_advantage_eligible & ...
    tests.UFE_p_holm < 0.05 & tests.variant_UFE_median < tests.reference_UFE_median;
tests.LFE_advantage = tests.evaluation_advantage_eligible & ...
    tests.LFE_p_holm < 0.05 & tests.variant_LFE_median < tests.reference_LFE_median;
end

function adjusted = holmAdjust(pValues)
adjusted = NaN(size(pValues));
valid = find(isfinite(pValues));
if isempty(valid), return; end
[ordered,order] = sort(pValues(valid));
adjustedOrdered = NaN(numel(ordered),1); previous = 0;
for i = 1:numel(ordered)
    previous = max(previous,min(1,(numel(ordered)-i+1)*ordered(i)));
    adjustedOrdered(i) = previous;
end
adjusted(valid(order)) = adjustedOrdered;
end

function validateSchedule(rows,spec,problems,numberOfRuns)
for smdNo = problems(:)'
    subset = rows(rows.SMD == smdNo,:);
    assert(height(subset) == numberOfRuns, ...
        '%s has an incomplete SMD%d run set.',spec.id,smdNo);
    assert(isequal(sort(subset.run_no)',1:numberOfRuns), ...
        '%s has duplicate/missing runs for SMD%d.',spec.id,smdNo);
    expectedSeed = (smdNo-1)*numberOfRuns+subset.run_no;
    assert(all(subset.seed == expectedSeed), ...
        '%s does not use paired seeds for SMD%d.',spec.id,smdNo);
end
end

function value = scalarField(item,name)
value = NaN;
if isstruct(item) && isfield(item,name) && ...
        (isnumeric(item.(name)) || islogical(item.(name))) && ...
        isscalar(item.(name)) && isfinite(item.(name))
    value = double(item.(name));
end
end

function value = safeRatio(numerator,denominator)
if denominator > 0, value = numerator/denominator; else, value = NaN; end
end

function value = finiteMedian(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = median(values); end
end

function value = finiteMean(values)
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = mean(values); end
end

function [middle,spread] = medianIQR(values)
values = sort(values(isfinite(values)));
if isempty(values), middle = NaN; spread = NaN; return; end
middle = median(values);
if numel(values) < 2, spread = NaN; return; end
position = @(p) 1+(numel(values)-1)*p;
q = zeros(1,2);
probabilities = [0.25,0.75];
for i = 1:2
    where = position(probabilities(i));
    lower = floor(where); upper = ceil(where);
    q(i) = values(lower) + (where-lower)*(values(upper)-values(lower));
end
spread = q(2)-q(1);
end

function path = portablePath(relativePath)
path = strrep(relativePath,'/',filesep);
path = strrep(path,'\\',filesep);
end

function value = tableText(column,index)
if iscell(column)
    value = char(column{index});
elseif ischar(column)
    value = strtrim(column(index,:));
else
    value = char(column(index));
end
end
