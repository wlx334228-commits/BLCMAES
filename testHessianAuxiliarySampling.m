function report = testHessianAuxiliarySampling(outputDir,replications)
%TESTHESSIANAUXILIARYSAMPLING Check H1 curvature-shaped auxiliary sampling.
% This non-evaluating test checks the inverse-curvature orientation, trace
% calibration, empirical Gaussian covariance, candidate composition, and
% the explicit all-normal fallback.  It does not call an SMD objective.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(projectRoot,'results_hessian_auxiliary_sampling_tests', ...
        datestr(now,'yyyymmdd_HHMMSS'));
end
if nargin < 2 || isempty(replications), replications = 2000; end
validateattributes(replications,{'numeric'},{'scalar','integer','>=',1000});
if exist(outputDir,'dir') ~= 7, mkdir(outputDir); end

BI = getBLOPinfo('SMD',1,5);
assert(BI.u_dim == 2 && BI.l_dim == 3 && BI.dim == 5, ...
    'This check requires SMD1 at (DU,DL)=(2,3).');
[CMA,rawUpper,rawLower] = syntheticCMA(BI);
model = syntheticQuadraticModel(CMA.xmean(1:BI.u_dim));
options = hessianOptions(BI,700001);
cmaCovariance = CMA.sigma^2 * CMA.C(1:BI.u_dim,1:BI.u_dim);

% Analytic check: the flatter curvature direction has larger variance,
% total variance equals CMA's, and the principal covariance direction is
% the flat Hessian direction.
build = constructHessianAuxiliaryCovariance(model,cmaCovariance,options);
[hVectors,hValues] = eig((build.covariance+build.covariance')/2);
[~,largestVarianceIndex] = max(real(diag(hValues)));
alignment = abs(dot(hVectors(:,largestVarianceIndex),model.flatDirection));
assert(alignment > 1-1e-10, ...
    'Hessian covariance principal direction is not the flat direction.');
flatVariance = model.flatDirection' * build.covariance * model.flatDirection;
steepVariance = model.steepDirection' * build.covariance * model.steepDirection;
assert(flatVariance > steepVariance, ...
    'A flatter quadratic direction did not receive larger variance.');
assert(abs(build.traceRatio-1) < 1e-12 && ...
    norm(build.covariance-build.covariance','fro') < 1e-12, ...
    'Hessian covariance is not trace-matched and symmetric.');
assert(all(eig(build.covariance) > 0), ...
    'Hessian covariance is not positive definite.');

% Relative regularisation must cap the curvature condition without relying
% on a hard-coded cross-problem absolute eigenvalue threshold.
illModel = model;
illModel.H = -model.rotation * diag([1e-12,10]) * model.rotation';
illBuild = constructHessianAuxiliaryCovariance(illModel,cmaCovariance,options);
assert(illBuild.regularizedCount >= 1 && ...
    illBuild.regularizedCurvatureCondition <= ...
        options.hessianCovarianceMaxCondition*(1+1e-12), ...
    'Relative curvature regularisation did not bound the condition number.');

state = initializePredictionInjectionState(BI,options);
state.pending = struct('valid',true,'x_pred',model.x_pred, ...
    'source_generation',10,'model',model);
rngBefore = rng;
[upper,lower,entry] = applyPredictionInjection(CMA,rawUpper,rawLower, ...
    11,BI,options,state);
assert(isequal(rngBefore,rng), ...
    'Hessian auxiliary sampling changed the global random-state sequence.');
assert(sum(strcmp(entry.source_labels,'normal')) == 5 && ...
    sum(strcmp(entry.source_labels,'predicted_direct')) == 1 && ...
    sum(strcmp(entry.source_labels,'predicted_auxiliary')) == 2, ...
    'H1 does not produce 5 normal + 1 direct + 2 auxiliary candidates.');
assert(norm(upper(6,:)-model.x_pred) < 1e-12 && ...
    norm(entry.auxiliary_upper_center-model.x_pred) < 1e-12, ...
    'H1 candidates are not centred on the existing prediction point.');
assert(isequal(upper(1:5,:),rawUpper(1:5,:)) && ...
    isequal(lower(1:5,:),rawLower(1:5,:)), ...
    'H1 changed normal CMA-ES candidates.');
assert(entry.hessian_covariance_attempted && ...
    entry.hessian_covariance_success && ...
    abs(entry.hessian_cma_trace_ratio-1) < 1e-12, ...
    'H1 covariance diagnostics are invalid.');

% The two logged raw auxiliaries in each invocation are independent draws
% from exactly the specified upper covariance before boundary repair.
samples = NaN(2*replications,BI.u_dim);
state = initializePredictionInjectionState(BI,options);
state.pending = struct('valid',true,'x_pred',model.x_pred, ...
    'source_generation',10,'model',model);
for i = 1:replications
    [~,~,sampleEntry,state] = applyPredictionInjection(CMA,rawUpper,rawLower, ...
        11,BI,options,state);
    samples((2*i-1):(2*i),:) = ...
        sampleEntry.auxiliary_raw_joint(:,1:BI.u_dim);
end
empiricalMean = mean(samples,1);
empiricalCovariance = cov(samples,1);
meanRelativeError = norm(empiricalMean-model.x_pred) / ...
    max(sqrt(trace(build.covariance)),eps);
covarianceRelativeError = norm(empiricalCovariance-build.covariance,'fro') / ...
    max(norm(build.covariance,'fro'),eps);
assert(meanRelativeError < 0.08 && covarianceRelativeError < 0.13, ...
    'Empirical H1 Gaussian samples do not match the requested covariance.');

% A concave prediction whose stored Hessian becomes invalid after fitting
% must not yield a mixed population: it falls back to all normal samples.
invalidModel = model;
invalidModel.H = eye(BI.u_dim);
invalidState = initializePredictionInjectionState(BI,options);
invalidState.pending = struct('valid',true,'x_pred',model.x_pred, ...
    'source_generation',10,'model',invalidModel);
[fallbackUpper,fallbackLower,fallbackEntry] = applyPredictionInjection( ...
    CMA,rawUpper,rawLower,11,BI,options,invalidState);
assert(isequal(fallbackUpper,rawUpper) && isequal(fallbackLower,rawLower) && ...
    all(strcmp(fallbackEntry.source_labels,'normal')) && ...
    fallbackEntry.hessian_covariance_attempted && ...
    ~fallbackEntry.hessian_covariance_success && ...
    strcmp(fallbackEntry.injection_reason, ...
        'hessian_covariance_failed_normal_fallback'), ...
    'Invalid Hessian did not use the documented all-normal fallback.');

report = struct('passed',true,'replications',replications, ...
    'analytic_covariance',build.covariance, ...
    'cma_covariance',cmaCovariance, ...
    'flat_variance',flatVariance,'steep_variance',steepVariance, ...
    'trace_ratio',build.traceRatio, ...
    'regularized_dimensions',illBuild.regularizedCount, ...
    'empirical_mean',empiricalMean, ...
    'empirical_covariance',empiricalCovariance, ...
    'mean_relative_error',meanRelativeError, ...
    'covariance_relative_error',covarianceRelativeError, ...
    'candidate_entry',entry, ...
    'fallback_entry',fallbackEntry, ...
    'integration',realIntegrationCheck(BI));
save(fullfile(outputDir,'hessian_auxiliary_sampling_test_report.mat'), ...
    'report','model','options');
disp(report);
end

function [CMA,rawUpper,rawLower] = syntheticCMA(BI)
base = [1.0 0.2 0.1 0.0 0.0; ...
        0.4 1.1 0.0 0.1 0.0; ...
        0.2 0.1 1.0 0.0 0.1; ...
        0.0 0.2 0.1 0.9 0.0; ...
        0.1 0.0 0.2 0.1 0.8];
C = base*base';
[B,values] = eig(C);
CMA = struct('xmean',(BI.xrange(1,:)+BI.xrange(2,:))/2, ...
    'sigma',0.02,'C',C,'B',B,'D',sqrt(diag(values))');
populationSize = 4+floor(3*log(BI.dim));
rawUpper = repmat(CMA.xmean(1:BI.u_dim),populationSize,1);
rawLower = repmat(CMA.xmean(BI.u_dim+1:end),populationSize,1);
end

function model = syntheticQuadraticModel(center)
angle = 32*pi/180;
R = [cos(angle),-sin(angle);sin(angle),cos(angle)];
% The first direction has the smaller curvature and is therefore flat.
H = -R*diag([0.5,8])*R';
model = struct('valid',true,'H',H,'scale',0.4, ...
    'x_pred',center,'flatDirection',R(:,1), ...
    'steepDirection',R(:,2),'rotation',R);
end

function options = hessianOptions(BI,seed)
BItest = BI;
BItest.enablePredictionCorrection = false;
BItest.enableIndividualPredictionCorrection = false;
BItest.predictionInjection = struct('mode','K3', ...
    'predictionInjectCount',3,'candidatePolicy','direct_plus_auxiliary', ...
    'auxiliarySamplingDistribution','hessian_gaussian', ...
    'auxiliarySamplingScale',1.0,'logEnabled',true, ...
    'startGeneration',10,'historyGenerations',10,'sampleCount',40, ...
    'auxiliaryRandomSeed',seed,'consistencyCheckEnabled',true, ...
    'hessianCovarianceRelativeEigenvalueFloor',1e-6, ...
    'hessianCovarianceMaxCondition',1e4);
options = predictionInjectionOptions(BItest);
end

function integration = realIntegrationCheck(BI)
% A short real run verifies that whatever candidates reach lower search and
% upper evaluation are the exact same positions later supplied to the
% CMA-ES update.  Whether a fitted prediction becomes valid is problem and
% seed dependent, so this check never fabricates one to force an injection.
BIrun = BI;
BIrun.UmaxFEs = 128;
BIrun.UmaxImprFEs = 350;
BIrun.LmaxFEs = 250;
BIrun.LmaxImprFEs = 25;
BIrun.u_ftol = 0;
BIrun.enablePredictionCorrection = false;
BIrun.enableIndividualPredictionCorrection = false;
BIrun.predictionInjection = struct('mode','K3', ...
    'predictionInjectCount',3,'candidatePolicy','direct_plus_auxiliary', ...
    'auxiliarySamplingDistribution','hessian_gaussian', ...
    'auxiliarySamplingScale',1.0,'logEnabled',true, ...
    'startGeneration',10,'historyGenerations',10,'sampleCount',40, ...
    'auxiliaryRandomSeed',710001,'randomSeed',123, ...
    'consistencyCheckEnabled',true, ...
    'hessianCovarianceRelativeEigenvalueFloor',1e-6, ...
    'hessianCovarianceMaxCondition',1e4);
rng(123,'twister');
ins = BLCMAES(BIrun);
log = ins.predictionInjectionLog;
assert(all(arrayfun(@(item) isequal(item.upper_entering_lower_search, ...
    item.upper_after_injection),log)), ...
    'Real H1 run did not pass actual candidates to lower search.');
for generation = 1:numel(log)
    item = log(generation);
    if item.mean_update_applied
        assert(item.consistency_checked && item.consistency_passed && ...
            isequal(item.selected_parent_joint, ...
            item.joint_for_cma_update(item.selected_parent_indices,:)), ...
            'Real H1 run has inconsistent evaluation/update candidates.');
    end
    if item.hessian_covariance_success
        assert(sum(strcmp(item.source_labels,'normal')) == 5 && ...
            sum(strcmp(item.source_labels,'predicted_direct')) == 1 && ...
            sum(strcmp(item.source_labels,'predicted_auxiliary')) == 2 && ...
            abs(item.hessian_cma_trace_ratio-1) < 1e-10, ...
            'Real H1 injection composition or trace calibration is invalid.');
    end
end
integration = struct('UFE',ins.UFEs,'LFE',ins.LFEs, ...
    'injected_generations',sum([log.effective_injected_count] > 0), ...
    'hessian_success_generations',sum([log.hessian_covariance_success] > 0));
end
