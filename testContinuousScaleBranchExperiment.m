function report = testContinuousScaleBranchExperiment(outputRoot)
%TESTCONTINUOUSSCALEBRANCHEXPERIMENT One-run smoke test for state branches.
% The test deliberately uses H=1 to validate snapshot identity, isolated
% counters, and first-generation pairing before a longer H=5 study.

projectRoot = fileparts(mfilename('fullpath'));
if nargin < 1 || isempty(outputRoot)
    outputRoot = fullfile(projectRoot, ...
        'results_continuous_scale_branch_tests','smoke_SMD1_H1');
end
global ulFunctionEvaluations llFunctionEvaluations;
experiment = runSMDContinuousScaleBranchExperiment(outputRoot,1,1,1,1);
assert(~isempty(experiment.stateSnapshots), ...
    'The smoke main run recorded no valid pre-injection snapshot.');
selected = experiment.stateSnapshots(experiment.stateSnapshots.selected ~= 0,:);
assert(~isempty(selected), 'The smoke run selected no state for branching.');
branches = experiment.branchSummary;
etaRows = branches(~strcmp(branches.eta_label,'A1'),:);
assert(all(ismember([0.25;0.50;0.75;1.00],unique(etaRows.eta))), ...
    'Not all four eta branches completed in the smoke run.');
assert(all(etaRows.completed_generations >= 1), ...
    'At least one eta branch failed before its first generation.');
% The two auxiliary offsets must use the same private Gaussian directions;
% before boundary repair the eta=.50 offsets are exactly twice eta=.25.
for stateIndex = unique(etaRows.state_index)'
    objects = experiment.branchObjects;
    allStateObjects = objects(cellfun(@(item) item.state_index == stateIndex && ...
        item.repeat_no == 1,objects));
    stateObjects = allStateObjects(cellfun(@(item) isfinite(item.eta), ...
        allStateObjects));
    eta025 = stateObjects(cellfun(@(item) abs(item.eta-0.25) < eps, ...
        stateObjects));
    eta050 = stateObjects(cellfun(@(item) abs(item.eta-0.50) < eps, ...
        stateObjects));
    a1 = allStateObjects(cellfun(@(item) ~isfinite(item.eta),allStateObjects));
    assert(numel(eta025) == 1 && numel(eta050) == 1, ...
        'Missing paired eta=.25/.50 branch object.');
    assert(numel(a1) == 1, 'Missing matched A1 branch object.');
    log025 = eta025{1}.ins.predictionInjectionLog(1);
    log050 = eta050{1}.ins.predictionInjectionLog(1);
    if log025.prediction_valid_used && log050.prediction_valid_used
        assert(sum(strcmp(log025.source_labels,'normal')) == 5 && ...
            sum(strcmp(log025.source_labels,'predicted_direct')) == 1 && ...
            sum(strcmp(log025.source_labels,'predicted_auxiliary')) == 2, ...
            'The eta branch does not use 5 normal + 1 direct + 2 auxiliary candidates.');
        assert(size(log025.auxiliary_upper_raw_offsets,1) == 2 && ...
            size(log050.auxiliary_upper_raw_offsets,1) == 2 && ...
            max(abs(log050.auxiliary_upper_raw_offsets(:) - ...
            2*log025.auxiliary_upper_raw_offsets(:))) < 1e-9, ...
            'Paired eta branches did not preserve their auxiliary base directions.');
    end
    a1Log = a1{1}.ins.predictionInjectionLog(1);
    if a1Log.prediction_valid_used
        assert(sum(strcmp(a1Log.source_labels,'normal')) == 7 && ...
            sum(strcmp(a1Log.source_labels,'predicted_direct')) == 1 && ...
            ~any(strcmp(a1Log.source_labels,'predicted_auxiliary')), ...
            'The A1 control does not use 7 normal + 1 direct candidates.');
        if log025.prediction_valid_used
            direct025 = find(strcmp(log025.source_labels,'predicted_direct'));
            directA1 = find(strcmp(a1Log.source_labels,'predicted_direct'));
            assert(isequal(log025.joint_after_true_evaluation(direct025,:), ...
                a1Log.joint_after_true_evaluation(directA1,:)), ...
                'The matched A1 direct point did not retain its paired true evaluation.');
        end
    end
end
% The detail log proves that the normal members are identical across eta in
% the first branch generation.  Direct prediction is also identical unless
% an explicit boundary repair is required, which is itself recorded.
details = experiment.generationDetails;
for stateId = unique(string(details.state_id))'
    rows = details(string(details.state_id) == stateId & ...
        details.generation_offset == 0 & strcmp(details.source,'normal'),:);
    rows = rows(startsWith(rows.eta_label,'eta_'),:);
    etaLabels = unique(rows.eta_label);
    if numel(etaLabels) < 4, continue; end
    reference = rows(strcmp(rows.eta_label,'eta_025'),:);
    for etaLabel = string(etaLabels)'
        candidate = rows(string(rows.eta_label) == etaLabel,:);
        assert(isequal(reference.candidate_index,candidate.candidate_index) && ...
            isequal(reference.joint,candidate.joint), ...
            'First-generation normal candidates differ across eta branches.');
    end
    directRows = details(string(details.state_id) == stateId & ...
        details.generation_offset == 0 & ...
        strcmp(details.source,'predicted_direct') & ...
        startsWith(details.eta_label,'eta_'),:);
    directReference = directRows(strcmp(directRows.eta_label,'eta_025'),:);
    for etaLabel = unique(string(directRows.eta_label))'
        candidate = directRows(string(directRows.eta_label) == etaLabel,:);
        assert(isequal(directReference.joint,candidate.joint), ...
            'First-generation direct prediction differs across eta branches.');
    end
end
mainFile = fullfile(outputRoot,'SMD1_run01_main.mat');
mainSaved = load(mainFile,'mainIns','mainRngAfter','BI');
assert(isequal(mainSaved.mainRngAfter,rng) && ...
    isequaln(mainSaved.mainIns.UFEs,ulFunctionEvaluations) && ...
    isequaln(mainSaved.mainIns.LFEs,llFunctionEvaluations), ...
    'A branch leaked RNG state or FE counters into the completed main run.');
% Capturing a snapshot is read-only.  A fresh ordinary F050 run with the
% same seed must reproduce the captured main run exactly on its core output.
outerRng = rng; outerUFE = ulFunctionEvaluations; outerLFE = llFunctionEvaluations;
cleanup = onCleanup(@() restoreOuterState(outerRng,outerUFE,outerLFE)); %#ok<NASGU>
rng(mainSaved.BI.predictionInjection.randomSeed,'twister');
referenceIns = BLCMAES(mainSaved.BI);
assert(isequaln([referenceIns.UF,referenceIns.LF,referenceIns.UFEs,referenceIns.LFEs], ...
    [mainSaved.mainIns.UF,mainSaved.mainIns.LF,mainSaved.mainIns.UFEs, ...
    mainSaved.mainIns.LFEs]) && ...
    isequaln(referenceIns.UX,mainSaved.mainIns.UX) && ...
    isequaln(referenceIns.LX,mainSaved.mainIns.LX) && ...
    isequaln(referenceIns.record,mainSaved.mainIns.record) && ...
    isequal(mainSaved.mainRngAfter,rng), ...
    'Read-only snapshot capture changed the normal BL-CMA-ES trajectory.');
report = struct('outputRoot',outputRoot,'selectedStates',height(selected), ...
    'branchRows',height(branches),'passed',true);
save(fullfile(outputRoot,'continuous_scale_branch_smoke_report.mat'),'report');
fprintf('Continuous-scale branch smoke test passed: %s\n',outputRoot);
end

function restoreOuterState(savedRng,savedUFE,savedLFE)
global ulFunctionEvaluations llFunctionEvaluations;
rng(savedRng);
ulFunctionEvaluations = savedUFE;
llFunctionEvaluations = savedLFE;
end
