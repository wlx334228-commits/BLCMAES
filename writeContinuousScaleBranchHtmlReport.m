function writeContinuousScaleBranchHtmlReport(fileName,config,branchSummary,analysisTable,figureFiles)
%WRITECONTINUOUSSCALEBRANCHHTMLREPORT Lightweight portable report wrapper.
file = fopen(fileName,'w');
assert(file >= 0,'Cannot write report %s.',fileName);
cleanup = onCleanup(@() fclose(file)); %#ok<NASGU>
fprintf(file,'<!doctype html><html><head><meta charset="utf-8">');
fprintf(file,'<title>Continuous scale branch diagnostic</title></head><body>');
fprintf(file,'<h1>Continuous scale branch diagnostic</h1>');
fprintf(file,'<p>H=%d, repeats=%d, eta=[0.25,0.50,0.75,1.00]. ', ...
    config.horizonGenerations,config.branchRepeats);
fprintf(file,['Auxiliary-only and whole-branch outcomes are deliberately ' ...
    'reported separately.</p>']);
fprintf(file,'<p>Branch rows: %d; analysis rows: %d.</p>', ...
    height(branchSummary),height(analysisTable));
fprintf(file,'<ul>');
for index = 1:numel(figureFiles)
    [~,name,extension] = fileparts(figureFiles{index});
    fprintf(file,'<li><img src="figures/%s%s" style="max-width:700px"></li>', ...
        name,extension);
end
fprintf(file,'</ul><p>See CSV files beside this report for all raw rows.</p>');
fprintf(file,['<p><a href="state_snapshots.csv">state snapshots</a> | ' ...
    '<a href="branch_generation_details.csv">generation details</a> | ' ...
    '<a href="auxiliary_candidate_details.csv">auxiliary candidates</a> | ' ...
    '<a href="branch_scale_summary.csv">branch summaries</a> | ' ...
    '<a href="branch_vs_A1_summary.csv">matched A1 comparison</a> | ' ...
    '<a href="state_scale_analysis.csv">state-scale analysis</a> | ' ...
    '<a href="state_scale_regression.csv">state-scale regression</a></p>']);
fprintf(file,'</body></html>');
end
