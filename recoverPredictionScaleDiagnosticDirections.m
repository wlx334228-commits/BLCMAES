function [z,info] = recoverPredictionScaleDiagnosticDirections(state)
%RECOVERPREDICTIONSCALEDIAGNOSTICDIRECTIONS Recover logged F050 directions.
% The F050 cma_gaussian policy stores each auxiliary joint point before its
% boundary repair.  Its upper offset is eta*sigma*z*sqrt(Cuu)', so this
% helper recovers the exact two upper standard-normal directions already
% used by the completed main run.  No random number is generated here.

upperDim = numel(state.x_pred);
assert(upperDim == 2, ...
    'This initial paired diagnostic is implemented for the two upper variables.');
assert(isfield(state,'auxiliary_raw_joint') && ...
    size(state.auxiliary_raw_joint,1) >= 2, ...
    'Logged raw auxiliary samples are required to recover paired directions.');
assert(isfinite(state.eta) && state.eta > 0 && isfinite(state.sigma) && ...
    state.sigma > 0, ...
    'The logged eta and sigma must be positive finite values.');

Cuu = (state.C(1:upperDim,1:upperDim) + ...
    state.C(1:upperDim,1:upperDim)')/2;
[B,eigenvalueMatrix] = eig(Cuu);
eigenvalues = real(diag(eigenvalueMatrix));
assert(all(isfinite(eigenvalues)) && all(eigenvalues > 0), ...
    'The logged upper covariance is not positive definite.');
factor = B*diag(sqrt(eigenvalues));
rawOffset = state.auxiliary_raw_joint(1:2,1:upperDim) - ...
    repmat(state.x_pred,2,1);
z = (rawOffset/(state.eta*state.sigma))/factor';
reconstructedOffset = state.eta*state.sigma*(z*factor');
residual = norm(reconstructedOffset-rawOffset,'fro');
relativeResidual = residual/max(1,norm(rawOffset,'fro'));
assert(relativeResidual <= 1e-10, ...
    'Recovered diagnostic directions do not reproduce logged raw offsets.');

info = struct('source','recovered_logged_f050_raw_offsets', ...
    'source_eta',state.eta,'upper_factor',factor, ...
    'Cuu_eigenvalues',eigenvalues,'raw_offset',rawOffset, ...
    'reconstruction_residual',residual, ...
    'reconstruction_relative_residual',relativeResidual);
end
