function report = testPredictionScaleAllEventDiagnostic(outputDir)
%TESTPREDICTIONSCALEALLEVENTDIAGNOSTIC Verify all-event post-run isolation.
% This smoke test runs one short F050 trajectory, copies every valid event,
% and then runs one private-stream multi-scale diagnostic. No diagnostic
% value may alter the completed main log, its counters, or global RNG state.

projectRoot = fileparts(mfilename('fullpath'));
addpath(projectRoot,fullfile(projectRoot,'BLEA_D'));
if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(projectRoot,'results_prediction_scale_all_events_tests', ...
        datestr(now,'yyyymmdd_HHMMSS'));
end
if exist(outputDir,'dir') ~= 7, mkdir(outputDir); end
BI = getBLOPinfo('SMD',1,5);
BIrun = BI;
BIrun.UmaxFEs = 256; BIrun.UmaxImprFEs = 1000;
BIrun.LmaxFEs = 50; BIrun.LmaxImprFEs = 20; BIrun.u_ftol = 0;
BIrun.enablePredictionCorrection = false;
BIrun.enableIndividualPredictionCorrection = false;
BIrun.predictionInjection = struct('mode','K3','predictionInjectCount',3, ...
    'candidatePolicy','direct_plus_auxiliary', ...
    'auxiliarySamplingDistribution','cma_gaussian', ...
    'auxiliarySamplingScale',0.5,'predictionModelType','quadratic', ...
    'logEnabled',true,'startGeneration',10,'historyGenerations',10, ...
    'sampleCount',40,'auxiliaryRandomSeed',741001,'randomSeed',741, ...
    'consistencyCheckEnabled',true);
rng(741,'twister');
ins = BLCMAES(BIrun);
logBeforeDiagnostic = ins.predictionInjectionLog;
rngAfterMain = rng;
[states,runInfo] = collectPredictionScaleAllEventStates( ...
    logBeforeDiagnostic,BIrun,ins.UFEs);
assert(~isempty(states),'The short smoke run did not reach a usable F050 event.');
validLog = logBeforeDiagnostic(arrayfun(@(entry) ...
    entry.prediction_valid_used && ...
    sum(strcmp(entry.source_labels,'predicted_auxiliary')) == 2, ...
    logBeforeDiagnostic));
assert(numel(states) == numel(validLog), ...
    'The all-event collector omitted or added a valid auxiliary event.');
assert(all([states.event_ordinal] == 1:numel(states)), ...
    'All-event ordinals must be consecutive within one main run.');
assert(runInfo.UFE_end == ins.UFEs && ...
    all([states.UFE_end] == ins.UFEs), ...
    'Post-run phase calculation did not use the actual terminal UFE.');
if runInfo.phase_assignment_available
    assert(abs(states(1).progress) < 1e-12 && ...
        all([states.progress] >= -1e-12) && all([states.progress] <= 1+1e-12), ...
        'All-event progress is not tied to the run-specific completed interval.');
end

eventRows = repmat(struct(),0,1);
candidateRows = repmat(struct(),0,1);
for index = 1:numel(states)
    [eventRow,rows] = buildPredictionScaleActualEventRows( ...
        states(index),1,1,741,false);
    if isempty(eventRows), eventRows = eventRow; else, eventRows(end+1,1) = eventRow; end %#ok<AGROW>
    if isempty(candidateRows), candidateRows = rows; else, candidateRows = [candidateRows;rows]; end %#ok<AGROW>
end
assert(numel(eventRows) == numel(states) && ...
    numel(candidateRows) == 2*numel(states), ...
    'Each valid F050 event must create one event row and two actual auxiliary rows.');
assert(isequal(rngAfterMain,rng), ...
    'Read-only all-event extraction changed MATLAB global RNG.');
[recoveredDirections,directionInfo] = ...
    recoverPredictionScaleDiagnosticDirections(states(1));
reconstructed = generatePredictionScaleDiagnosticCandidates(states(1),0.5, ...
    recoveredDirections);
assert(all(arrayfun(@(index) norm(reconstructed(index).raw_upper- ...
    states(1).auxiliary_raw_joint(index,1:BIrun.u_dim)) <= ...
    1e-10*max(1,norm(states(1).auxiliary_raw_joint(index,1:BIrun.u_dim))), ...
    1:2)), ...
    'Recovered eta=0.5 directions do not reproduce logged main candidates.');
assert(strcmp(directionInfo.source,'recovered_logged_f050_raw_offsets'), ...
    'The paired diagnostic must use logged, not newly sampled, directions.');
allChoice = selectPredictionScaleDiagnosticEvents(states,'all',1,2);
assert(all([allChoice.selected]), ...
    'All-state diagnostic selection omitted a valid event.');
uniformChoice = selectPredictionScaleDiagnosticEvents(states, ...
    'uniform_per_phase',1,2);
for stage = {'early','middle','late'}
    stateCount = sum(strcmp({states.stage},stage{1}));
    selectedStateCount = sum([uniformChoice.selected] & ...
        strcmp({states.stage},stage{1}));
    assert(selectedStateCount == min(2,stateCount), ...
        'Uniform phase selection did not choose the expected number of states.');
end
global ulFunctionEvaluations llFunctionEvaluations;
UFEafterMain = ulFunctionEvaluations; LFEafterMain = llFunctionEvaluations;
[diagnosticRows,totals] = evaluatePredictionScaleDiagnosticState( ...
    states(1),BIrun,1,1,741,[0.25 0.5 0.75 1.0]);
assert(numel(diagnosticRows) == 8 && totals.candidate_count == 8, ...
    'One diagnosed event must create four eta values times two candidates.');
eta05Rows = diagnosticRows(abs([diagnosticRows.eta]-0.5) < 1e-12);
assert(all([eta05Rows.raw_upper_matches_logged_main]), ...
    'Eta=0.5 diagnostic rows do not match logged raw upper candidates.');
assert(isequal(rngAfterMain,rng) && ...
    ulFunctionEvaluations == UFEafterMain && llFunctionEvaluations == LFEafterMain, ...
    'The offline multi-scale diagnostic leaked into main RNG or counters.');
assert(isequaln(ins.predictionInjectionLog,logBeforeDiagnostic), ...
    'All-event diagnostics changed the completed main trajectory.');
for candidateIndex = 1:2
    subset = diagnosticRows([diagnosticRows.candidate_index] == candidateIndex);
    assert(numel(subset) == 4 && numel(unique([subset.lower_random_seed])) == 1, ...
        'Each eta must share the same lower random seed for a fixed candidate index.');
end
report = struct('passed',true,'main_UFE',ins.UFEs,'main_LFE',ins.LFEs, ...
    'valid_event_count',numel(states),'runInfo',runInfo, ...
    'states',{states},'actual_event_rows',{eventRows}, ...
    'actual_candidate_rows',{candidateRows},'diagnostic_rows',diagnosticRows, ...
    'diagnostic_totals',totals);
save(fullfile(outputDir,'prediction_scale_all_event_test_report.mat'), ...
    'report','-v7');
disp(report);
end
